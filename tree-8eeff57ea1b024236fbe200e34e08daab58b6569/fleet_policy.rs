/// Normalized live group state read back from GitHub.
#[derive(Debug, Clone, PartialEq, Eq)]
#[allow(dead_code)]
pub struct ObservedGroup {
    pub name: String,
    pub visibility: String,
    pub allows_public_repositories: bool,
    pub restricted_to_workflows: bool,
    pub selected_repositories: BTreeSet<String>,
    /// Raw `owner/repo/.github/workflows/file.yml@ref` strings as reported.
    pub selected_workflows: BTreeSet<String>,
}

/// Normalize raw readback workflow strings into typed identities, rejecting
/// anything the policy contract forbids.
#[allow(dead_code)]
pub fn normalize_observed_workflows(raw: &BTreeSet<String>) -> Result<BTreeSet<WorkflowIdentity>> {
    let mut out = BTreeSet::new();
    for value in raw {
        let (path, git_ref) = value.rsplit_once('@').ok_or_else(|| {
            anyhow::anyhow!("field 'observed_workflows': value '{value}' lacks '@ref' suffix")
        })?;
        ensure_no_wildcard("observed_workflows", value)?;
        ensure_qualified_ref("observed_workflows", value, git_ref)?;
        split_identity_path("observed_workflows", value, path)?;
        out.insert(WorkflowIdentity {
            path: path.to_owned(),
            git_ref: git_ref.to_owned(),
        });
    }
    Ok(out)
}

/// Machine-readable reason carried by every repository removal (observed
/// selection entry absent from the desired closure) in the semantic-diff
/// surface; operator review must always see why a removal happened.
#[allow(dead_code)]
pub const REPOSITORY_REMOVAL_REASON: &str = "no direct workflow closure in release-ref ledger";

/// Semantic equality between desired policy and observed readback; every
/// mismatch becomes one deterministic line.
#[allow(dead_code)]
pub fn semantic_diff(
    desired: &OrgPolicy,
    organization: &str,
    observed: &ObservedGroup,
) -> Result<Vec<String>> {
    validate_policy(desired)?;
    let mut diffs = Vec::new();
    if organization != desired.organization {
        diffs.push(format!(
            "organization: requested '{organization}' but policy targets '{}'",
            desired.organization
        ));
        return Ok(diffs);
    }
    if observed.name != desired.group_name {
        diffs.push(format!(
            "group_name: want '{}' got '{}'",
            desired.group_name, observed.name
        ));
    }
    if observed.visibility != desired.visibility.to_string() {
        diffs.push(format!(
            "visibility: want '{}' got '{}'",
            desired.visibility, observed.visibility
        ));
    }
    if observed.allows_public_repositories != desired.allows_public_repositories {
        diffs.push(format!(
            "allows_public_repositories: want '{}' got '{}'",
            desired.allows_public_repositories, observed.allows_public_repositories
        ));
    }
    if observed.restricted_to_workflows != desired.restricted_to_workflows {
        diffs.push(format!(
            "restricted_to_workflows: want '{}' got '{}'",
            desired.restricted_to_workflows, observed.restricted_to_workflows
        ));
    }
    let want_repos: BTreeSet<_> = desired.selected_repositories.iter().collect();
    let got_repos: BTreeSet<_> = observed.selected_repositories.iter().collect();
    for missing in want_repos.difference(&got_repos) {
        diffs.push(format!("selected_repositories: missing '{missing}'"));
    }
    for extra in got_repos.difference(&want_repos) {
        diffs.push(format!(
            "selected_repositories: unexpected '{extra}' reason='{REPOSITORY_REMOVAL_REASON}'"
        ));
    }
    let want_workflows = normalize_observed_workflows(&BTreeSet::from_iter(
        desired
            .selected_workflows
            .iter()
            .map(|identity| identity.to_selected_string()),
    ))?;
    let got_workflows = normalize_observed_workflows(&observed.selected_workflows)?;
    for missing in want_workflows.difference(&got_workflows) {
        diffs.push(format!("selected_workflows: missing '{missing}'"));
    }
    for extra in got_workflows.difference(&want_workflows) {
        diffs.push(format!("selected_workflows: unexpected '{extra}'"));
    }
    Ok(diffs)
}

