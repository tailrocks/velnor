/// Build the deterministic per-organization desired policies from a validated
/// ledger.
///
/// Review-state mechanism (exact behavior that produced the committed
/// 2026-08-24 snapshots): only currently admitted (`approved` with no expiry,
/// or an expiry today/future) entries flow into their organization's policy.
/// Entries are grouped by owner; repositories and workflow identities are
/// sorted and de-duplicated by [`OrgPolicy::normalized`] before canonical
/// serialization.
pub fn generate_policies_from_ledger(ledger: &ReleaseRefLedger) -> Result<Vec<OrgPolicy>> {
    let mut by_org: BTreeMap<&str, Vec<&ReleaseRefEntry>> = BTreeMap::new();
    for entry in &ledger.entries {
        if !approved_entry_is_currently_admitted(entry)? {
            continue;
        }
        by_org.entry(entry.owner.as_str()).or_default().push(entry);
    }
    let mut policies = Vec::new();
    for (organization, entries) in &by_org {
        let mut policy = OrgPolicy::new((*organization).to_owned());
        let mut repositories = BTreeSet::new();
        let mut workflows = Vec::new();
        for entry in entries {
            repositories.insert(format!("{}/{}", entry.owner, entry.repository));
            workflows.push(WorkflowIdentity {
                path: format!(
                    "{}/{}/{}",
                    entry.owner, entry.repository, entry.workflow_path
                ),
                git_ref: entry.git_ref.clone(),
            });
        }
        policy.selected_repositories = repositories.into_iter().collect();
        policy.selected_workflows = workflows;
        let policy = policy.normalized();
        // Canonical JSON validates; a generated policy can never be invalid.
        policy.canonical_json()?;
        policies.push(policy);
    }
    if policies.is_empty() {
        bail!("field 'entries': value must be non-empty");
    }
    Ok(policies)
}

/// Mutation [`fleet_generate`] performs for one organization's policy file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum PolicyFileAction {
    /// On-disk bytes differ from (or no file carries) the generated bytes.
    Written,
    /// On-disk bytes already equal the generated bytes; leave mtime alone so
    /// drift stays observable through the filesystem.
    Skipped,
    /// `<org>-desired-policy.json` whose org is absent from the ledger.
    Removed,
}

/// One planned per-org change: the action plus the canonical bytes a write
/// would persist (`None` for removals).
type PlannedPolicyChange = (PolicyFileAction, Option<Vec<u8>>);

#[cfg(unix)]
type PolicyFileIdentity = (u64, u64, u64);

#[cfg(unix)]
#[derive(Debug)]
struct ExistingPolicyFile {
    bytes: Vec<u8>,
    identity: PolicyFileIdentity,
}

#[cfg(unix)]
impl AsRef<[u8]> for ExistingPolicyFile {
    fn as_ref(&self) -> &[u8] {
        &self.bytes
    }
}

#[cfg(unix)]
#[derive(Debug, Clone, Copy)]
enum PolicyFileExpectation {
    Absent,
    Existing(PolicyFileIdentity),
}

#[cfg(unix)]
impl PolicyFileExpectation {
    fn identity(self) -> Option<PolicyFileIdentity> {
        match self {
            Self::Absent => None,
            Self::Existing(identity) => Some(identity),
        }
    }
}

/// Pure decision core of [`fleet_generate`]: map every generated policy and
/// every existing `<org>-desired-policy.json` file (keyed by its org stem) to
/// a per-org action. `existing` must contain only entries whose filename
/// strictly matches `<org>-desired-policy.json`; callers never pass anything
/// else, so this function cannot decide to touch unrelated files.
fn plan_policy_actions<T: AsRef<[u8]>>(
    policies: &[OrgPolicy],
    existing: &BTreeMap<String, T>,
) -> Result<BTreeMap<String, PlannedPolicyChange>> {
    // Fail closed on ASCII-case-insensitive filename collisions (review G2,
    // residual H1/H2): on case-insensitive filesystems (macOS APFS, Windows
    // NTFS) two names differing only by ASCII case address one physical file.
    // An intra-ledger pair would classify both spellings as Written and clobber
    // one policy with exit 0; a stale-file pair would classify both as Removed
    // so the second unlink fails ENOENT after the writes already applied —
    // partial mutation either way. Bail naming both original spellings BEFORE
    // any write/remove is planned. Unreadable on-disk state aborts upstream
    // for the same reason; refusing the run over partial mutation is
    // intentional (review G4).
    let mut planned_by_lowercase: BTreeMap<String, &str> = BTreeMap::new();
    for policy in policies {
        match planned_by_lowercase.entry(policy.organization.to_ascii_lowercase()) {
            Entry::Occupied(slot) => {
                let first = *slot.get();
                if first != policy.organization.as_str() {
                    bail!(
                        "fleet policy generation: case-insensitive organization-name collision \
                         within the release-ref ledger between '{first}' and '{}'; both map to \
                         '<org>-desired-policy.json' on a case-insensitive filesystem. \
                         Deduplicate the ledger organizations before generating.",
                        policy.organization
                    );
                }
            }
            Entry::Vacant(slot) => {
                slot.insert(&policy.organization);
            }
        }
    }
    for stem in existing.keys() {
        let lowercase_stem = stem.to_ascii_lowercase();
        if let Some(org) = planned_by_lowercase.get(lowercase_stem.as_str())
            && *org != stem.as_str()
        {
            bail!(
                "fleet policy generation: case-insensitive filename collision between \
                 ledger organization '{org}' and existing policy stem '{stem}'; both map \
                 to '{stem}-desired-policy.json' on a case-insensitive filesystem. Rename \
                 or remove the stale file before generating."
            );
        }
    }
    // Stale-file pair check (residual H2): plan_policy_actions performs no
    // filesystem mutation itself, and fleet_generate only writes/unlinks after
    // this function returns Ok, so bailing here is strictly pre-mutation even
    // when both colliding stems can only coexist on a case-sensitive volume.
    let mut existing_by_lowercase: BTreeMap<String, &str> = BTreeMap::new();
    for stem in existing.keys() {
        match existing_by_lowercase.entry(stem.to_ascii_lowercase()) {
            Entry::Occupied(slot) => {
                let first = *slot.get();
                if first != stem.as_str() {
                    bail!(
                        "fleet policy generation: case-insensitive filename collision between \
                         stale policy files '{first}' and '{stem}' (both '-desired-policy.json'); \
                         they map to one physical file on a case-insensitive filesystem, so their \
                         removals could partially apply. Rename or remove one of them before \
                         generating."
                    );
                }
            }
            Entry::Vacant(slot) => {
                slot.insert(stem);
            }
        }
    }

    let mut plan = BTreeMap::new();
    let mut ledger_orgs = BTreeSet::new();
    for policy in policies {
        let bytes = format!("{}\n", policy.canonical_json()?);
        if bytes.len() > MAX_POLICY_FILE_BYTES {
            bail!(
                "generated fleet policy for '{}' exceeds the {} MiB file limit",
                policy.organization,
                MAX_POLICY_FILE_BYTES / (1024 * 1024)
            );
        }
        let action = if existing
            .get(&policy.organization)
            .is_some_and(|on_disk| on_disk.as_ref() == bytes.as_bytes())
        {
            PolicyFileAction::Skipped
        } else {
            PolicyFileAction::Written
        };
        ledger_orgs.insert(policy.organization.clone());
        plan.insert(
            policy.organization.clone(),
            (action, Some(bytes.into_bytes())),
        );
    }
    for org in existing.keys() {
        if !ledger_orgs.contains(org) {
            plan.insert(org.clone(), (PolicyFileAction::Removed, None));
        }
    }
    Ok(plan)
}

/// Scan `out_dir` for files named exactly `<org>-desired-policy.json` and
/// return stem → current bytes. Anything else in the directory (other names,
/// subdirectories) is ignored entirely and never becomes a removal candidate.
///
/// Fail-closed symlink rule (review G1): any entry whose name matches
/// `<org>-desired-policy.json` but is a symlink — dangling or not — is a hard
/// error naming the path. Detection uses [`Path::symlink_metadata`], which
/// never follows links, and the scan never unlinks or writes through them, so
/// neither the write nor the removal classification can reach a target
/// outside `out_dir`. A matched entry that cannot be inspected or read also
/// aborts generation instead of being skipped; that fail-closed choice is
/// intentional (review G4): partial mutation is worse than a refused run.
#[cfg(not(unix))]
fn read_existing_policy_files(out_dir: &Path) -> Result<BTreeMap<String, Vec<u8>>> {
    let mut existing = BTreeMap::new();
    for entry in fs::read_dir(out_dir).with_context(|| format!("reading {}", out_dir.display()))? {
        let path = entry
            .with_context(|| format!("reading entry under {}", out_dir.display()))?
            .path();
        let name = path
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or_default();
        let Some(stem) = name.strip_suffix("-desired-policy.json") else {
            continue;
        };
        let is_symlink = path
            .symlink_metadata()
            .with_context(|| format!("inspecting {}", path.display()))?
            .file_type()
            .is_symlink();
        if is_symlink {
            bail!(
                "refusing symlinked fleet policy entry {}; expected a regular file inside {}",
                path.display(),
                out_dir.display()
            );
        }
        if stem.is_empty() || !path.is_file() {
            continue;
        }
        let bytes = fs::read(&path).with_context(|| format!("reading {}", path.display()))?;
        existing.insert(stem.to_owned(), bytes);
    }
    Ok(existing)
}

/// Write one generated policy through a directory descriptor.
///
/// The output directory is opened with `O_NOFOLLOW`, then the temporary file
/// and final rename are both relative to that descriptor. This prevents a
/// parent-directory replacement from redirecting the write, avoids mutating a
/// hardlink target, and makes a partial write invisible. Existing regular
/// file modes are preserved; symlinks and non-regular final members fail
/// closed.
#[cfg(unix)]
struct PolicyDirectory {
    path: PathBuf,
    file: File,
}

#[cfg(unix)]
impl PolicyDirectory {
    fn open_or_create(path: &Path) -> Result<Self> {
        let directory_fd = open_policy_directory_fd(path, true)?;
        let file = unsafe { File::from_raw_fd(directory_fd) };
        lock_policy_directory(&file, path)?;
        Ok(Self {
            path: path.to_owned(),
            file,
        })
    }
}

#[cfg(unix)]
fn lock_policy_directory(file: &File, path: &Path) -> Result<()> {
    loop {
        let result = unsafe { libc::flock(file.as_raw_fd(), libc::LOCK_EX) };
        if result == 0 {
            return Ok(());
        }
        let error = io::Error::last_os_error();
        if error.kind() == io::ErrorKind::Interrupted {
            continue;
        }
        return Err(error).with_context(|| {
            format!(
                "locking fleet policy directory {} for generation",
                path.display()
            )
        });
    }
}

#[cfg(unix)]
fn open_policy_directory_fd(path: &Path, create: bool) -> Result<RawFd> {
    let pending = policy_directory_components(path)?;

    // Keep stable root and working-directory descriptors. Every component is
    // opened relative to a descriptor; aliases are expanded only from a
    // target captured by readlinkat, never by rebuilding a canonical path.
    let root_c = CString::new("/").expect("static path has no NUL");
    let root_fd = unsafe {
        libc::open(
            root_c.as_ptr(),
            libc::O_RDONLY | libc::O_DIRECTORY | libc::O_CLOEXEC | libc::O_NOFOLLOW,
        )
    };
    if root_fd < 0 {
        return Err(io::Error::last_os_error()).with_context(|| {
            format!("opening root for fleet policy directory {}", path.display())
        });
    }
    let current = if path.is_absolute() {
        unsafe { libc::dup(root_fd) }
    } else {
        let start_c = CString::new(".").expect("static path has no NUL");
        unsafe {
            libc::open(
                start_c.as_ptr(),
                libc::O_RDONLY | libc::O_DIRECTORY | libc::O_CLOEXEC | libc::O_NOFOLLOW,
            )
        }
    };
    if current < 0 {
        let error = io::Error::last_os_error();
        unsafe { libc::close(root_fd) };
        return Err(error).with_context(|| {
            format!(
                "opening start for fleet policy directory {}",
                path.display()
            )
        });
    }

    let result = open_policy_directory_components(current, root_fd, pending, create, path);
    let root_close = unsafe { libc::close(root_fd) };
    match result {
        Ok(directory_fd) if root_close == 0 => Ok(directory_fd),
        Ok(directory_fd) => {
            let error = io::Error::last_os_error();
            unsafe { libc::close(directory_fd) };
            Err(error).with_context(|| {
                format!("closing root for fleet policy directory {}", path.display())
            })
        }
        Err(error) => Err(error),
    }
}

#[cfg(unix)]
fn policy_directory_components(path: &Path) -> Result<VecDeque<OsString>> {
    let mut components = VecDeque::new();
    for component in path.components() {
        match component {
            Component::Normal(component) => components.push_back(component.to_os_string()),
            Component::RootDir | Component::CurDir => {}
            Component::ParentDir => {
                bail!(
                    "refusing parent component in fleet policy directory {}",
                    path.display()
                );
            }
            Component::Prefix(_) => {
                bail!(
                    "unsupported path prefix in fleet policy directory {}",
                    path.display()
                );
            }
        }
    }
    Ok(components)
}

#[cfg(unix)]
fn open_policy_directory_component(
    parent_fd: RawFd,
    component: &OsStr,
    create: bool,
) -> io::Result<RawFd> {
    let component_c = CString::new(component.as_bytes()).map_err(|_| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            "fleet policy output directory contains NUL",
        )
    })?;
    let flags = libc::O_RDONLY | libc::O_DIRECTORY | libc::O_CLOEXEC | libc::O_NOFOLLOW;
    let mut next = unsafe { libc::openat(parent_fd, component_c.as_ptr(), flags) };
    if next >= 0 {
        return Ok(next);
    }
    if create && io::Error::last_os_error().raw_os_error() == Some(libc::ENOENT) {
        let mkdir_result =
            unsafe { libc::mkdirat(parent_fd, component_c.as_ptr(), 0o755 as libc::mode_t) };
        if mkdir_result < 0 && io::Error::last_os_error().raw_os_error() != Some(libc::EEXIST) {
            return Err(io::Error::last_os_error());
        }
        next = unsafe { libc::openat(parent_fd, component_c.as_ptr(), flags) };
        if next >= 0 {
            return Ok(next);
        }
    }
    Err(io::Error::last_os_error())
}

#[cfg(unix)]
fn read_link_at(directory: RawFd, name: &OsStr) -> io::Result<OsString> {
    // Capture once. A size-probing loop could observe a replacement on its
    // second read and make the walk follow a different alias than the one
    // that produced ELOOP.
    const MAX_TARGET_BYTES: usize = 64 * 1024;
    let name_c = CString::new(name.as_bytes()).map_err(|_| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            "fleet policy output directory contains NUL",
        )
    })?;
    let before = policy_symlink_identity(directory, &name_c)?;
    let mut buffer = vec![0_u8; MAX_TARGET_BYTES];
    let length = unsafe {
        libc::readlinkat(
            directory,
            name_c.as_ptr(),
            buffer.as_mut_ptr().cast::<libc::c_char>(),
            buffer.len(),
        )
    };
    if length < 0 {
        return Err(io::Error::last_os_error());
    }
    let length = length as usize;
    if length == buffer.len() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "directory symlink target exceeds 64 KiB",
        ));
    }
    let after = policy_symlink_identity(directory, &name_c)?;
    if before != after {
        return Err(io::Error::from_raw_os_error(libc::EAGAIN));
    }
    buffer.truncate(length);
    if buffer.is_empty() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "directory symlink target is empty",
        ));
    }
    Ok(OsString::from_vec(buffer))
}

#[cfg(unix)]
fn policy_symlink_identity(directory: RawFd, name: &CString) -> io::Result<(u64, u64, u64)> {
    let mut stat = std::mem::MaybeUninit::<libc::stat>::uninit();
    let result = unsafe {
        libc::fstatat(
            directory,
            name.as_ptr(),
            stat.as_mut_ptr(),
            libc::AT_SYMLINK_NOFOLLOW,
        )
    };
    if result < 0 {
        return Err(io::Error::last_os_error());
    }
    let stat = unsafe { stat.assume_init() };
    if stat.st_mode & libc::S_IFMT != libc::S_IFLNK {
        return Err(io::Error::from_raw_os_error(libc::EINVAL));
    }
    Ok((stat.st_dev as _, stat.st_ino, stat.st_mode as u64))
}

#[cfg(unix)]
fn open_policy_directory_components(
    mut current: RawFd,
    root_fd: RawFd,
    mut pending: VecDeque<OsString>,
    create: bool,
    path: &Path,
) -> Result<RawFd> {
    const MAX_SYMLINK_HOPS: usize = 40;
    let mut symlink_hops = 0;

    while let Some(component) = pending.pop_front() {
        let is_final = pending.is_empty();
        let next = match open_policy_directory_component(current, &component, create) {
            Ok(next) => next,
            Err(error)
                if !is_final
                    && matches!(
                        error.raw_os_error(),
                        Some(libc::ELOOP) | Some(libc::ENOTDIR)
                    ) =>
            {
                let component_c = match CString::new(component.as_bytes()) {
                    Ok(component_c) => component_c,
                    Err(error) => {
                        unsafe { libc::close(current) };
                        return Err(anyhow::Error::new(error));
                    }
                };
                let is_symlink = match policy_symlink_identity(current, &component_c) {
                    Ok(_) => true,
                    Err(identity_error)
                        if matches!(
                            identity_error.raw_os_error(),
                            Some(libc::EINVAL) | Some(libc::ENOENT)
                        ) =>
                    {
                        false
                    }
                    Err(identity_error) => {
                        unsafe { libc::close(current) };
                        return Err(identity_error).with_context(|| {
                            format!(
                                "inspecting symlinked fleet policy directory component {}/{}",
                                path.display(),
                                component.to_string_lossy()
                            )
                        });
                    }
                };
                if !is_symlink {
                    unsafe { libc::close(current) };
                    return Err(error).with_context(|| {
                        format!(
                            "opening component {} in fleet policy directory {}",
                            component.to_string_lossy(),
                            path.display()
                        )
                    });
                }
                if symlink_hops == MAX_SYMLINK_HOPS {
                    unsafe { libc::close(current) };
                    return Err(io::Error::from_raw_os_error(libc::ELOOP)).with_context(|| {
                        format!("resolving fleet policy directory {}", path.display())
                    });
                }
                let target = match read_link_at(current, &component) {
                    Ok(target) => target,
                    Err(error) => {
                        unsafe { libc::close(current) };
                        return Err(error).with_context(|| {
                            format!(
                                "capturing symlinked fleet policy directory component {}/{}",
                                path.display(),
                                component.to_string_lossy()
                            )
                        });
                    }
                };
                let target_path = Path::new(&target);
                let mut target_components = match policy_directory_components(target_path) {
                    Ok(components) => components,
                    Err(error) => {
                        unsafe { libc::close(current) };
                        return Err(error);
                    }
                };
                let replacement_base = unsafe {
                    libc::dup(if target_path.is_absolute() {
                        root_fd
                    } else {
                        current
                    })
                };
                if replacement_base < 0 {
                    let error = io::Error::last_os_error();
                    unsafe { libc::close(current) };
                    return Err(error).with_context(|| {
                        format!(
                            "duplicating symlink base for fleet policy directory {}",
                            path.display()
                        )
                    });
                }
                unsafe { libc::close(current) };
                target_components.append(&mut pending);
                pending = target_components;
                current = replacement_base;
                symlink_hops += 1;
                continue;
            }
            Err(error) => {
                unsafe { libc::close(current) };
                return Err(error).with_context(|| {
                    format!(
                        "opening component {} in fleet policy directory {}",
                        component.to_string_lossy(),
                        path.display()
                    )
                });
            }
        };
        unsafe { libc::close(current) };
        current = next;
    }
    Ok(current)
}

#[cfg(unix)]
fn clear_errno() {
    #[cfg(any(
        target_os = "macos",
        target_os = "ios",
        target_os = "tvos",
        target_os = "watchos",
        target_os = "freebsd",
        target_os = "openbsd",
        target_os = "netbsd"
    ))]
    {
        // SAFETY: libc returns the current thread's valid errno slot, which
        // this assignment updates without exposing the raw pointer.
        unsafe {
            *libc::__error() = 0;
        }
    }
    #[cfg(not(any(
        target_os = "macos",
        target_os = "ios",
        target_os = "tvos",
        target_os = "watchos",
        target_os = "freebsd",
        target_os = "openbsd",
        target_os = "netbsd"
    )))]
    {
        // SAFETY: libc returns the current thread's valid errno slot, which
        // this assignment updates without exposing the raw pointer.
        unsafe {
            *libc::__errno_location() = 0;
        }
    }
}

