pub fn validate_policy(policy: &OrgPolicy) -> Result<()> {
    if policy.schema_version != RELEASE_REF_LEDGER_SCHEMA_VERSION {
        bail!(
            "field 'schema_version': value {} is unsupported; expected {}",
            policy.schema_version,
            RELEASE_REF_LEDGER_SCHEMA_VERSION
        );
    }
    if policy.contract_version != POLICY_CONTRACT_VERSION {
        bail!(
            "field 'contract_version': value '{}' is unsupported; expected '{}'",
            policy.contract_version,
            POLICY_CONTRACT_VERSION
        );
    }
    if policy.generator_version != GENERATOR_VERSION {
        bail!(
            "field 'generator_version': value '{}' is unsupported; expected '{}'",
            policy.generator_version,
            GENERATOR_VERSION
        );
    }
    let organization = policy.organization.as_bytes();
    let valid_organization = !organization.is_empty()
        && organization.len() <= 39
        && matches!(organization.first(), Some(byte) if byte.is_ascii_alphanumeric())
        && matches!(organization.last(), Some(byte) if byte.is_ascii_alphanumeric())
        && organization
            .iter()
            .all(|byte| byte.is_ascii_alphanumeric() || *byte == b'-')
        && !organization
            .windows(2)
            .any(|window| window[0] == b'-' && window[1] == b'-');
    if !valid_organization {
        bail!(
            "field 'organization': value '{}' must be a single safe GitHub login segment",
            policy.organization
        );
    }
    if policy.group_name != REQUIRED_GROUP_NAME {
        bail!(
            "field 'group_name': value '{}' must equal required non-default group '{}'",
            policy.group_name,
            REQUIRED_GROUP_NAME
        );
    }
    if !policy
        .runner_labels
        .iter()
        .any(|label| label == REQUIRED_RUNNER_LABEL)
    {
        bail!(
            "field 'runner_labels': values {:?} must include required label '{}'",
            policy.runner_labels,
            REQUIRED_RUNNER_LABEL
        );
    }
    if policy.runner_labels != normalize_strings(policy.runner_labels.clone()) {
        bail!(
            "field 'runner_labels': values {:?} must be sorted and duplicate-free",
            policy.runner_labels
        );
    }
    for label in &policy.runner_labels {
        if label.chars().any(|c| WILDCARDS.contains(&c)) {
            bail!("field 'runner_labels': value '{label}' must not contain wildcards");
        }
    }
    if !matches!(policy.visibility, GroupVisibility::Selected) {
        bail!(
            "field 'visibility': value '{}' must be 'selected'",
            policy.visibility
        );
    }
    if !policy.allows_public_repositories {
        bail!("field 'allows_public_repositories': value false must be true");
    }
    if !policy.restricted_to_workflows {
        bail!("field 'restricted_to_workflows': value false must be true");
    }
    if policy.selected_repositories.is_empty() {
        bail!("field 'selected_repositories': value must be non-empty");
    }
    if policy.selected_workflows.is_empty() {
        bail!("field 'selected_workflows': value must be non-empty");
    }
    if policy.selected_repositories != normalize_strings(policy.selected_repositories.clone()) {
        bail!(
            "field 'selected_repositories': values {:?} must be sorted and duplicate-free",
            policy.selected_repositories
        );
    }
    for repository in &policy.selected_repositories {
        ensure_slug("selected_repositories", repository)?;
        let repository_owner = repository.split('/').next().unwrap_or_default();
        if repository_owner != policy.organization {
            bail!(
                "field 'selected_repositories': value '{repository}' has owner '{repository_owner}', expected organization '{}'",
                policy.organization
            );
        }
    }

    let mut seen_paths: BTreeMap<String, String> = BTreeMap::new();
    let mut seen_values: BTreeSet<String> = BTreeSet::new();
    let mut covered_repos: BTreeSet<String> = BTreeSet::new();
    for identity in &policy.selected_workflows {
        let value = identity.to_selected_string();
        if !seen_values.insert(value.clone()) {
            bail!("field 'selected_workflows': duplicate entry '{value}'");
        }
        ensure_no_wildcard("selected_workflows", &value)?;
        ensure_qualified_ref("selected_workflows", &value, &identity.git_ref)?;
        let (owner_repo, _) = split_identity_path("selected_workflows", &value, &identity.path)?;
        let workflow_owner = owner_repo.split('/').next().unwrap_or_default();
        if workflow_owner != policy.organization {
            bail!(
                "field 'selected_workflows': entry '{value}' has owner '{workflow_owner}', expected organization '{}'",
                policy.organization
            );
        }
        if !policy.selected_repositories.contains(&owner_repo) {
            bail!(
                "field 'selected_workflows': entry '{value}' references repository '{owner_repo}' absent from field 'selected_repositories'"
            );
        }
        if let Some(prior_ref) = seen_paths.get(&identity.path)
            && prior_ref != &identity.git_ref
        {
            bail!(
                "field 'selected_workflows': contradictory entries for workflow path '{}': refs '{prior_ref}' and '{}'",
                identity.path,
                identity.git_ref
            );
        }
        seen_paths.insert(identity.path.clone(), identity.git_ref.clone());
        covered_repos.insert(owner_repo);
    }
    if policy.selected_workflows != {
        let mut workflows = policy.selected_workflows.clone();
        workflows.sort();
        workflows
    } {
        bail!(
            "field 'selected_workflows': values must be sorted and duplicate-free; got {:?}",
            policy
                .selected_workflows
                .iter()
                .map(WorkflowIdentity::to_selected_string)
                .collect::<Vec<_>>()
        );
    }
    for repository in &policy.selected_repositories {
        if !covered_repos.contains(repository) {
            bail!(
                "field 'selected_repositories': value '{repository}' has no 'selected_workflows' entry (extra selection)"
            );
        }
    }
    Ok(())
}

fn ensure_slug(field: &str, value: &str) -> Result<()> {
    let invalid = |message: String| anyhow::anyhow!("field '{field}': {message}");
    let mut parts = value.splitn(2, '/');
    let (owner, repo) = match (parts.next(), parts.next()) {
        (Some(owner), Some(repo)) if !repo.contains('/') => (owner, repo),
        _ => return Err(invalid(format!("value '{value}' must be 'owner/repo'"))),
    };
    let slug_ok = |part: &str| {
        !part.is_empty()
            && part
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '.' | '_'))
    };
    if !slug_ok(owner) || !slug_ok(repo) {
        return Err(invalid(format!(
            "value '{value}' is not a valid owner/repo slug"
        )));
    }
    Ok(())
}

/// Split `owner/repo/.github/workflows/file.(yml|yaml)` into `(owner/repo, file)`.
fn split_identity_path(field: &str, value: &str, path: &str) -> Result<(String, String)> {
    let segments: Vec<&str> = path.split('/').collect();
    let shape = "owner/repo/.github/workflows/file.yml";
    if segments.len() < 5 {
        return Err(anyhow::anyhow!(
            "field '{field}': entry '{value}' has path '{path}'; expected '{shape}'"
        ));
    }
    let owner = segments[0];
    let repo = segments[1];
    if segments[2] != ".github" || segments[3] != "workflows" {
        return Err(anyhow::anyhow!(
            "field '{field}': entry '{value}' has path '{path}'; expected '{shape}'"
        ));
    }
    let file = segments[4..].join("/");
    if !file.ends_with(".yml") && !file.ends_with(".yaml") {
        return Err(anyhow::anyhow!(
            "field '{field}': entry '{value}' workflow file '{file}' must end in .yml or .yaml"
        ));
    }
    Ok((format!("{owner}/{repo}"), file))
}

fn ensure_no_wildcard(field: &str, value: &str) -> Result<()> {
    if value.chars().any(|c| WILDCARDS.contains(&c)) {
        bail!("field '{field}': value '{value}' must not contain wildcards");
    }
    Ok(())
}

/// Validate a `YYYY-MM-DD` calendar date (real month/day bounds).
fn ensure_calendar_date(value: &str) -> std::result::Result<(), String> {
    parse_calendar_date(value).map(|_| ())
}

fn parse_calendar_date(value: &str) -> std::result::Result<Date, String> {
    let shape = "must be a real YYYY-MM-DD date";
    let mut parts = value.splitn(3, '-');
    let (year, month, day) = match (parts.next(), parts.next(), parts.next()) {
        (Some(y), Some(m), Some(d)) if y.len() == 4 && m.len() == 2 && d.len() == 2 => (y, m, d),
        _ => return Err(shape.to_owned()),
    };
    let year: i32 = year.parse().map_err(|_| shape.to_owned())?;
    let month: u8 = month.parse().map_err(|_| shape.to_owned())?;
    let day: u8 = day.parse().map_err(|_| shape.to_owned())?;
    let month = Month::try_from(month).map_err(|_| shape.to_owned())?;
    Date::from_calendar_date(year, month, day).map_err(|_| shape.to_owned())
}

fn ensure_qualified_ref(field: &str, value: &str, git_ref: &str) -> Result<()> {
    if git_ref.starts_with(REFS_HEADS_PREFIX) && git_ref.len() > REFS_HEADS_PREFIX.len() {
        return Ok(());
    }
    if git_ref.starts_with(REFS_TAGS_PREFIX) && git_ref.len() > REFS_TAGS_PREFIX.len() {
        return Ok(());
    }
    if git_ref.len() == FULL_SHA_LEN && git_ref.chars().all(|c| c.is_ascii_hexdigit()) {
        return Ok(());
    }
    bail!(
        "field '{field}': entry '{value}' has unqualified ref '{git_ref}'; use '{REFS_HEADS_PREFIX}...', exact '{REFS_TAGS_PREFIX}...', or a full {FULL_SHA_LEN}-character SHA"
    );
}

