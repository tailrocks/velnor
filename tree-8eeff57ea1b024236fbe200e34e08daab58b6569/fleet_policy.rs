#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum GroupVisibility {
    Selected,
}

impl fmt::Display for GroupVisibility {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            GroupVisibility::Selected => write!(f, "selected"),
        }
    }
}

/// One admitted workflow identity: `<owner>/<repo>/.github/workflows/<file>@<qualified ref>`.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub struct WorkflowIdentity {
    /// Full path including `owner/repo` prefix.
    pub path: String,
    /// Qualified `refs/heads/...`, exact `refs/tags/...`, or full 40-char SHA.
    #[serde(rename = "ref")]
    pub git_ref: String,
}

impl WorkflowIdentity {
    pub fn to_selected_string(&self) -> String {
        format!("{}@{}", self.path, self.git_ref)
    }
}

impl fmt::Display for WorkflowIdentity {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.to_selected_string())
    }
}

/// Generated per-organization trusted-group policy (leaf Step 1 fields).
///
/// Field declaration order is the canonical JSON order; vectors must be kept
/// sorted (see [`OrgPolicy::normalized`]) so generated bytes are reproducible.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OrgPolicy {
    pub schema_version: i64,
    pub contract_version: String,
    pub generator_version: String,
    pub organization: String,
    pub group_name: String,
    pub runner_labels: Vec<String>,
    pub visibility: GroupVisibility,
    pub allows_public_repositories: bool,
    pub restricted_to_workflows: bool,
    /// Sorted, duplicate-free `owner/repo` values.
    pub selected_repositories: Vec<String>,
    /// Sorted, duplicate-free workflow identities.
    pub selected_workflows: Vec<WorkflowIdentity>,
}

impl OrgPolicy {
    #[allow(dead_code)]
    pub fn new(organization: impl Into<String>) -> Self {
        Self {
            schema_version: RELEASE_REF_LEDGER_SCHEMA_VERSION,
            contract_version: POLICY_CONTRACT_VERSION.to_owned(),
            generator_version: GENERATOR_VERSION.to_owned(),
            organization: organization.into(),
            group_name: REQUIRED_GROUP_NAME.to_owned(),
            runner_labels: vec![REQUIRED_RUNNER_LABEL.to_owned()],
            visibility: GroupVisibility::Selected,
            allows_public_repositories: true,
            restricted_to_workflows: true,
            selected_repositories: Vec::new(),
            selected_workflows: Vec::new(),
        }
    }

    /// Sort and de-duplicate the mutable entry sets in place.
    #[allow(dead_code)]
    pub fn normalized(mut self) -> Self {
        self.runner_labels = normalize_strings(self.runner_labels);
        self.selected_repositories = normalize_strings(self.selected_repositories);
        let workflows: BTreeSet<WorkflowIdentity> = self.selected_workflows.into_iter().collect();
        self.selected_workflows = workflows.into_iter().collect();
        self
    }

    /// Canonical compact JSON; fails closed on an invalid policy.
    pub fn canonical_json(&self) -> Result<String> {
        validate_policy(self)?;
        serde_json::to_string(self).context("canonical policy JSON serialization")
    }

    /// `sha256:<hex>` over [`Self::canonical_json`] bytes.
    pub fn digest(&self) -> Result<String> {
        let json = self.canonical_json()?;
        Ok(format!("sha256:{}", hex_digest(json.as_bytes())))
    }
}

fn normalize_strings(values: Vec<String>) -> Vec<String> {
    values
        .into_iter()
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect()
}

fn hex_digest(bytes: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    let out = hasher.finalize();
    out.iter().map(|byte| format!("{byte:02x}")).collect()
}

/// Reject a stale reviewed digest against the freshly computed one.
pub fn verify_plan_digest(reported: &str, actual: &str) -> Result<()> {
    if reported == actual {
        return Ok(());
    }
    bail!(
        "field 'plan_digest': reported digest '{reported}' is stale; current policy digest is '{actual}' (re-run plan and re-review)"
    );
}

