fn refresh_velnor_source_pins(template: &str) -> String {
    let mut rendered = String::with_capacity(template.len());
    let mut previous_line_was_velnor_repository = false;

    for segment in template.split_inclusive('\n') {
        let line = segment.strip_suffix('\n').unwrap_or(segment);
        let replacement = if previous_line_was_velnor_repository {
            replace_full_sha_after_key(line, "ref:")
        } else {
            replace_full_sha_after_key(line, "VELNOR_SOURCE_SHA:")
        };
        if let Some(replacement) = replacement {
            rendered.push_str(&replacement);
            if segment.ends_with('\n') {
                rendered.push('\n');
            }
        } else {
            rendered.push_str(segment);
        }
        previous_line_was_velnor_repository =
            line.trim() == format!("repository: {}", crate::regen_repository_marker());
    }

    rendered
}

fn replace_full_sha_after_key(line: &str, key: &str) -> Option<String> {
    let trimmed = line.trim_start();
    let indentation = line.len() - trimmed.len();
    let rest = trimmed.strip_prefix(key)?;
    if !rest.chars().next().is_some_and(char::is_whitespace) {
        return None;
    }
    let value_offset = rest.find(|character: char| !character.is_whitespace())?;
    let value = rest[value_offset..].split_whitespace().next()?;
    if value.len() != 40 || !value.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return None;
    }

    let value_start = indentation + key.len() + value_offset;
    let value_end = value_start + value.len();
    let mut replacement = String::with_capacity(line.len());
    replacement.push_str(&line[..value_start]);
    replacement.push_str(VELNOR_WORKFLOW_SOURCE_REV);
    replacement.push_str(&line[value_end..]);
    Some(replacement)
}

fn refresh_velnor_action_pins(template: &str) -> String {
    let action = "jdx/mr-boxington-action";
    let marker = format!("{action}@");
    let replacement = ActionPin::MrBoxington.reference();
    let mut rendered = String::with_capacity(template.len());
    let mut mr_boxington_step_indent = None;

    for segment in template.split_inclusive('\n') {
        let line = segment.strip_suffix('\n').unwrap_or(segment);
        let trimmed = line.trim_start();
        let indentation = line.len() - trimmed.len();
        if mr_boxington_step_indent
            .is_some_and(|step_indent| !trimmed.is_empty() && indentation <= step_indent)
        {
            mr_boxington_step_indent = None;
        }

        if mr_boxington_step_indent.is_some_and(|step_indent| {
            indentation > step_indent && trimmed.starts_with("max-size:")
        }) {
            if segment.ends_with('\n') {
                rendered.push('\n');
            }
            continue;
        }

        if let Some(marker_start) = line.find(&marker) {
            let value_start = marker_start + marker.len();
            let value = line[value_start..]
                .split_whitespace()
                .next()
                .unwrap_or_default();
            if value.len() == 40 && value.bytes().all(|byte| byte.is_ascii_hexdigit()) {
                rendered.push_str(&line[..marker_start]);
                rendered.push_str(replacement);
                if segment.ends_with('\n') {
                    rendered.push('\n');
                }
                mr_boxington_step_indent = Some(indentation);
                continue;
            }
        }

        rendered.push_str(segment);
    }

    rendered
}

/// The inline policy job body, rendered into every trusted aggregate caller
/// (`Advisory policy` lanes) and into the base-owned `ci-policy.yml`
/// entrypoint (`Policy`).
///
/// The job mirrors the reviewed policy steps verbatim: checkout of the caller
/// workflow data, the Mr. Boxington setup, a `cargo install` of the pinned
/// policy runtime, and the audit itself. It is deliberately a `steps` job, not
/// a reusable-workflow call: a same-repository reusable call pinned to another
/// revision stops GitHub from dispatching any job of the caller on push,
/// schedule, and `workflow_dispatch` events (the run stays `pending` with zero
/// jobs until the next push cancels it), so the approved steps are inlined and
/// the runtime validator admits exactly this shape and nothing else.
///
/// `revision` is the policy runtime pin. It feeds the install `--rev`, the Mr.
/// Boxington cache-key suffix, and the `VELNOR_WORKFLOW_POLICY_REVISION` value
/// the installed audit binary requires, so the runtime that audits a tree is
/// always exactly the runtime the tree declares. The audit lane itself is
/// pinned to a hosted runner on purpose: it checks out untrusted fork head
/// data, so it must never land on self-hosted capacity.
pub(crate) fn inline_policy_job(name: &str, revision: &str) -> String {
    format!(
            "  policy:\n    name: {name}\n    runs-on: ubuntu-24.04\n    timeout-minutes: 10\n    permissions:\n      contents: read\n    steps:\n      - name: Checkout caller workflow data\n        uses: {}\n        with:\n          repository: ${{{{ github.event.pull_request.head.repo.full_name || github.repository }}}}\n          ref: ${{{{ github.event.pull_request.head.sha || github.sha }}}}\n          path: policy-checkout\n          sparse-checkout: |\n            .github/workflows\n          sparse-checkout-cone-mode: true\n          fetch-depth: 1\n          persist-credentials: false\n          # Static policy validation only; fork head checkout is intentional.\n          allow-unsafe-pr-checkout: true\n      - name: Set up Mr. Boxington\n        uses: {}\n        with:\n          backend: github\n          version: {MR_BOXINGTON_VERSION}\n          cache-key: velnor-policy-mbx-{MR_BOXINGTON_VERSION}-${{{{ runner.os }}}}-${{{{ runner.arch }}}}-{revision}\n          restore-keys: |\n            velnor-policy-mbx-{MR_BOXINGTON_VERSION}-${{{{ runner.os }}}}-${{{{ runner.arch }}}}-\n      - name: Install pinned Velnor workflow runtime\n        env:\n          CARGO_HOME: ${{{{ runner.temp }}}}/velnor-workflow-cargo-home\n          CARGO_TARGET_DIR: ${{{{ runner.temp }}}}/velnor-workflow-cargo-target\n          VELNOR_WORKFLOW_INSTALL_DIR: ${{{{ runner.temp }}}}/velnor-workflow-install\n          VELNOR_WORKFLOW_ROOT: ${{{{ runner.temp }}}}/velnor-workflow\n        run: |\n          set -euo pipefail\n          install -d -m 700 \\\n            \"$CARGO_HOME\" \\\n            \"$CARGO_TARGET_DIR\" \\\n            \"$VELNOR_WORKFLOW_INSTALL_DIR\"\n          cd \"$VELNOR_WORKFLOW_INSTALL_DIR\"\n          cargo install \\\n            --locked \\\n            --git {VELNOR_WORKFLOW_INSTALL_GIT_URL} \\\n            --rev {revision} \\\n            --root \"$VELNOR_WORKFLOW_ROOT\" \\\n            velnor-workflow \\\n            --bin velnor-workflow\n          echo \"$VELNOR_WORKFLOW_ROOT/bin\" >> \"$GITHUB_PATH\"\n      - name: Enforce workflow policy\n        env:\n          WORKFLOW_ROOT: ${{{{ github.workspace }}}}/policy-checkout\n          {VELNOR_POLICY_REVISION_ENV}: {revision}\n        run: velnor-workflow policy --workflow-root \"$WORKFLOW_ROOT\"\n",
        ActionPin::Checkout.reference(),
        ActionPin::MrBoxington.reference(),
    )
}

