fn write_toml_string(output: &mut String, name: &str, value: &str) {
    let escaped = value.replace('\\', "\\\\").replace('"', "\\\"");
    let _ = writeln!(output, "{name} = \"{escaped}\"");
}

fn write_toml_array(output: &mut String, name: &str, values: &[String]) {
    let values = values
        .iter()
        .map(|value| format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\"")))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(output, "{name} = [{values}]");
}

/// Scan a local repository without evaluating project-controlled files.
///
/// # Errors
/// Returns filesystem errors with the affected path.
pub fn scan_repository(root: &Path, runners: RunnerMode) -> Result<ProjectConfig, GeneratorError> {
    scan_repository_with_default_branch(root, runners, "main")
}

fn scan_repository_with_default_branch(
    root: &Path,
    runners: RunnerMode,
    default_branch: &str,
) -> Result<ProjectConfig, GeneratorError> {
    Ok(scan_target(root, runners, default_branch)?.config)
}

/// One scan pass over a repository: the shape, the optional repo-owned
/// generation config, and the generation inputs they pin together.
#[derive(Clone, Debug, PartialEq)]
struct ScannedTarget {
    shape: scan::RepositoryShape,
    config: ProjectConfig,
    generation: Option<config::RepoGenerationConfig>,
    inputs: GenerationInputs,
}

fn scan_target(
    root: &Path,
    runners: RunnerMode,
    default_branch: &str,
) -> Result<ScannedTarget, GeneratorError> {
    let generation = config::discover(root)?;
    let exclude = generation
        .as_ref()
        .map(config::RepoGenerationConfig::scan_exclude)
        .transpose()?
        .unwrap_or(&[]);
    let shape = scan::scan_shape(root, runners, default_branch, exclude)?;
    let mut config = ProjectConfig::from(shape.clone());
    enable_mr_boxington_commands(&mut config);
    if let Some(generation) = &generation {
        apply_generation_config(&mut config, generation, root)?;
    }
    // A repo-owned config can add Rust units the scan did not produce. They
    // compile with the repository's own pinned toolchain like every scanned
    // Rust unit, so the parsed pin is stamped onto any Rust unit that lacks
    // one; a repository with no pin leaves them unstamped for generation to
    // refuse.
    if let Some(toolchain) = scan::rust::parse_rust_toolchain_from_dir(root)? {
        for unit in &mut config.units {
            if unit.kind == UnitKind::Rust && unit.toolchain.is_none() {
                unit.toolchain = Some(toolchain.clone());
            }
        }
    }
    let config = load_workflow_templates(root, config, generation.as_ref())?;
    let mut config = estate::apply_legacy_runner_profile(root, config);
    // The repo-owned config is validated against the resolved surface before
    // it can influence anything: a declared unit the scan did not find, or a
    // channel grant for an owner block the render does not declare, is a hard
    // error, never a silent no-op.
    if let Some(generation) = &generation {
        config.package_update_channels = generation.package_update_channels();
        let unit_ids = config
            .units
            .iter()
            .map(|unit| unit.id.clone())
            .collect::<Vec<_>>();
        let blocks = package_update_owner_blocks(&config);
        let blocks = blocks.iter().map(String::as_str).collect::<Vec<_>>();
        generation.validate(&unit_ids, &blocks)?;
    }
    // Every surface that renders a self-hosted lane must name its labels,
    // whether the rest of the contract is scanned or declared.
    validate_runner_labels(&config)?;
    let inputs = GenerationInputs::current(generation.as_ref(), &shape)?;
    Ok(ScannedTarget {
        shape,
        config,
        generation,
        inputs,
    })
}

pub(crate) fn enable_mr_boxington_commands(config: &mut ProjectConfig) {
    for unit in &mut config.units {
        if unit.kind == UnitKind::Rust {
            unit.pr_commands = unit
                .pr_commands
                .iter()
                .map(|command| mbxify_cargo_command(command))
                .collect();
            unit.full_commands = unit
                .full_commands
                .iter()
                .map(|command| mbxify_cargo_command(command))
                .collect();
        }
        unit.watch.sort();
        unit.watch.dedup();
    }
    if config.units.iter().any(|unit| unit.kind == UnitKind::Rust) {
        config.notes.push(format!(
            "Rust verification uses Mr. Boxington {MR_BOXINGTON_VERSION} by default on both lanes. GitHub-hosted jobs use its GitHub cache backend with stable per-unit keys (exact hits reuse the cache; a new entry is saved only when dependency inputs change). Velnor jobs use an explicit local-backend setup step against the image/runner-provided local store."
        ));
    }
}

fn mbxify_cargo_command(command: &str) -> String {
    if command.contains("velnor-workflow test-crates") {
        return if command.contains(MR_BOXINGTON_ENABLED_ENV) {
            command.to_owned()
        } else {
            format!("{MR_BOXINGTON_ENABLED_ENV}=1 {command}")
        };
    }
    mbxify_cargo_invocations(command).0
}

fn is_mr_boxington_cargo_subcommand(token: &str) -> bool {
    MR_BOXINGTON_CARGO_SUBCOMMANDS.contains(&token)
}

fn next_shell_token(input: &str, start: usize) -> Option<(usize, usize)> {
    let start = start
        + input[start..]
            .bytes()
            .take_while(u8::is_ascii_whitespace)
            .count();
    let first = *input.as_bytes().get(start)?;
    if matches!(first, b'\'' | b'"') {
        let mut index = start + 1;
        while index < input.len() {
            if input.as_bytes()[index] == first {
                return Some((start, index + 1));
            }
            index += 1;
        }
        return None;
    }
    let end = start
        + input[start..]
            .bytes()
            .take_while(|byte| !byte.is_ascii_whitespace())
            .count();
    Some((start, end))
}

fn is_word_boundary_before(input: &str, index: usize) -> bool {
    input
        .as_bytes()
        .get(index.wrapping_sub(1))
        .is_none_or(|byte| !byte.is_ascii_alphanumeric() && *byte != b'_' && *byte != b'-')
}

fn is_cargo_token(input: &str, index: usize) -> bool {
    input
        .get(index..index + "cargo".len())
        .is_some_and(|token| token == "cargo")
        && is_word_boundary_before(input, index)
        && input
            .as_bytes()
            .get(index + "cargo".len())
            .is_some_and(u8::is_ascii_whitespace)
}

fn is_mbx_token(input: &str, index: usize) -> bool {
    input
        .get(index..index + "mbx".len())
        .is_some_and(|token| token == "mbx")
        && is_word_boundary_before(input, index)
        && input
            .as_bytes()
            .get(index + "mbx".len())
            .is_some_and(u8::is_ascii_whitespace)
}

fn is_shell_command_separator(token: &str) -> bool {
    matches!(token, "&&" | "||" | "|" | ";" | "&")
}

fn strip_mbx_no_deps(input: &str) -> String {
    let mut output = String::with_capacity(input.len());
    let mut cursor = 0;
    let mut mbx_pending_subcommand = false;
    let mut mbx_check_or_clippy = false;
    while let Some((start, end)) = next_shell_token(input, cursor) {
        if input[cursor..start].contains('\n') {
            mbx_pending_subcommand = false;
            mbx_check_or_clippy = false;
        }
        let token = &input[start..end];
        if mbx_check_or_clippy && token == "--no-deps" {
            // Mr. Boxington's check and clippy wrappers intentionally do not
            // expose Cargo's `--no-deps` option.
            cursor = end;
        } else {
            output.push_str(&input[cursor..end]);
            cursor = end;
        }

        if is_shell_command_separator(token) {
            mbx_pending_subcommand = false;
            mbx_check_or_clippy = false;
        } else if mbx_check_or_clippy {
            // Keep the state until the shell command ends so flags can be
            // removed regardless of their position in the invocation.
        } else if mbx_pending_subcommand {
            if matches!(token, "check" | "clippy") {
                mbx_pending_subcommand = false;
                mbx_check_or_clippy = true;
            } else if !token.starts_with('+') || token.len() == 1 {
                mbx_pending_subcommand = false;
            }
        } else if token == "mbx" {
            mbx_pending_subcommand = true;
        }
    }
    output.push_str(&input[cursor..]);
    output
}

fn mbxify_rustup_cargo_invocations(input: &str) -> (String, bool) {
    let mut output = String::with_capacity(input.len());
    let mut cursor = 0;
    let mut changed = false;
    while let Some(relative_start) = input[cursor..].find("rustup run ") {
        let start = cursor + relative_start;
        if !is_word_boundary_before(input, start) {
            cursor = start + "rustup".len();
            continue;
        }
        let toolchain_start = start + "rustup run ".len();
        let Some((toolchain_start, toolchain_end)) = next_shell_token(input, toolchain_start)
        else {
            cursor = toolchain_start;
            continue;
        };
        let Some((cargo_start, cargo_end)) = next_shell_token(input, toolchain_end) else {
            cursor = toolchain_end;
            continue;
        };
        if !is_cargo_token(input, cargo_start) {
            cursor = cargo_end;
            continue;
        }
        let Some((subcommand_start, subcommand_end)) = next_shell_token(input, cargo_end) else {
            cursor = cargo_end;
            continue;
        };
        let subcommand = &input[subcommand_start..subcommand_end];
        if !is_mr_boxington_cargo_subcommand(subcommand) {
            cursor = subcommand_end;
            continue;
        }
        output.push_str(&input[cursor..start]);
        output.push_str("mbx +");
        output.push_str(&input[toolchain_start..toolchain_end]);
        cursor = cargo_end;
        changed = true;
    }
    output.push_str(&input[cursor..]);
    (output, changed)
}

fn mbxify_cargo_invocations(input: &str) -> (String, bool) {
    let (input, rustup_changed) = mbxify_rustup_cargo_invocations(input);
    let mut output = String::with_capacity(input.len());
    let mut cursor = 0;
    let mut changed = rustup_changed;
    while let Some(relative_start) = input[cursor..].find("cargo") {
        let start = cursor + relative_start;
        if !is_cargo_token(&input, start) {
            output.push_str(&input[cursor..start + "cargo".len()]);
            cursor = start + "cargo".len();
            continue;
        }
        let cargo_end = start + "cargo".len();
        let Some((subcommand_start, subcommand_end)) = next_shell_token(&input, cargo_end) else {
            output.push_str(&input[cursor..]);
            return (output, changed);
        };
        let subcommand = &input[subcommand_start..subcommand_end];
        output.push_str(&input[cursor..start]);
        if is_mr_boxington_cargo_subcommand(subcommand) {
            output.push_str("mbx");
            changed = true;
        } else {
            output.push_str("cargo");
        }
        cursor = cargo_end;
    }
    output.push_str(&input[cursor..]);
    let normalized = strip_mbx_no_deps(&output);
    let changed = changed || normalized != output;
    (normalized, changed)
}

const STATIC_MR_BOXINGTON_STEP: &str = r"      - name: Set up Mr. Boxington
        uses: jdx/mr-boxington-action@7234d3dd1a6ca8f6c381eea8e4dfb03f18fcf777 # v1.3.0
        with:
          backend: github
          github-cache-mode: objects
          version: 1.8.3
          cache-key: velnor-static-mbx-objects-v2-1.8.3-${{ runner.os }}-${{ runner.arch }}-${{ github.workflow }}-${{ github.job }}-${{ hashFiles('Cargo.lock', 'rust-toolchain.toml', 'rust-toolchain', 'mise.toml', 'mise.lock', '**/Cargo.toml') }}
          restore-keys: |
            velnor-static-mbx-objects-v2-1.8.3-${{ runner.os }}-${{ runner.arch }}-${{ github.workflow }}-${{ github.job }}-
          save-on-workflow-dispatch: true
";

fn static_workflow_job_ranges(lines: &[String]) -> Vec<(usize, usize)> {
    let Some(jobs_start) = lines.iter().position(|line| {
        line.trim_end_matches(['\n', '\r']) == "jobs:"
            && line.chars().take_while(char::is_ascii_whitespace).count() == 0
    }) else {
        return Vec::new();
    };
    let job_starts = lines
        .iter()
        .enumerate()
        .skip(jobs_start + 1)
        .take_while(|(_, line)| {
            let trimmed = line.trim();
            trimmed.is_empty()
                || line
                    .chars()
                    .next()
                    .is_some_and(|character| character.is_ascii_whitespace())
        })
        .filter_map(|(index, line)| {
            let trimmed = line.trim();
            let indentation = line.len() - line.trim_start().len();
            (indentation == 2 && trimmed.ends_with(':') && !trimmed.starts_with('-'))
                .then_some(index)
        })
        .collect::<Vec<_>>();
    job_starts
        .iter()
        .enumerate()
        .map(|(index, &start)| {
            let end = job_starts.get(index + 1).copied().unwrap_or(lines.len());
            (start, end)
        })
        .collect()
}

fn line_has_mbx_cargo_invocation(line: &str) -> bool {
    let mut cursor = 0;
    while let Some(relative_start) = line[cursor..].find("mbx") {
        let start = cursor + relative_start;
        if is_mbx_token(line, start) {
            let mbx_end = start + "mbx".len();
            let Some((token_start, token_end)) = next_shell_token(line, mbx_end) else {
                return false;
            };
            let token = &line[token_start..token_end];
            if let Some(toolchain) = token.strip_prefix('+') {
                if !toolchain.is_empty()
                    && next_shell_token(line, token_end).is_some_and(|(start, end)| {
                        is_mr_boxington_cargo_subcommand(&line[start..end])
                    })
                {
                    return true;
                }
            } else if is_mr_boxington_cargo_subcommand(token) {
                return true;
            }
        }
        cursor = start + "mbx".len();
    }
    false
}

fn static_workflow_step_start(line: &str) -> bool {
    line.len() - line.trim_start().len() == 6 && line.trim_start().starts_with("- ")
}

fn ensure_static_mr_boxington_steps(lines: &mut Vec<String>) {
    let ranges = static_workflow_job_ranges(lines);
    let mut insertions = Vec::new();
    for (job_start, job_end) in ranges {
        if !lines[job_start..job_end]
            .iter()
            .any(|line| line.contains("jdx/mr-boxington-action@"))
            && lines[job_start..job_end]
                .iter()
                .any(|line| line_has_mbx_cargo_invocation(line))
        {
            let Some(steps_start) = (job_start..job_end).find(|&index| {
                let line = &lines[index];
                line.len() - line.trim_start().len() == 4 && line.trim() == "steps:"
            }) else {
                continue;
            };
            let step_starts = (steps_start + 1..job_end)
                .filter(|&index| static_workflow_step_start(&lines[index]))
                .collect::<Vec<_>>();
            let insert_at = step_starts
                .iter()
                .enumerate()
                .find_map(|(index, &step_start)| {
                    let step_end = step_starts.get(index + 1).copied().unwrap_or(job_end);
                    lines[step_start..step_end]
                        .iter()
                        .any(|line| line.contains("actions/checkout@"))
                        .then_some(step_end)
                })
                .or_else(|| step_starts.first().copied())
                .unwrap_or(steps_start + 1);
            insertions.push((insert_at, STATIC_MR_BOXINGTON_STEP.to_owned()));
        }
    }
    for (index, step) in insertions.into_iter().rev() {
        lines.insert(index, step);
    }
}

fn refresh_static_mr_boxington_commands(template: &str) -> String {
    let mut lines = template
        .split_inclusive('\n')
        .map(str::to_owned)
        .collect::<Vec<_>>();
    for line in &mut lines {
        line.clone_from(&mbxify_cargo_invocations(line).0);
    }
    ensure_static_mr_boxington_steps(&mut lines);
    lines.concat()
}

fn load_workflow_templates(
    root: &Path,
    mut config: ProjectConfig,
    generation: Option<&config::RepoGenerationConfig>,
) -> Result<ProjectConfig, GeneratorError> {
    let declared = generation.and_then(|generation| generation.templates_dir());
    let directory = match declared {
        Some(directory) => root.join(directory),
        None => root.join(WORKFLOW_TEMPLATE_DIR),
    };
    if !directory.is_dir() {
        if let Some(declared) = declared {
            return Err(GeneratorError::usage(format!(
                "generation config declares `[workflow] templates = \"{declared}\"`, which is not a directory: {}",
                directory.display()
            )));
        }
        return Ok(config);
    }
    let entries = fs::read_dir(&directory)
        .map_err(|error| GeneratorError::io("read workflow templates", &directory, &error))?;
    let mut names = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|error| {
            GeneratorError::io("read workflow template entry", &directory, &error)
        })?;
        let path = entry.path();
        let file_type = entry
            .file_type()
            .map_err(|error| GeneratorError::io("read workflow template type", &path, &error))?;
        let Some(name) = path.file_name().and_then(|value| value.to_str()) else {
            continue;
        };
        let extension = path.extension().and_then(|value| value.to_str());
        if !file_type.is_file() || !matches!(extension, Some("yml" | "yaml")) {
            continue;
        }
        let content = fs::read_to_string(&path)
            .map_err(|error| GeneratorError::io("read workflow template", &path, &error))?;
        let body = content.strip_prefix(GENERATED_HEADER).ok_or_else(|| {
            GeneratorError::usage(format!(
                "workflow template is not generated by velnor-workflow: {}",
                path.display()
            ))
        })?;
        names.push(name.to_owned());
        config
            .workflow_templates
            .insert(name.to_owned(), body.to_owned());
    }
    names.sort();
    names.dedup();
    // A declared template directory is the repository's own reviewed surface:
    // it owns the file list instead of extending the generator's default one.
    if declared.is_some() {
        if names.is_empty() {
            return Err(GeneratorError::usage(format!(
                "generation config declares `[workflow] templates = \"{}\"`, which owns no workflow template",
                directory.display()
            )));
        }
        config.workflow_files = names;
        config.adopted_workflow_surface = true;
        return Ok(config);
    }
    // A repository without a resolved identity reloads its adopted surface:
    // the template directory it already owns is the whole workflow list, not
    // an extension of the generator's default one.
    if config.repository.is_empty() {
        config.workflow_files = names;
        config.adopted_workflow_surface = true;
        return Ok(config);
    }
    for name in names {
        if !config.workflow_files.contains(&name) {
            config.workflow_files.push(name);
        }
    }
    Ok(config)
}

/// Apply the generation config a repository declares for itself. Every field
/// is optional: an absent one keeps the resolved scan default, which is what
/// lets a repository adopt the config one section at a time.
///
/// # Errors
/// Returns errors for a declared source file that is missing or unreadable.
fn validate_config_text(value: &str, field: &str) -> Result<(), GeneratorError> {
    if value.is_empty() || value.chars().any(char::is_control) {
        return Err(GeneratorError::usage(format!(
            "{field} must be non-empty and contain no control characters"
        )));
    }
    Ok(())
}

fn apply_generation_config(
    config: &mut ProjectConfig,
    generation: &config::RepoGenerationConfig,
    root: &Path,
) -> Result<(), GeneratorError> {
    if let Some(repository) = generation.repository() {
        repository.clone_into(&mut config.repository);
    }
    if let Some(runner) = generation.github_runner() {
        validate_config_text(runner, "[workflow] github_runner")?;
        runner.clone_into(&mut config.github_runner);
    }
    if let Some(labels) = generation.velnor_labels() {
        if labels.is_empty() {
            return Err(GeneratorError::usage(
                "[workflow] velnor_labels must not be empty",
            ));
        }
        for label in labels {
            validate_config_text(label, "[workflow] velnor_labels")?;
        }
        config.velnor_labels = labels.to_vec();
    }
    if let Some(group) = generation.velnor_runner_group() {
        config.velnor_runner_group = Some(group.to_owned());
    }
    if let Some(profile) = generation.profile() {
        profile.clone_into(&mut config.profile);
    }
    if let Some(verified) = generation.verified() {
        config.verified = verified;
    }
    if let Some(files) = generation.files() {
        config.workflow_files = files.to_vec();
    }
    if let Some(units) = generation.version_bump_units() {
        config.version_bump_units = units.to_vec();
    }
    if let Some(branch) = generation.default_branch() {
        validate_default_branch(branch)?;
        branch.clone_into(&mut config.default_branch);
    }
    if let Some(ci_required) = generation.ci_required() {
        config.ci_required = ci_required;
    }
    if let Some(null) = generation.actionlint_config_variables_null() {
        config.actionlint_config_variables_null = null;
    }
    apply_release(config, generation.release());
    apply_unit_rows(config, generation.units());
    read_static_files(config, generation.static_files(), root)?;
    config.declared_surface = true;
    Ok(())
}

/// The release contract a repository declares. `enabled` and `reason` are the
/// recorded decision; the rest is the contract the publisher renders from.
fn apply_release(config: &mut ProjectConfig, release: &config::ReleaseSection) {
    if let Some(enabled) = release.enabled() {
        config.release_enabled = enabled;
    }
    if let Some(reason) = release.reason() {
        reason.clone_into(&mut config.release_reason);
    }
    let declared = release.kind().is_some()
        || !release.packages().is_empty()
        || release.package().is_some()
        || release.binary().is_some()
        || !release.targets().is_empty()
        || release.image().is_some()
        || release.source_repository().is_some()
        || release.consumer_repository().is_some()
        || release.artifact_path().is_some()
        || release.description().is_some();
    if !declared {
        return;
    }
    let mut spec = config.release.clone().unwrap_or_default();
    if let Some(kind) = release.kind() {
        kind.clone_into(&mut spec.kind);
    }
    if let Some(package) = release.package() {
        package.clone_into(&mut spec.package);
    }
    if !release.packages().is_empty() {
        spec.packages = release.packages().to_vec();
    }
    if let Some(binary) = release.binary() {
        binary.clone_into(&mut spec.binary);
    }
    if !release.targets().is_empty() {
        spec.targets = release.targets().to_vec();
    }
    if let Some(image) = release.image() {
        image.clone_into(&mut spec.image);
    }
    if let Some(source) = release.source_repository() {
        source.clone_into(&mut spec.source_repository);
    }
    if let Some(consumer) = release.consumer_repository() {
        consumer.clone_into(&mut spec.consumer_repository);
    }
    if let Some(artifact) = release.artifact_path() {
        artifact.clone_into(&mut spec.artifact_path);
    }
    if let Some(description) = release.description() {
        description.clone_into(&mut spec.description);
    }
    config.release = Some(spec);
}

/// Apply the `[[unit]]` rows a repository declares: a row whose `id` the scan
/// produced overrides only the fields it names, any other id adds a unit at
/// the end of the scan order.
fn apply_unit_rows(config: &mut ProjectConfig, rows: &[config::UnitSection]) {
    for row in rows {
        apply_unit_row(config, row);
    }
}

fn apply_unit_row(config: &mut ProjectConfig, row: &config::UnitSection) {
    let Some(id) = row.id() else {
        return;
    };
    let existing = config.units.iter_mut().find(|unit| unit.id == id);
    let Some(unit) = existing else {
        let Some(kind) = row.kind().and_then(UnitKind::from_prefix) else {
            return;
        };
        config.units.push(Unit {
            id: id.to_owned(),
            label: row.label().unwrap_or_default().to_owned(),
            kind,
            root: row.root().unwrap_or_default().to_owned(),
            pinned_lockfile: row.pinned_lockfile().unwrap_or(false),
            watch: row.watch().unwrap_or_default().to_vec(),
            pr_commands: row.pr_commands().unwrap_or_default().to_vec(),
            full_commands: row.full_commands().unwrap_or_default().to_vec(),
            github_pr_commands: row.github_pr_commands().map(Vec::from),
            github_full_commands: row.github_full_commands().map(Vec::from),
            velnor_pr_commands: row.velnor_pr_commands().map(Vec::from),
            velnor_full_commands: row.velnor_full_commands().map(Vec::from),
            depends_on: row.depends_on().unwrap_or_default().to_vec(),
            cache: row.cache().map(|cache| CacheSpec {
                key_files: cache.key_files().unwrap_or_default().to_vec(),
                paths: cache.paths().unwrap_or_default().to_vec(),
                purpose: CachePurpose::Generic,
                mbx_output_cache_justification: None,
            }),
            tool_version: row.tool_version().map(str::to_owned),
            toolchain: None,
        });
        return;
    };
    if let Some(label) = row.label() {
        label.clone_into(&mut unit.label);
    }
    if let Some(kind) = row.kind().and_then(UnitKind::from_prefix) {
        unit.kind = kind;
    }
    if let Some(root) = row.root() {
        root.clone_into(&mut unit.root);
    }
    if let Some(watch) = row.watch() {
        unit.watch = watch.to_vec();
    }
    if let Some(commands) = row.pr_commands() {
        unit.pr_commands = commands.to_vec();
    }
    if let Some(commands) = row.full_commands() {
        unit.full_commands = commands.to_vec();
    }
    if let Some(commands) = row.github_pr_commands() {
        unit.github_pr_commands = Some(commands.to_vec());
    }
    if let Some(commands) = row.github_full_commands() {
        unit.github_full_commands = Some(commands.to_vec());
    }
    if let Some(commands) = row.velnor_pr_commands() {
        unit.velnor_pr_commands = Some(commands.to_vec());
    }
    if let Some(commands) = row.velnor_full_commands() {
        unit.velnor_full_commands = Some(commands.to_vec());
    }
    if let Some(dependencies) = row.depends_on() {
        unit.depends_on = dependencies.to_vec();
    }
    if let Some(cache) = row.cache() {
        unit.cache = Some(CacheSpec {
            key_files: cache.key_files().unwrap_or_default().to_vec(),
            paths: cache.paths().unwrap_or_default().to_vec(),
            purpose: CachePurpose::Generic,
            mbx_output_cache_justification: None,
        });
    }
    if let Some(pinned) = row.pinned_lockfile() {
        unit.pinned_lockfile = pinned;
    }
    if let Some(version) = row.tool_version() {
        unit.tool_version = Some(version.to_owned());
    }
}

/// Read the repository-local files the generated output owns verbatim. The
/// repository owns the bytes at `source`; the generator owns the write to
/// `file`, which stays inside `.github/`.
///
/// # Errors
/// Returns errors for a declared source that is missing, unreadable, or not
/// UTF-8.
fn read_static_files(
    config: &mut ProjectConfig,
    rows: &[config::StaticFileSection],
    root: &Path,
) -> Result<(), GeneratorError> {
    for row in rows {
        let (Some(file), Some(source)) = (row.file(), row.source()) else {
            continue;
        };
        let path = root.join(source);
        let content = fs::read_to_string(&path).map_err(|error| {
            GeneratorError::io("read declared static file source", &path, &error)
        })?;
        config.static_files.push(StaticFile {
            path: file.to_owned(),
            source: source.to_owned(),
            content,
        });
    }
    Ok(())
}

