fn strip_workflow_generator_header(content: &str) -> &str {
    if let Some(body) = content.strip_prefix(GENERATED_HEADER) {
        return body;
    }
    let Some((first, body)) = content.split_once('\n') else {
        return content;
    };
    if first.starts_with("# Generated by ") {
        body
    } else {
        content
    }
}

fn adopt_existing_workflow_templates(
    root: &Path,
    mut config: ProjectConfig,
) -> Result<ProjectConfig, GeneratorError> {
    let workflows = root.join(".github/workflows");
    if !workflows.is_dir() {
        return Ok(config);
    }
    let entries = fs::read_dir(&workflows)
        .map_err(|error| GeneratorError::io("read workflows", &workflows, &error))?;
    let mut existing = Vec::new();
    for entry in entries {
        let entry =
            entry.map_err(|error| GeneratorError::io("read workflow entry", &workflows, &error))?;
        let path = entry.path();
        let file_type = entry
            .file_type()
            .map_err(|error| GeneratorError::io("read workflow type", &path, &error))?;
        let Some(name) = path.file_name().and_then(|value| value.to_str()) else {
            continue;
        };
        let extension = path.extension().and_then(|value| value.to_str());
        if !file_type.is_file() || !matches!(extension, Some("yml" | "yaml")) {
            continue;
        }
        existing.push(name.to_owned());
    }
    existing.sort();
    existing.dedup();
    if existing.is_empty() {
        return Ok(config);
    }

    let declared_surface = config.declared_surface;
    let already_adopted = config.adopted_workflow_surface;
    if !declared_surface && !already_adopted {
        config.workflow_files.clone_from(&existing);
    }
    let generated = generated_files(&config)?;
    for name in existing {
        let output = PathBuf::from(".github/workflows").join(&name);
        if declared_surface && generated.contains_key(&output) {
            continue;
        }
        let path = root.join(&output);
        let content = fs::read_to_string(&path)
            .map_err(|error| GeneratorError::io("read workflow for adoption", &path, &error))?;
        if already_adopted
            && content.starts_with(GENERATED_HEADER)
            && !config.workflow_templates.contains_key(&name)
        {
            continue;
        }
        if config.workflow_templates.contains_key(&name) {
            continue;
        }
        config
            .workflow_templates
            .insert(name, strip_workflow_generator_header(&content).to_owned());
    }
    if !declared_surface {
        config.adopted_workflow_surface = true;
    }
    config.workflow_files = config
        .workflow_files
        .into_iter()
        .chain(config.workflow_templates.keys().cloned())
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();
    Ok(config)
}

pub(crate) fn parent_path(path: &str) -> String {
    path.rsplit_once('/')
        .map_or_else(|| ".".to_owned(), |(parent, _)| parent.to_owned())
}

fn identifier_suffix(value: &str) -> String {
    value
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect::<String>()
        .trim_matches('-')
        .to_owned()
}

fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

