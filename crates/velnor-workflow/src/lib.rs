fn plan_generated_write_with_options(
    root: &Path,
    files: &BTreeMap<PathBuf, String>,
    inputs: &GenerationInputs,
    adopt: bool,
) -> Result<GeneratedWritePlan, GeneratorError> {
    reject_symlinked_output_root(root)?;
    reject_managed_symlink_ancestors(root, files.keys())?;
    let preimages = files
        .keys()
        .map(|relative| {
            capture_file_preimage(&root.join(relative), relative)
                .map(|preimage| (relative.clone(), preimage))
        })
        .collect::<Result<BTreeMap<_, _>, _>>()?;
    let ownership_path = PathBuf::from(OWNERSHIP_STATE);
    let ownership_preimage = capture_file_preimage(&root.join(&ownership_path), &ownership_path)?;
    let state_file = parse_ownership_state(root, &ownership_preimage)?;
    let foreign_schema = match &state_file {
        OwnershipStateFile::ForeignSchema { message } => Some(message.clone()),
        _ => None,
    };
    let ownership = match &state_file {
        OwnershipStateFile::Present(state) => Some(state),
        OwnershipStateFile::Absent | OwnershipStateFile::ForeignSchema { .. } => None,
    };
    let ownership_needs_refresh = verify_generated_ownership(
        files,
        ownership.map(|state| &state.outputs),
        &preimages,
        adopt,
    )? || !ownership_preimage
        .has_bytes(ownership_state_content(files, inputs).as_bytes());
    let stale_files = stale_owned_files(root, files, ownership.map(|state| &state.outputs))?;
    let stale = stale_files
        .iter()
        .map(|file| file.path.clone())
        .collect::<Vec<_>>();
    let changed: Vec<PathBuf> = files
        .iter()
        .filter(|(relative, wanted)| {
            preimages
                .get(*relative)
                .is_none_or(|preimage| !preimage.has_bytes(wanted.as_bytes()))
        })
        .map(|(relative, _)| relative.clone())
        .collect::<Vec<_>>();
    let legacy = direct_legacy_workflows(root, files)?;
    let conflicts = changed
        .iter()
        .filter(|relative| root.join(relative).exists())
        .cloned()
        .collect::<Vec<_>>();

    // Every recognized workflow is emitted by this generator. Refuse an
    // unrecognized workflow before `--force` can archive or remove an active
    // publisher; add its fixed renderer/template first.
    if !legacy.is_empty() {
        return Err(GeneratorError::usage(format!(
            "existing workflows are outside the Velnor workflow generator and will not be migrated, archived, or removed: {}; rerun with --adopt after review",
            display_paths(legacy.iter()),
        )));
    }
    let mut planned_files = files
        .keys()
        .map(|path| {
            let action = if changed.contains(path) {
                if root.join(path).exists() {
                    PlannedAction::Update
                } else {
                    PlannedAction::Create
                }
            } else {
                PlannedAction::Same
            };
            PlannedFile {
                path: path.clone(),
                action,
                preimage: preimages
                    .get(path)
                    .cloned()
                    .unwrap_or(FilePreimage::Missing),
            }
        })
        .collect::<Vec<_>>();
    planned_files.extend(stale_files);
    let ownership_action = if ownership.is_none() {
        PlannedAction::Create
    } else if ownership_needs_refresh || !changed.is_empty() || !stale.is_empty() {
        PlannedAction::Update
    } else {
        PlannedAction::Same
    };
    planned_files.push(PlannedFile {
        path: ownership_path,
        action: ownership_action,
        preimage: ownership_preimage,
    });
    Ok(GeneratedWritePlan {
        files: planned_files,
        changed,
        stale,
        conflicts,
        ownership_present: matches!(state_file, OwnershipStateFile::Present(_)),
        ownership_needs_refresh,
        recorded_inputs: ownership.map(|state| state.inputs.clone()),
        foreign_schema,
    })
}

/// The `--check` verdict: `None` means current, `Some` is the failure to
/// report. When the only planned change is the state file itself, the outputs
/// still match, so the report names the input that moved instead of listing a
/// "diff" that is really provenance drift.
fn generated_check_error(
    inputs: &GenerationInputs,
    plan: &GeneratedWritePlan,
) -> Option<GeneratorError> {
    let input_change = |plan: &GeneratedWritePlan| {
        plan.recorded_inputs.as_ref().and_then(|recorded| {
            inputs.changed_from(recorded).map(|(name, previous, current)| {
                GeneratorError::usage(format!(
                    "generated files match but generation inputs changed: {name} input changed from {previous} to {current} in {}; regenerate to record the current generation inputs",
                    Path::new(OWNERSHIP_STATE).display(),
                ))
            })
        })
    };
    let outputs_unchanged = plan.changed.is_empty() && plan.stale.is_empty();
    if outputs_unchanged
        && plan.differences() == [PathBuf::from(OWNERSHIP_STATE)]
        && let Some(error) = input_change(plan)
    {
        return Some(error);
    }
    if !plan.has_drift() {
        return input_change(plan);
    }
    if outputs_unchanged && !plan.ownership_present {
        return Some(GeneratorError::usage(
            "generated files have no ownership state; rerun generate once to adopt the exact generated output",
        ));
    }
    Some(GeneratorError::usage(format!(
        "generated files differ: {}; rerun generate",
        display_paths(plan.differences().iter()),
    )))
}

fn apply_generated_write_plan(
    root: &Path,
    files: &BTreeMap<PathBuf, String>,
    inputs: &GenerationInputs,
    dry_run: bool,
    check: bool,
    force: bool,
    plan: &GeneratedWritePlan,
) -> Result<WriteOutcome, GeneratorError> {
    validate_plan_preimages(root, plan)?;
    // A state file written by another schema is never parsed, so its recorded
    // provenance cannot support a check verdict: refuse to conclude instead of
    // silently treating it as absent.
    if let Some(message) = &plan.foreign_schema
        && (check || dry_run)
    {
        return Err(GeneratorError::usage(message.clone()));
    }
    if check {
        return match generated_check_error(inputs, plan) {
            Some(error) => Err(error),
            None => Ok(WriteOutcome::Unchanged),
        };
    }
    if dry_run {
        return Ok(WriteOutcome::DryRun(plan.differences()));
    }
    if !plan.conflicts.is_empty() && !force {
        return Err(GeneratorError::usage(format!(
            "would overwrite generated files: {}; rerun with --force after review",
            display_paths(plan.conflicts.iter()),
        )));
    }
    if !plan.has_drift() {
        return Ok(WriteOutcome::Unchanged);
    }
    let _generation_lock = GenerationLock::acquire(root, files.keys())?;
    validate_plan_preimages(root, plan)?;
    // A pre-state version is safe to adopt only when every existing generated
    // file exactly matches this renderer's output. `verify_generated_ownership`
    // rejects any divergent file before this point, including under `--force`.
    if plan.changed.is_empty()
        && plan.stale.is_empty()
        && (!plan.ownership_present || plan.ownership_needs_refresh)
    {
        return apply_ownership_refresh(root, files, inputs, plan);
    }
    let created = plan
        .files
        .iter()
        .filter(|file| file.action == PlannedAction::Create)
        .map(|file| file.path.clone())
        .collect::<BTreeSet<_>>();
    let mut written = plan.changed.clone();
    written.extend(plan.stale.iter().cloned());
    let ownership_path = PathBuf::from(OWNERSHIP_STATE);
    if !written.contains(&ownership_path) {
        written.push(ownership_path.clone());
    }
    for relative in &plan.changed {
        let Some(content) = files.get(relative) else {
            return Err(GeneratorError::usage(format!(
                "generated plan references an unknown file: {}",
                relative.display()
            )));
        };
        let planned = plan
            .files
            .iter()
            .find(|file| &file.path == relative)
            .ok_or_else(|| GeneratorError::usage("generated plan has no file preimage"))?;
        write_reviewed_file(&root.join(relative), relative, content, &planned.preimage)?;
    }
    for relative in &plan.stale {
        let planned = plan
            .files
            .iter()
            .find(|file| &file.path == relative)
            .ok_or_else(|| GeneratorError::usage("generated plan has no stale-file preimage"))?;
        delete_reviewed_file(&root.join(relative), relative, &planned.preimage)?;
    }
    let ownership_file = plan
        .files
        .iter()
        .find(|file| file.path == ownership_path)
        .ok_or_else(|| GeneratorError::usage("generated plan has no ownership preimage"))?;
    write_reviewed_file(
        &root.join(&ownership_path),
        &ownership_path,
        &ownership_state_content(files, inputs),
        &ownership_file.preimage,
    )?;
    Ok(WriteOutcome::Written {
        changed: written,
        created,
    })
}

fn apply_ownership_refresh(
    root: &Path,
    files: &BTreeMap<PathBuf, String>,
    inputs: &GenerationInputs,
    plan: &GeneratedWritePlan,
) -> Result<WriteOutcome, GeneratorError> {
    let ownership_path = PathBuf::from(OWNERSHIP_STATE);
    let ownership_file = plan
        .files
        .iter()
        .find(|file| file.path == ownership_path)
        .ok_or_else(|| GeneratorError::usage("generated plan has no ownership preimage"))?;
    let created = (ownership_file.action == PlannedAction::Create)
        .then(|| ownership_path.clone())
        .into_iter()
        .collect();
    write_reviewed_file(
        &root.join(&ownership_path),
        &ownership_path,
        &ownership_state_content(files, inputs),
        &ownership_file.preimage,
    )?;
    Ok(WriteOutcome::Written {
        changed: vec![ownership_path],
        created,
    })
}

fn reject_symlinked_output_root(root: &Path) -> Result<(), GeneratorError> {
    match fs::symlink_metadata(root) {
        Ok(metadata) if metadata.file_type().is_symlink() => Err(GeneratorError::usage(format!(
            "refusing symlinked output root: {}",
            root.display()
        ))),
        Ok(metadata) if !metadata.is_dir() => Err(GeneratorError::usage(format!(
            "output root is not a directory: {}",
            root.display()
        ))),
        Ok(_) => Ok(()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(GeneratorError::io("inspect output root", root, &error)),
    }
}

/// Generated paths are intentionally constrained beneath the target repository.
/// Refuse a symlinked managed directory instead of letting normal filesystem
/// resolution redirect a write outside that repository. The managed set is
/// derived from the emitted paths so owned files outside `.github/workflows`
/// (composite actions, workflow templates) get the same protection.
fn reject_managed_symlink_ancestors<'a>(
    root: &Path,
    generated: impl IntoIterator<Item = &'a PathBuf>,
) -> Result<(), GeneratorError> {
    let mut managed = BTreeSet::from([PathBuf::from(".github")]);
    for relative in generated {
        managed.extend(
            relative
                .ancestors()
                .skip(1)
                .filter(|ancestor| ancestor.starts_with(".github"))
                .map(Path::to_path_buf),
        );
    }
    for relative in managed {
        let path = root.join(relative);
        match fs::symlink_metadata(&path) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(GeneratorError::usage(format!(
                    "refusing symlinked managed directory: {}",
                    path.display()
                )));
            }
            Ok(metadata) if !metadata.is_dir() => {
                return Err(GeneratorError::usage(format!(
                    "managed path is not a directory: {}",
                    path.display()
                )));
            }
            Ok(_) => (),
            Err(error) if error.kind() == io::ErrorKind::NotFound => (),
            Err(error) => {
                return Err(GeneratorError::io(
                    "inspect managed directory",
                    &path,
                    &error,
                ));
            }
        }
    }
    Ok(())
}

fn capture_file_preimage(path: &Path, relative: &Path) -> Result<FilePreimage, GeneratorError> {
    let observed = match fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            return Ok(FilePreimage::Missing);
        }
        Err(error) => return Err(GeneratorError::io("inspect generated file", path, &error)),
    };
    if !observed.file_type().is_file() {
        return Err(GeneratorError::usage(format!(
            "refusing non-regular generated file: {}",
            relative.display()
        )));
    }
    let observed_identity = file_identity(&observed);
    let mut file = fs::File::open(path)
        .map_err(|error| GeneratorError::io("open generated file", path, &error))?;
    let opened_identity = file
        .metadata()
        .map(|metadata| file_identity(&metadata))
        .map_err(|error| GeneratorError::io("inspect opened generated file", path, &error))?;
    if opened_identity != observed_identity {
        return Err(GeneratorError::usage(format!(
            "generated file changed during preflight: {}",
            relative.display()
        )));
    }
    let mut bytes = Vec::new();
    file.read_to_end(&mut bytes)
        .map_err(|error| GeneratorError::io("read generated file", path, &error))?;
    let final_identity = file
        .metadata()
        .map(|metadata| file_identity(&metadata))
        .map_err(|error| GeneratorError::io("reinspect generated file", path, &error))?;
    if final_identity != observed_identity || final_identity.length != bytes.len() as u64 {
        return Err(GeneratorError::usage(format!(
            "generated file changed during preflight: {}",
            relative.display()
        )));
    }
    Ok(FilePreimage::Regular {
        identity: observed_identity,
        bytes: bytes.into_boxed_slice(),
    })
}

fn file_identity(metadata: &fs::Metadata) -> FileIdentity {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt as _;

        FileIdentity {
            length: metadata.len(),
            device: metadata.dev(),
            inode: metadata.ino(),
        }
    }
    #[cfg(not(unix))]
    {
        FileIdentity {
            length: metadata.len(),
        }
    }
}

fn validate_plan_preimages(root: &Path, plan: &GeneratedWritePlan) -> Result<(), GeneratorError> {
    reject_symlinked_output_root(root)?;
    reject_managed_symlink_ancestors(root, plan.files.iter().map(|file| &file.path))?;
    let mut changed = Vec::new();
    for file in &plan.files {
        let current = capture_file_preimage(&root.join(&file.path), &file.path)?;
        if current != file.preimage {
            changed.push(file.path.clone());
        }
    }
    if changed.is_empty() {
        return Ok(());
    }
    Err(GeneratorError::usage(format!(
        "generated files changed after preflight: {}; review again",
        display_paths(changed.iter()),
    )))
}

/// Verify that an existing generated file still matches the last generated
/// bytes before allowing a replacement. The state is accidental-loss
/// protection, not a security boundary: repository writers can alter it.
/// Returns whether exact current output needs its state refreshed.
fn verify_generated_ownership(
    files: &BTreeMap<PathBuf, String>,
    ownership: Option<&BTreeMap<PathBuf, u64>>,
    preimages: &BTreeMap<PathBuf, FilePreimage>,
    adopt: bool,
) -> Result<bool, GeneratorError> {
    let mut needs_refresh = false;
    for (relative, wanted) in files {
        let Some(preimage) = preimages.get(relative) else {
            continue;
        };
        let Some(current) = preimage.bytes() else {
            continue;
        };
        if is_known_legacy_actionlint_config(relative, current) {
            continue;
        }
        if is_known_legacy_workflows_agents_md(relative, current) {
            continue;
        }
        if adopt
            && (relative.starts_with(Path::new(".github/workflows"))
                || relative.starts_with(Path::new(WORKFLOW_TEMPLATE_DIR)))
        {
            needs_refresh = true;
            continue;
        }
        match ownership.and_then(|state| state.get(relative)) {
            Some(digest) if *digest == content_digest_bytes(current) => (),
            Some(_) => {
                if current == wanted.as_bytes() {
                    needs_refresh = true;
                    continue;
                }
                return Err(GeneratorError::usage(format!(
                    "refusing to overwrite manually modified generated file: {}; restore its recorded generated content or reconcile it manually",
                    relative.display()
                )));
            }
            None if current == wanted.as_bytes() => (),
            None => {
                return Err(GeneratorError::usage(format!(
                    "cannot prove ownership of existing generated file: {}; it differs from current output and has no recorded state",
                    relative.display()
                )));
            }
        }
    }
    Ok(needs_refresh)
}

fn is_known_legacy_actionlint_config(relative: &Path, current: &[u8]) -> bool {
    relative == Path::new(".github/actionlint.yaml")
        && current == crate::estate::LEGACY_ACTIONLINT_CONFIG.as_bytes()
}

/// The hand-written nested rule file the velnor estate shipped before the
/// generator owned it. Byte-exact, so a takeover can only adopt that one
/// documented wording and never silently rewrite a different rule file.
const LEGACY_WORKFLOWS_AGENTS_MD: &str = "# Rules\n\n\
         - Never hand-edit this directory: fix the `velnor-workflow` generator \
         (`crates/velnor-workflow`), then regenerate; regeneration overwrites manual edits.\n";

fn is_known_legacy_workflows_agents_md(relative: &Path, current: &[u8]) -> bool {
    relative == Path::new(".github/workflows/AGENTS.md")
        && current == LEGACY_WORKFLOWS_AGENTS_MD.as_bytes()
}

fn stale_owned_files(
    root: &Path,
    files: &BTreeMap<PathBuf, String>,
    ownership: Option<&BTreeMap<PathBuf, u64>>,
) -> Result<Vec<PlannedFile>, GeneratorError> {
    let Some(ownership) = ownership else {
        return Ok(Vec::new());
    };
    let mut stale = Vec::new();
    for (relative, expected) in ownership {
        if files.contains_key(relative) {
            continue;
        }
        let path = root.join(relative);
        if fs::symlink_metadata(&path).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
            return Err(GeneratorError::usage(format!(
                "refusing to remove symlinked stale generated file: {}",
                path.display()
            )));
        }
        let preimage = capture_file_preimage(&path, relative)?;
        let Some(current) = preimage.bytes() else {
            continue;
        };
        if content_digest_bytes(current) != *expected {
            return Err(GeneratorError::usage(format!(
                "stale generated file was manually modified: {}",
                relative.display()
            )));
        }
        stale.push(PlannedFile {
            path: relative.clone(),
            action: PlannedAction::Delete,
            preimage,
        });
    }
    Ok(stale)
}

/// The generation inputs a recorded state file pins: the repo-owned config
/// digest, the scanned shape digest, and the generator revision.
///
/// Generation is a function of these three plus nothing else, so `--check` may
/// conclude "current" only when the recorded outputs match and these inputs
/// still match what the current run would record.
#[derive(Clone, Debug, Eq, PartialEq)]
struct GenerationInputs {
    config: u64,
    scan: u64,
    generator: String,
}

impl GenerationInputs {
    fn current(
        generation: Option<&config::RepoGenerationConfig>,
        shape: &scan::RepositoryShape,
    ) -> Result<Self, GeneratorError> {
        Ok(Self {
            config: config::RepoGenerationConfig::digest(generation)?,
            scan: content_digest_bytes(shape.canonical_json()?.as_bytes()),
            generator: GENERATOR_REVISION.to_owned(),
        })
    }

    /// The canonical "no config, no scan" form used by the estate catalog,
    /// whose generation is a function of code-owned profiles only.
    fn parts(config: u64, scan: u64) -> Self {
        Self {
            config,
            scan,
            generator: GENERATOR_REVISION.to_owned(),
        }
    }

    fn names() -> [&'static str; 3] {
        ["config", "scan", "generator"]
    }

    fn value(&self, name: &str) -> String {
        match name {
            "config" => format!("{:016x}", self.config),
            "scan" => format!("{:016x}", self.scan),
            _ => self.generator.clone(),
        }
    }

    fn changed_from(&self, recorded: &Self) -> Option<(&'static str, String, String)> {
        Self::names().into_iter().find_map(|name| {
            let current = self.value(name);
            let previous = recorded.value(name);
            (current != previous).then_some((name, previous, current))
        })
    }
}

/// Parsed generated ownership state.
#[derive(Clone, Debug, Eq, PartialEq)]
struct OwnershipState {
    inputs: GenerationInputs,
    outputs: BTreeMap<PathBuf, u64>,
}

/// The state file as it exists on disk.
///
/// `ForeignSchema` carries the rejection message for a state file written by
/// another schema: it is never parsed, so its provenance stays unproven.
#[derive(Clone, Debug, Eq, PartialEq)]
enum OwnershipStateFile {
    Absent,
    Present(OwnershipState),
    ForeignSchema { message: String },
}

fn parse_ownership_state(
    root: &Path,
    preimage: &FilePreimage,
) -> Result<OwnershipStateFile, GeneratorError> {
    let path = root.join(OWNERSHIP_STATE);
    let Some(bytes) = preimage.bytes() else {
        return Ok(OwnershipStateFile::Absent);
    };
    let invalid = || {
        GeneratorError::usage(format!(
            "invalid generated ownership state: {}",
            path.display()
        ))
    };
    let content = std::str::from_utf8(bytes).map_err(|_| invalid())?;
    let mut lines = content.lines();
    if lines.next() != Some(OWNERSHIP_STATE_HEADER.trim_end()) {
        return Err(invalid());
    }
    let schema = lines.next().and_then(|line| line.strip_prefix("schema = "));
    if schema != Some(OWNERSHIP_STATE_SCHEMA) {
        return Ok(OwnershipStateFile::ForeignSchema {
            message: format!(
                "generated ownership state {} records `{}`; this generator writes and reads schema {} only, which adds the generation inputs (`config`, `scan`, `generator`) beside the recorded outputs and does not parse the older layout; rerun generate to move the state file to schema {}",
                path.display(),
                schema.unwrap_or("no schema line"),
                OWNERSHIP_STATE_SCHEMA,
                OWNERSHIP_STATE_SCHEMA,
            ),
        });
    }
    let section = lines.next().ok_or_else(invalid)?;
    if section != "[inputs]" {
        return Err(invalid());
    }
    let inputs = parse_inputs(&mut lines, &path)?;
    let outputs = parse_digest(lines, &path)?;
    Ok(OwnershipStateFile::Present(OwnershipState {
        inputs,
        outputs,
    }))
}

fn parse_inputs<'a>(
    lines: &mut impl Iterator<Item = &'a str>,
    path: &Path,
) -> Result<GenerationInputs, GeneratorError> {
    let invalid = || {
        GeneratorError::usage(format!(
            "invalid generated ownership state: {}",
            path.display()
        ))
    };
    let mut fields: [Option<u64>; 2] = [None, None];
    for (index, name) in GenerationInputs::names().into_iter().enumerate() {
        let line = lines.next().ok_or_else(invalid)?;
        let (raw_name, raw_value) = line.split_once('\t').ok_or_else(invalid)?;
        if raw_name != name {
            return Err(GeneratorError::usage(format!(
                "invalid generated ownership state: {} expected the {name} input",
                path.display()
            )));
        }
        if name == "generator" {
            return Ok(GenerationInputs {
                config: fields[0].ok_or_else(invalid)?,
                scan: fields[1].ok_or_else(invalid)?,
                generator: raw_value.to_owned(),
            });
        }
        fields[index] = Some(u64::from_str_radix(raw_value, 16).map_err(|_| invalid())?);
    }
    Err(invalid())
}

fn parse_digest<'a>(
    lines: impl Iterator<Item = &'a str>,
    path: &Path,
) -> Result<BTreeMap<PathBuf, u64>, GeneratorError> {
    let invalid = || {
        GeneratorError::usage(format!(
            "invalid generated ownership state: {}",
            path.display()
        ))
    };
    let mut owned = lines;
    if owned.next() != Some("[outputs]") {
        return Err(invalid());
    }
    let mut state = BTreeMap::new();
    for line in owned {
        let (raw_path, raw_digest) = line.split_once('\t').ok_or_else(invalid)?;
        let relative = managed_relative_path(raw_path)?;
        let digest = u64::from_str_radix(raw_digest, 16).map_err(|_| invalid())?;
        if state.insert(relative, digest).is_some() {
            return Err(GeneratorError::usage(format!(
                "duplicate generated ownership state entry: {}",
                path.display()
            )));
        }
    }
    Ok(state)
}

fn ownership_state_content(files: &BTreeMap<PathBuf, String>, inputs: &GenerationInputs) -> String {
    let mut content = String::from(OWNERSHIP_STATE_HEADER);
    content.push_str("schema = ");
    content.push_str(OWNERSHIP_STATE_SCHEMA);
    content.push('\n');
    content.push_str("[inputs]\n");
    for name in GenerationInputs::names() {
        let _ = writeln!(content, "{name}\t{}", inputs.value(name));
    }
    content.push_str("[outputs]\n");
    for (relative, generated) in files {
        let _ = writeln!(
            content,
            "{}\t{:016x}",
            relative.display(),
            content_digest(generated)
        );
    }
    content
}

fn managed_relative_path(value: &str) -> Result<PathBuf, GeneratorError> {
    let path = Path::new(value);
    if path
        .components()
        .all(|component| matches!(component, Component::Normal(_)))
        && value.starts_with(".github/")
    {
        return Ok(path.to_path_buf());
    }
    Err(GeneratorError::usage(
        "generated ownership state contains an unsafe path",
    ))
}

fn content_digest(content: &str) -> u64 {
    content_digest_bytes(content.as_bytes())
}

fn content_digest_bytes(content: &[u8]) -> u64 {
    // Stable FNV-1a; this catches accidental edits without a dependency.
    content
        .iter()
        .fold(0xcbf2_9ce4_8422_2325_u64, |hash, byte| {
            (hash ^ u64::from(*byte)).wrapping_mul(0x0000_0100_0000_01b3)
        })
}

fn display_paths<'a>(paths: impl Iterator<Item = &'a PathBuf>) -> String {
    paths
        .map(|path| path.display().to_string())
        .collect::<Vec<_>>()
        .join(", ")
}

fn direct_legacy_workflows(
    root: &Path,
    generated: &BTreeMap<PathBuf, String>,
) -> Result<Vec<PathBuf>, GeneratorError> {
    let workflows = root.join(".github/workflows");
    if !workflows.exists() {
        return Ok(Vec::new());
    }
    let entries = fs::read_dir(&workflows)
        .map_err(|error| GeneratorError::io("read workflows", &workflows, &error))?;
    let mut legacy = Vec::new();
    for entry in entries {
        let entry =
            entry.map_err(|error| GeneratorError::io("read workflow entry", &workflows, &error))?;
        let path = entry.path();
        let file_type = entry
            .file_type()
            .map_err(|error| GeneratorError::io("read workflow type", &path, &error))?;
        let extension = path.extension().and_then(|value| value.to_str());
        let relative = path
            .strip_prefix(root)
            .map_err(|error| {
                GeneratorError::usage(format!("make workflow path relative: {error}"))
            })?
            .to_path_buf();
        let generated_by_velnor =
            fs::read_to_string(&path).is_ok_and(|content| content.starts_with(GENERATED_HEADER));
        if file_type.is_file()
            && matches!(extension, Some("yml" | "yaml"))
            && !generated.contains_key(&relative)
            && !generated_by_velnor
        {
            legacy.push(relative);
        }
    }
    legacy.sort();
    Ok(legacy)
}

struct GenerationLock {
    _directory: fs::File,
}

impl GenerationLock {
    fn acquire<'a>(
        root: &Path,
        generated: impl IntoIterator<Item = &'a PathBuf>,
    ) -> Result<Self, GeneratorError> {
        reject_symlinked_output_root(root)?;
        fs::create_dir_all(root)
            .map_err(|error| GeneratorError::io("create output root", root, &error))?;
        reject_managed_symlink_ancestors(root, generated)?;
        let directory = fs::File::open(root)
            .map_err(|error| GeneratorError::io("open output root for locking", root, &error))?;
        // Blocking acquisition is the contract: concurrent mutators of one
        // output root serialize, they never fail spuriously. A failed
        // attempt would turn benign contention (parallel tests, overlapping
        // CLI invocations) into a hard error even though the second writer
        // could proceed safely once the first finishes.
        directory
            .lock()
            .map_err(|error| GeneratorError::io("lock output root for generation", root, &error))?;
        Ok(Self {
            _directory: directory,
        })
    }
}

fn write_reviewed_file(
    path: &Path,
    relative: &Path,
    content: &str,
    expected: &FilePreimage,
) -> Result<(), GeneratorError> {
    write_reviewed_file_observed(path, relative, content, expected, |_| Ok(()))
}

fn write_reviewed_file_observed<F>(
    path: &Path,
    relative: &Path,
    content: &str,
    expected: &FilePreimage,
    before_replace: F,
) -> Result<(), GeneratorError>
where
    F: FnOnce(&Path) -> Result<(), GeneratorError>,
{
    let current = capture_file_preimage(path, relative)?;
    if &current != expected {
        return Err(preimage_changed(relative));
    }
    let staged = stage_generated_file(path, content)?;
    match expected {
        FilePreimage::Missing => {
            if let Err(error) = fs::hard_link(&staged, path) {
                let _ = fs::remove_file(&staged);
                if error.kind() == io::ErrorKind::AlreadyExists {
                    return Err(preimage_changed(relative));
                }
                return Err(GeneratorError::io(
                    "install new generated file",
                    path,
                    &error,
                ));
            }
            fs::remove_file(&staged)
                .map_err(|error| GeneratorError::io("remove staged file", &staged, &error))?;
            Ok(())
        }
        FilePreimage::Regular { .. } => {
            let (backup_dir, backup) = reserve_backup_path(path)?;
            if let Err(error) = fs::hard_link(path, &backup) {
                let _ = fs::remove_file(&staged);
                let _ = fs::remove_dir(&backup_dir);
                return Err(GeneratorError::io(
                    "back up reviewed generated file",
                    path,
                    &error,
                ));
            }
            let backed_up = match capture_file_preimage(&backup, relative) {
                Ok(backed_up) => backed_up,
                Err(error) => {
                    let _ = fs::remove_file(&backup);
                    let _ = fs::remove_dir(&backup_dir);
                    let _ = fs::remove_file(&staged);
                    return Err(error);
                }
            };
            let live_matches =
                capture_file_preimage(path, relative).is_ok_and(|current| &current == expected);
            if &backed_up != expected || !live_matches {
                let _ = fs::remove_file(&backup);
                let _ = fs::remove_dir(&backup_dir);
                let _ = fs::remove_file(&staged);
                return Err(preimage_changed(relative));
            }
            if let Err(error) = before_replace(path) {
                let _ = fs::remove_file(&backup);
                let _ = fs::remove_dir(&backup_dir);
                let _ = fs::remove_file(&staged);
                return Err(error);
            }
            if let Err(error) = fs::rename(&staged, path) {
                let _ = fs::remove_file(&staged);
                let _ = fs::remove_file(&backup);
                let _ = fs::remove_dir(&backup_dir);
                return Err(GeneratorError::io(
                    "atomically replace reviewed generated file",
                    path,
                    &error,
                ));
            }
            // The atomic rename is the commit point. Cleanup cannot turn a
            // successful replacement into a reported failure that skips the
            // ownership-state update; a leftover backup remains recoverable.
            let _ = fs::remove_file(&backup);
            let _ = fs::remove_dir(&backup_dir);
            Ok(())
        }
    }
}

fn delete_reviewed_file(
    path: &Path,
    relative: &Path,
    expected: &FilePreimage,
) -> Result<(), GeneratorError> {
    if matches!(expected, FilePreimage::Missing) {
        return Err(preimage_changed(relative));
    }
    let current = capture_file_preimage(path, relative)?;
    if &current != expected {
        return Err(preimage_changed(relative));
    }
    let (backup_dir, backup) = reserve_backup_path(path)?;
    if let Err(error) = fs::rename(path, &backup) {
        let _ = fs::remove_dir(&backup_dir);
        return Err(GeneratorError::io(
            "reserve stale generated file",
            path,
            &error,
        ));
    }
    let moved = match capture_file_preimage(&backup, relative) {
        Ok(moved) => moved,
        Err(error) => {
            restore_reviewed_backup(path, &backup, &backup_dir)?;
            return Err(error);
        }
    };
    if &moved != expected {
        restore_reviewed_backup(path, &backup, &backup_dir)?;
        return Err(preimage_changed(relative));
    }
    // Removal of the reviewed pathname is committed. Keep ownership-state
    // progress monotonic even if cleanup leaves a recoverable hidden backup.
    let _ = fs::remove_file(&backup);
    let _ = fs::remove_dir(&backup_dir);
    Ok(())
}

/// Test helper: replace a path with new content through the same staged
/// rename the reviewed writer uses, so the file identity changes while the
/// bytes stay identical.
#[cfg(test)]
fn atomic_write(path: &Path, content: &str) -> Result<(), GeneratorError> {
    let staged = stage_generated_file(path, content)?;
    fs::rename(&staged, path)
        .map_err(|error| GeneratorError::io("install generated file", path, &error))
}

fn stage_generated_file(path: &Path, content: &str) -> Result<PathBuf, GeneratorError> {
    let parent = path
        .parent()
        .ok_or_else(|| GeneratorError::usage(format!("path has no parent: {}", path.display())))?;
    fs::create_dir_all(parent)
        .map_err(|error| GeneratorError::io("create output directory", parent, &error))?;
    let filename = path
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or_else(|| GeneratorError::usage("invalid generated output filename"))?;
    for attempt in 0..16_u8 {
        let staged = parent.join(format!(
            ".{filename}.stage-{}-{}-{attempt}",
            std::process::id(),
            unique_suffix()
        ));
        match fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&staged)
        {
            Ok(mut file) => {
                file.write_all(content.as_bytes()).map_err(|error| {
                    GeneratorError::io("write staged generated file", &staged, &error)
                })?;
                file.sync_all().map_err(|error| {
                    GeneratorError::io("sync staged generated file", &staged, &error)
                })?;
                return Ok(staged);
            }
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => (),
            Err(error) => {
                return Err(GeneratorError::io(
                    "create staged generated file",
                    &staged,
                    &error,
                ));
            }
        }
    }
    Err(GeneratorError::usage(format!(
        "could not reserve a staged file for {}",
        path.display()
    )))
}

fn reserve_backup_path(path: &Path) -> Result<(PathBuf, PathBuf), GeneratorError> {
    let parent = path
        .parent()
        .ok_or_else(|| GeneratorError::usage(format!("path has no parent: {}", path.display())))?;
    let filename = path
        .file_name()
        .ok_or_else(|| GeneratorError::usage("invalid generated output filename"))?;
    for attempt in 0..16_u8 {
        let directory = parent.join(format!(
            ".velnor-workflow-backup-{}-{}-{attempt}",
            std::process::id(),
            unique_suffix()
        ));
        match fs::create_dir(&directory) {
            Ok(()) => return Ok((directory.clone(), directory.join(filename))),
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => (),
            Err(error) => {
                return Err(GeneratorError::io(
                    "reserve generated backup directory",
                    &directory,
                    &error,
                ));
            }
        }
    }
    Err(GeneratorError::usage(format!(
        "could not reserve a backup for {}",
        path.display()
    )))
}

fn restore_reviewed_backup(
    path: &Path,
    backup: &Path,
    backup_dir: &Path,
) -> Result<(), GeneratorError> {
    fs::hard_link(backup, path).map_err(|error| {
        GeneratorError::usage(format!(
            "generated file changed concurrently; preserved reviewed bytes at {} and refused to overwrite {}: {error}",
            backup.display(),
            path.display()
        ))
    })?;
    fs::remove_file(backup)
        .map_err(|error| GeneratorError::io("remove restored backup", backup, &error))?;
    fs::remove_dir(backup_dir)
        .map_err(|error| GeneratorError::io("remove restored backup directory", backup_dir, &error))
}

fn preimage_changed(relative: &Path) -> GeneratorError {
    GeneratorError::usage(format!(
        "generated file changed after preflight: {}; review again",
        relative.display()
    ))
}

/// Uniqueness must never depend on clock resolution: parallel tests that
/// start in the same instant previously collided on one temporary root and
/// spuriously failed generation with "another generation is in progress".
/// The atomic sequence guarantees in-process uniqueness; the process id
/// separates concurrent test binaries; the timestamp keeps names legible.
fn unique_suffix() -> u128 {
    use std::sync::atomic::{AtomicU64, Ordering};
    static SEQUENCE: AtomicU64 = AtomicU64::new(0);
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |duration| duration.as_nanos());
    (nanos << 64)
        | (u128::from(std::process::id()) << 32)
        | u128::from(SEQUENCE.fetch_add(1, Ordering::Relaxed))
}

enum RepositorySource {
    Local(PathBuf),
    GitHub { owner: String, repository: String },
}

impl RepositorySource {
    fn parse(value: &str) -> Result<Self, GeneratorError> {
        Self::parse_with_candidate_path(value, PathBuf::from(value))
    }

    fn parse_with_candidate_path(value: &str, path: PathBuf) -> Result<Self, GeneratorError> {
        if path.is_dir() {
            return Ok(Self::Local(path));
        }
        if let Some((owner, repository)) = github_coordinates(value) {
            return Ok(Self::GitHub { owner, repository });
        }
        Err(GeneratorError::usage(format!(
            "target must be a local directory, https://github.com/owner/repository, or owner/repository: {value}",
        )))
    }

    fn checkout(&self) -> Result<Checkout, GeneratorError> {
        match self {
            Self::Local(path) => {
                Ok(Checkout::Local(path.canonicalize().map_err(|error| {
                    GeneratorError::io("canonicalize repository", path, &error)
                })?))
            }
            Self::GitHub { owner, repository } => Checkout::clone_github(owner, repository),
        }
    }

    fn default_branch(&self, checkout: &Path) -> Result<String, GeneratorError> {
        let _ = self;
        resolve_default_branch(checkout)
    }

    fn output_root(&self, local_checkout: &Path) -> Result<PathBuf, GeneratorError> {
        match self {
            Self::Local(_) => Ok(local_checkout.to_path_buf()),
            Self::GitHub { owner, repository } => {
                let directory = env::current_dir().map_err(|error| {
                    GeneratorError::usage(format!(
                        "read current directory for remote output: {error}"
                    ))
                })?;
                let directory = directory.canonicalize().map_err(|error| {
                    GeneratorError::io(
                        "canonicalize current directory for remote output",
                        &directory,
                        &error,
                    )
                })?;
                remote_output_root(&directory, owner, repository)
            }
        }
    }
}

fn resolve_default_branch(repository: &Path) -> Result<String, GeneratorError> {
    let symbolic_ref = Command::new("git")
        .arg("-C")
        .arg(repository)
        .args(["symbolic-ref", "--short", "refs/remotes/origin/HEAD"])
        .output();
    if let Ok(output) = symbolic_ref
        && output.status.success()
    {
        let reference = String::from_utf8_lossy(&output.stdout).trim().to_owned();
        if let Some(branch) = reference.strip_prefix("origin/") {
            return validate_default_branch(branch).map(str::to_owned);
        }
    }

    let remote_head = Command::new("git")
        .arg("-C")
        .arg(repository)
        .args(["ls-remote", "--symref", "origin", "HEAD"])
        .output()
        .map_err(|error| {
            GeneratorError::usage(format!(
                "resolve repository default branch from Git metadata: {error}; pass --default-branch explicitly"
            ))
        })?;
    if remote_head.status.success() {
        let output = String::from_utf8_lossy(&remote_head.stdout);
        if let Some(branch) = parse_remote_head(&output) {
            return Ok(branch.to_owned());
        }
    }
    Err(GeneratorError::usage(
        "repository default branch is unavailable from Git metadata; pass --default-branch explicitly",
    ))
}

fn parse_remote_head(output: &str) -> Option<&str> {
    output.lines().find_map(|line| {
        let reference = line.strip_prefix("ref: refs/heads/")?;
        let (branch, target) = reference.split_once('\t')?;
        (target == "HEAD").then(|| validate_default_branch(branch).ok())?
    })
}

fn validate_default_branch(branch: &str) -> Result<&str, GeneratorError> {
    let valid = !branch.is_empty()
        && branch.len() <= 255
        && !branch.starts_with('/')
        && !branch.ends_with('/')
        && !branch.starts_with('.')
        && !branch.ends_with('.')
        && !branch.contains("..")
        && !branch.contains("@{")
        && !branch.contains("//")
        && branch.chars().all(|character| {
            character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.' | '/')
        })
        && !Path::new(branch)
            .extension()
            .is_some_and(|extension| extension.eq_ignore_ascii_case("lock"))
        && !branch.chars().any(|character| {
            character.is_control()
                || character.is_whitespace()
                || matches!(character, '~' | '^' | ':' | '?' | '*' | '[' | '\\')
        })
        && !branch
            .split('/')
            .any(|component| component.is_empty() || component == "." || component == "..");
    if valid {
        Ok(branch)
    } else {
        Err(GeneratorError::usage(format!(
            "invalid default branch name: {branch:?}"
        )))
    }
}

fn remote_output_root(
    launch_directory: &Path,
    owner: &str,
    repository: &str,
) -> Result<PathBuf, GeneratorError> {
    let launch_directory = launch_directory.canonicalize().map_err(|error| {
        GeneratorError::io(
            "canonicalize launch directory for remote output",
            launch_directory,
            &error,
        )
    })?;
    output_root_for_repository(&launch_directory.join("repositories"), owner, repository)
}

fn output_root_for_repository(
    output_root: &Path,
    owner: &str,
    repository: &str,
) -> Result<PathBuf, GeneratorError> {
    let output = output_root.join(owner).join(repository);
    reject_path_ancestors(&output, "remote output")?;
    Ok(output)
}

fn resolve_output_path(path: &Path) -> Result<PathBuf, GeneratorError> {
    let current_directory = env::current_dir().map_err(|error| {
        GeneratorError::usage(format!("resolve current directory for output: {error}"))
    })?;
    let current_directory = current_directory.canonicalize().map_err(|error| {
        GeneratorError::io(
            "canonicalize current directory for output",
            &current_directory,
            &error,
        )
    })?;
    let candidate = if path.is_absolute() {
        path.to_path_buf()
    } else {
        current_directory.join(path)
    };
    let output = canonicalize_existing_output_prefix(&candidate)?;
    reject_path_ancestors(&output, "output path")?;
    Ok(output)
}

fn canonicalize_existing_output_prefix(path: &Path) -> Result<PathBuf, GeneratorError> {
    let mut existing = path.to_path_buf();
    let mut missing = Vec::new();
    loop {
        match fs::symlink_metadata(&existing) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                if missing.is_empty() {
                    return Err(GeneratorError::usage(format!(
                        "refusing symlinked output root: {}",
                        existing.display()
                    )));
                }
                let canonical = existing.canonicalize().map_err(|error| {
                    GeneratorError::io("canonicalize output path", &existing, &error)
                })?;
                let mut output = canonical;
                for component in missing.iter().rev() {
                    output.push(component);
                }
                return Ok(output);
            }
            Ok(metadata) if !metadata.is_dir() => {
                return Err(GeneratorError::usage(format!(
                    "output path ancestor is not a directory: {}",
                    existing.display()
                )));
            }
            Ok(_) => {
                let canonical = existing.canonicalize().map_err(|error| {
                    GeneratorError::io("canonicalize output path", &existing, &error)
                })?;
                let mut output = canonical;
                for component in missing.iter().rev() {
                    output.push(component);
                }
                return Ok(output);
            }
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                let component = existing.file_name().ok_or_else(|| {
                    GeneratorError::usage(format!(
                        "output path has no existing parent: {}",
                        path.display()
                    ))
                })?;
                missing.push(component.to_os_string());
                existing.pop();
            }
            Err(error) => {
                return Err(GeneratorError::io(
                    "inspect output path ancestor",
                    &existing,
                    &error,
                ));
            }
        }
    }
}

fn reject_path_ancestors(path: &Path, label: &str) -> Result<(), GeneratorError> {
    let mut current = PathBuf::new();
    for component in path.components() {
        current.push(component.as_os_str());
        match fs::symlink_metadata(&current) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(GeneratorError::usage(format!(
                    "refusing symlinked {label} ancestor: {}",
                    current.display()
                )));
            }
            Ok(metadata) if !metadata.is_dir() => {
                return Err(GeneratorError::usage(format!(
                    "{label} ancestor is not a directory: {}",
                    current.display()
                )));
            }
            Ok(_) => (),
            Err(error) if error.kind() == io::ErrorKind::NotFound => (),
            Err(error) => {
                return Err(GeneratorError::io(
                    &format!("inspect {label} ancestor"),
                    &current,
                    &error,
                ));
            }
        }
    }
    Ok(())
}

fn github_coordinates(value: &str) -> Option<(String, String)> {
    let trimmed = value.trim_end_matches('/').trim_end_matches(".git");
    let coordinates = trimmed
        .strip_prefix("https://github.com/")
        .or_else(|| trimmed.strip_prefix("git@github.com:"))
        .unwrap_or(trimmed);
    let mut parts = coordinates.split('/');
    let owner = parts.next()?;
    let repository = parts.next()?;
    if parts.next().is_some()
        || !valid_github_component(owner)
        || !valid_github_component(repository)
    {
        return None;
    }
    Some((owner.to_owned(), repository.to_owned()))
}

fn local_github_repository(root: &Path) -> Option<String> {
    let config = fs::read_to_string(git_config_path(root)?).ok()?;
    let mut origin = false;
    for line in config.lines().map(str::trim) {
        if let Some(remote) = line
            .strip_prefix("[remote \"")
            .and_then(|value| value.strip_suffix("\"]"))
        {
            origin = remote == "origin";
            continue;
        }
        if line.starts_with('[') {
            origin = false;
            continue;
        }
        if !origin {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        if key.trim() != "url" {
            continue;
        }
        let (owner, repository) = github_coordinates(value.trim())?;
        return Some(format!("{owner}/{repository}"));
    }
    None
}

fn git_config_path(root: &Path) -> Option<PathBuf> {
    let dot_git = root.join(".git");
    if fs::metadata(&dot_git).ok()?.is_dir() {
        return Some(dot_git.join("config"));
    }

    // Linked worktrees store a gitdir pointer in root/.git and the remote
    // configuration in the common git directory named by commondir.
    let gitfile = fs::read_to_string(&dot_git).ok()?;
    let gitdir_value = gitfile
        .lines()
        .map(str::trim)
        .find_map(|line| line.strip_prefix("gitdir:").map(str::trim))
        .filter(|value| !value.is_empty())?;
    let gitdir = resolve_git_path(root, gitdir_value);
    let config_dir = fs::read_to_string(gitdir.join("commondir"))
        .ok()
        .and_then(|commondir| {
            commondir
                .lines()
                .map(str::trim)
                .find(|line| !line.is_empty())
                .map(|line| resolve_git_path(&gitdir, line))
        })
        .unwrap_or(gitdir);
    Some(config_dir.join("config"))
}

fn resolve_git_path(base: &Path, value: &str) -> PathBuf {
    let path = Path::new(value);
    if path.is_absolute() {
        path.to_owned()
    } else {
        base.join(path)
    }
}

fn valid_github_component(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 100
        // Dot segments would make the constructed clone URL identify a
        // different repository. Names such as `.github` remain valid.
        && !matches!(value, "." | "..")
        && value.chars().all(|character| {
            character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.')
        })
}

enum Checkout {
    Local(PathBuf),
    Temporary(PathBuf),
}

impl Checkout {
    fn clone_github(owner: &str, repository: &str) -> Result<Self, GeneratorError> {
        let mut target = env::temp_dir().join(format!(
            "velnor-workflow-{owner}-{repository}-{}",
            unique_suffix()
        ));
        let mut attempts = 0;
        loop {
            match fs::create_dir(&target) {
                Ok(()) => break,
                Err(error) if error.kind() == io::ErrorKind::AlreadyExists => {
                    attempts += 1;
                    if attempts >= 8 {
                        return Err(GeneratorError::usage(
                            "could not reserve a unique temporary checkout directory",
                        ));
                    }
                    target = env::temp_dir().join(format!(
                        "velnor-workflow-{owner}-{repository}-{}",
                        unique_suffix()
                    ));
                }
                Err(error) => {
                    return Err(GeneratorError::io(
                        "create temporary checkout directory",
                        &target,
                        &error,
                    ));
                }
            }
        }
        let remote = format!("https://github.com/{owner}/{repository}.git");
        let output = match Command::new("git")
            .args([
                "clone",
                "--depth",
                "1",
                "--filter=blob:none",
                "--no-tags",
                "--",
                &remote,
            ])
            .arg(&target)
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .output()
        {
            Ok(output) => output,
            Err(error) => {
                return Err(failed_clone_error(
                    &target,
                    format!("start safe shallow clone: {error}"),
                ));
            }
        };
        if !output.status.success() {
            let details = String::from_utf8_lossy(&output.stderr).trim().to_owned();
            let message = if details.is_empty() {
                format!("safe shallow clone failed: {remote}")
            } else {
                format!("safe shallow clone failed: {remote}: {details}")
            };
            return Err(failed_clone_error(&target, message));
        }
        Ok(Self::Temporary(target))
    }

    fn path(&self) -> &Path {
        match self {
            Self::Local(path) | Self::Temporary(path) => path,
        }
    }
}

fn failed_clone_error(target: &Path, message: String) -> GeneratorError {
    match fs::remove_dir_all(target) {
        Ok(()) => GeneratorError::usage(message),
        Err(error) if error.kind() == io::ErrorKind::NotFound => GeneratorError::usage(message),
        Err(error) => GeneratorError::usage(format!(
            "{message}; failed to remove partial checkout {}: {error}",
            target.display()
        )),
    }
}

impl Drop for Checkout {
    fn drop(&mut self) {
        if let Self::Temporary(path) = self {
            let _ = fs::remove_dir_all(path);
        }
    }
}

