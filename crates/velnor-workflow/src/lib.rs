/// Run the generator from the process argument vector.
///
/// # Errors
/// Reports parsing, clone, scanning, and write failures without replacing a
/// handwritten generated file or migrating existing workflows. Individual
/// generated files are replaced atomically.
pub fn run_from_env() -> Result<(), GeneratorError> {
    let arguments = env::args_os().skip(1).collect::<Vec<_>>();
    if runtime::try_run(&arguments)? {
        return Ok(());
    }
    let raw = match parse_raw_clap(arguments) {
        Ok(raw) => raw,
        Err(error)
            if matches!(
                error.kind(),
                clap::error::ErrorKind::DisplayHelp | clap::error::ErrorKind::DisplayVersion
            ) =>
        {
            print!("{error}");
            return Ok(());
        }
        Err(error) => return Err(clap_usage_error(&error)),
    };
    let cli = raw.try_into()?;
    run(&cli)
}

fn run(cli: &Cli) -> Result<(), GeneratorError> {
    if cli.target == "estate" {
        return run_estate(cli);
    }
    if !cli.plain && io::stdin().is_terminal() && io::stdout().is_terminal() {
        return tui::run(cli);
    }
    let source = RepositorySource::parse(&cli.target)?;
    let checkout = source.checkout()?;
    let config = scan_repository(checkout.path(), cli.runners)?;
    if config.units.is_empty() {
        return Err(GeneratorError::usage(
            "scanner found no supported manifest or project shape; add project.toml manually only after defining a safe command",
        ));
    }
    let files = generated_files(&config);
    let output_root = match cli.output.as_deref() {
        Some(path) => resolve_output_path(path)?,
        None => source.output_root(checkout.path())?,
    };
    let outcome = write_generated(&output_root, &files, cli.dry_run, cli.check, cli.force)?;
    print_report(&cli.target, &config, &files, &outcome, &output_root);
    Ok(())
}

fn run_estate(cli: &Cli) -> Result<(), GeneratorError> {
    let root = env::current_dir()
        .map_err(|error| GeneratorError::usage(format!("resolve current directory: {error}")))?
        .canonicalize()
        .map_err(|error| {
            GeneratorError::usage(format!("canonicalize current directory: {error}"))
        })?;
    let output_root = match cli.output.as_deref() {
        Some(path) => resolve_output_path(path)?,
        None => root.join("repositories"),
    };
    let mut generated = 0usize;
    for entry in ESTATE_PROFILES {
        let profile = estate_profile(entry.repository).ok_or_else(|| {
            GeneratorError::usage(format!("missing catalog profile: {}", entry.repository))
        })?;
        let config = catalog_config(profile, cli.runners);
        let files = generated_files(&config);
        let (owner, repository) = profile.repository.split_once('/').ok_or_else(|| {
            GeneratorError::usage(format!(
                "invalid catalog repository: {}",
                profile.repository
            ))
        })?;
        let destination = output_root_for_repository(&output_root, owner, repository)?;
        let outcome = write_generated(&destination, &files, cli.dry_run, cli.check, cli.force)?;
        match &outcome {
            WriteOutcome::Written { .. } | WriteOutcome::Unchanged => generated += 1,
            WriteOutcome::DryRun(changed) => {
                if !changed.is_empty() {
                    println!("{}: {}", profile.repository, display_paths(changed.iter()));
                }
            }
        }
    }
    if cli.dry_run {
        println!("Estate dry-run inspected {generated} catalog profiles");
    } else {
        println!(
            "Generated {generated} catalog profiles in {}",
            output_root.display()
        );
    }
    Ok(())
}

fn generated_files(config: &ProjectConfig) -> BTreeMap<PathBuf, String> {
    let mut files = BTreeMap::new();
    files.insert(PathBuf::from(".github/ci/project.toml"), config.toml());
    let workflow = WorkflowIr::from_config(config);
    for workflow_file in &config.workflow_files {
        let content = match workflow_file.as_str() {
            "ci-pr.yml" => Some(workflow.render_nested(WorkflowKind::PullRequest)),
            "ci-main.yml" => Some(workflow.render_nested(WorkflowKind::Main)),
            "nightly.yml" => Some(workflow.render_nested(WorkflowKind::Nightly)),
            "maintenance.yml" => Some(format!("{GENERATED_HEADER}{}", render_maintenance(config))),
            "preview.yml" => Some(render_preview(config)),
            "release.yml" => config
                .release
                .as_ref()
                .map(|release| render_release(config, release)),
            // Catalog data is code-owned; ignore no unknown runtime path and never
            // let configuration turn into an arbitrary filesystem write.
            _ => None,
        };
        if let Some(content) = content {
            files.insert(
                PathBuf::from(".github/workflows").join(workflow_file),
                content,
            );
        }
    }
    for unit in &config.units {
        files.insert(
            PathBuf::from(".github/workflows").join(nested_unit_workflow_file(unit)),
            workflow.render_nested_unit(unit, WorkflowKind::Main),
        );
    }
    files
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum PlannedAction {
    Create,
    Update,
    Delete,
    Same,
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct PlannedFile {
    path: PathBuf,
    action: PlannedAction,
    preimage: FilePreimage,
}

#[derive(Clone, Debug, Eq, PartialEq)]
enum FilePreimage {
    Missing,
    Regular {
        identity: FileIdentity,
        bytes: Box<[u8]>,
    },
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct FileIdentity {
    length: u64,
    #[cfg(unix)]
    device: u64,
    #[cfg(unix)]
    inode: u64,
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct GeneratedWritePlan {
    files: Vec<PlannedFile>,
    changed: Vec<PathBuf>,
    stale: Vec<PathBuf>,
    conflicts: Vec<PathBuf>,
    ownership_present: bool,
    ownership_needs_refresh: bool,
}

impl GeneratedWritePlan {
    fn has_drift(&self) -> bool {
        self.files
            .iter()
            .any(|file| file.action != PlannedAction::Same)
    }

    fn differences(&self) -> Vec<PathBuf> {
        self.files
            .iter()
            .filter(|file| file.action != PlannedAction::Same)
            .map(|file| file.path.clone())
            .collect()
    }
}

impl FilePreimage {
    fn bytes(&self) -> Option<&[u8]> {
        match self {
            Self::Missing => None,
            Self::Regular { bytes, .. } => Some(bytes),
        }
    }

    fn has_bytes(&self, expected: &[u8]) -> bool {
        self.bytes().is_some_and(|bytes| bytes == expected)
    }
}

enum WriteOutcome {
    Written {
        changed: Vec<PathBuf>,
        created: BTreeSet<PathBuf>,
    },
    Unchanged,
    DryRun(Vec<PathBuf>),
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct OutputStyle {
    color: bool,
}

impl OutputStyle {
    fn auto() -> Self {
        let disabled = env::var_os("NO_COLOR").is_some()
            || env::var("CLICOLOR").is_ok_and(|value| value == "0");
        let forced = env::var("CLICOLOR_FORCE").is_ok_and(|value| value != "0");
        Self {
            color: !disabled && (forced || io::stdout().is_terminal()),
        }
    }

    fn paint(self, code: &str, value: impl std::fmt::Display) -> String {
        if self.color {
            format!("\x1b[{code}m{value}\x1b[0m")
        } else {
            value.to_string()
        }
    }
}

