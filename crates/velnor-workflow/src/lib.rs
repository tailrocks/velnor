#[expect(
    clippy::too_many_lines,
    reason = "the CLI report intentionally keeps detection, topology, and file explanations together"
)]
fn render_report(
    target: &str,
    config: &ProjectConfig,
    files: &BTreeMap<PathBuf, String>,
    outcome: &WriteOutcome,
    output_root: &Path,
    style: OutputStyle,
) -> String {
    let repository = if config.repository.is_empty() {
        target
    } else {
        &config.repository
    };
    let mut output = String::new();
    let _ = writeln!(
        output,
        "{} {}",
        style.paint("1;36", "Repository"),
        repository
    );
    let _ = writeln!(
        output,
        "  source: {}\n  profile: {}\n  runners: {}",
        config.analysis.method,
        config.profile.as_str(),
        config.runners.as_str()
    );

    let _ = writeln!(output, "\n{}\n", style.paint("1;36", "Detected"));
    if config.analysis.detected.is_empty() {
        output.push_str("  (none)\n");
    } else {
        for detection in &config.analysis.detected {
            let _ = writeln!(
                output,
                "  {} {}",
                style.paint("32", "✓"),
                human_detection(detection)
            );
        }
    }

    let _ = writeln!(output, "\n{}\n", style.paint("1;36", "Execution units"));
    let mut counts = BTreeMap::<UnitKind, usize>::new();
    for unit in &config.units {
        *counts.entry(unit.kind).or_default() += 1;
    }
    for (kind, count) in counts {
        let _ = writeln!(
            output,
            "  {}: {count} job{}",
            kind.label(),
            if count == 1 { "" } else { "s" }
        );
    }
    for unit in &config.units {
        let runner = report_unit_runners(config, unit);
        let tool = unit
            .tool_version
            .as_deref()
            .map_or_else(String::new, |version| format!(" · tool={version}"));
        let _ = writeln!(
            output,
            "  - {} [{}] · root={} · runners={runner}{tool}",
            unit.id,
            unit.kind.label(),
            unit.root
        );
        let _ = writeln!(output, "    PR: {}", unit.pr_commands.join(" ; "));
        if !unit.depends_on.is_empty() {
            let _ = writeln!(output, "    needs: {}", unit.depends_on.join(", "));
        }
    }
    let dependency_edges = config
        .units
        .iter()
        .map(|unit| unit.depends_on.len())
        .sum::<usize>();
    let _ = writeln!(
        output,
        "  total: {} unit{} · {dependency_edges} dependency edge{}",
        config.units.len(),
        if config.units.len() == 1 { "" } else { "s" },
        if dependency_edges == 1 { "" } else { "s" }
    );

    let _ = writeln!(output, "\n{}\n", style.paint("1;36", "Generated files"));
    for relative in files.keys() {
        let state = generated_file_state(relative, outcome, output_root);
        let marker = match state {
            "create" => style.paint("32", "+"),
            "update" => style.paint("33", "~"),
            "unchanged" => style.paint("2", "="),
            _ => style.paint("36", "·"),
        };
        let _ = writeln!(
            output,
            "  {marker} {state:9} {:<42} {}",
            relative.display(),
            generated_file_purpose(relative)
        );
    }
    let ownership_path = Path::new(OWNERSHIP_STATE);
    let ownership_state = generated_file_state(ownership_path, outcome, output_root);
    let ownership_marker = match ownership_state {
        "create" => style.paint("32", "+"),
        "update" => style.paint("33", "~"),
        "unchanged" => style.paint("2", "="),
        _ => style.paint("36", "·"),
    };
    let _ = writeln!(
        output,
        "  {ownership_marker} {ownership_state:9} {OWNERSHIP_STATE:<42} ownership and overwrite safety state"
    );
    let _ = writeln!(output, "\n{}\n", style.paint("1;36", "Why"));
    for reason in generation_reasons(config) {
        let _ = writeln!(output, "  {} {reason}", style.paint("36", "→"));
    }
    if !config.analysis.limitations.is_empty() {
        let _ = writeln!(output, "\n{}\n", style.paint("1;36", "Boundaries"));
        for limitation in &config.analysis.limitations {
            let _ = writeln!(output, "  {} {limitation}", style.paint("33", "!"));
        }
    }
    let result = match outcome {
        WriteOutcome::Written { .. } => format!(
            "Generated {} files in {}",
            files.len() + 1,
            output_root.display()
        ),
        WriteOutcome::Unchanged => {
            format!("Generated files are current in {}", output_root.display())
        }
        WriteOutcome::DryRun(changed) => format!(
            "Dry-run: {} file{} would change in {}",
            changed.len(),
            if changed.len() == 1 { "" } else { "s" },
            output_root.display()
        ),
    };
    let _ = writeln!(output, "\n{} {}\n", style.paint("1;32", "Result"), result);
    output
}

fn report_unit_runners(config: &ProjectConfig, unit: &Unit) -> String {
    match config.runners {
        RunnerMode::Github => {
            if unit.kind == UnitKind::Swift {
                "github: macos-15".to_owned()
            } else {
                format!("github: {}", config.github_runner)
            }
        }
        RunnerMode::Velnor => {
            if unit.kind == UnitKind::Swift {
                "velnor: skipped (Apple unit requires macOS)".to_owned()
            } else {
                format!("velnor: {}", velnor_runner(&config.velnor_labels))
            }
        }
        RunnerMode::Both => {
            if unit.kind == UnitKind::Swift {
                "github: macos-15; velnor: skipped (Apple unit requires macOS)".to_owned()
            } else {
                format!(
                    "github: {}; velnor: {}",
                    config.github_runner,
                    velnor_runner(&config.velnor_labels)
                )
            }
        }
    }
}

fn generated_file_state(relative: &Path, outcome: &WriteOutcome, root: &Path) -> &'static str {
    match outcome {
        WriteOutcome::Written { changed, created } => {
            if created.contains(relative) {
                "create"
            } else if changed.iter().any(|path| path == relative) {
                "update"
            } else {
                "unchanged"
            }
        }
        WriteOutcome::DryRun(changed) if changed.iter().any(|path| path == relative) => {
            if root.join(relative).exists() {
                "update"
            } else {
                "create"
            }
        }
        WriteOutcome::Unchanged | WriteOutcome::DryRun(_) => "unchanged",
    }
}

fn generated_file_purpose(path: &Path) -> &'static str {
    match path.to_string_lossy().as_ref() {
        ".github/ci/project.toml" => "detected CI graph + binary runtime contract",
        value if value.ends_with("ci-pr.yml") => "parallel PR verification",
        value if value.ends_with("ci-main.yml") => "trusted main verification",
        value if value.ends_with("nightly.yml") => "scheduled full verification",
        value if value.ends_with("maintenance.yml") => "closed-PR cache cleanup",
        value if value.ends_with("preview.yml") => "preview artifact workflow",
        value if value.ends_with("release.yml") => "release publisher workflow",
        _ => "generated CI support file",
    }
}

fn human_detection(value: &str) -> String {
    if let Some(count) = value.strip_prefix("rust-workspace-members:") {
        return format!("Rust workspace · {count} packages");
    }
    if let Some(value) = value.strip_prefix("package-manager:")
        && let Some((manager, root)) = value.split_once(':')
    {
        return format!("{manager} package manager · {root}");
    }
    if let Some(value) = value.strip_prefix("package-script:")
        && let Some((root, script)) = value.rsplit_once(':')
    {
        return format!("package.json script `{script}` · {root}");
    }
    if let Some(root) = value.strip_prefix("package-workspace:") {
        return format!("package.json workspace · {root}");
    }
    if let Some(count) = value.strip_prefix("xcode-shared-schemes:") {
        return format!("shared Xcode schemes · {count} jobs");
    }
    value.split_once(':').map_or_else(
        || value.replace('-', " "),
        |(kind, rest)| format!("{kind}: {rest}"),
    )
}

fn generation_reasons(config: &ProjectConfig) -> Vec<String> {
    let mut reasons = Vec::new();
    if config.units.iter().any(|unit| unit.kind == UnitKind::Rust) {
        reasons.push(
            "Rust manifests become one job per crate; local dependency edges become job needs, so independent crates run in parallel.".to_owned(),
        );
    }
    if config
        .units
        .iter()
        .any(|unit| matches!(unit.kind, UnitKind::Bun | UnitKind::Node))
    {
        reasons.push(
            "package.json scripts and lockfiles select the native package manager, install mode, cache, and package job.".to_owned(),
        );
    }
    if config.units.iter().any(|unit| unit.kind == UnitKind::Swift) {
        reasons.push(
            "SwiftPM packages and shared Xcode schemes run as isolated Apple jobs on macOS; unknown schemes/destinations are not guessed.".to_owned(),
        );
    }
    reasons.push(
        "Only checked-in, statically detected evidence controls generated commands; project code and task runners are never executed.".to_owned(),
    );
    reasons.push(
        "Generated jobs invoke `velnor-workflow run` directly; the checked-in TOML remains the runtime contract for planning, execution, policy, and release commands.".to_owned(),
    );
    reasons
}

fn write_generated(
    root: &Path,
    files: &BTreeMap<PathBuf, String>,
    dry_run: bool,
    check: bool,
    force: bool,
) -> Result<WriteOutcome, GeneratorError> {
    let plan = plan_generated_write(root, files)?;
    apply_generated_write_plan(root, files, dry_run, check, force, &plan)
}

fn plan_generated_write(
    root: &Path,
    files: &BTreeMap<PathBuf, String>,
) -> Result<GeneratedWritePlan, GeneratorError> {
    reject_symlinked_output_root(root)?;
    reject_managed_symlink_ancestors(root)?;
    let preimages = files
        .keys()
        .map(|relative| {
            capture_file_preimage(&root.join(relative), relative)
                .map(|preimage| (relative.clone(), preimage))
        })
        .collect::<Result<BTreeMap<_, _>, _>>()?;
    let ownership_path = PathBuf::from(OWNERSHIP_STATE);
    let ownership_preimage = capture_file_preimage(&root.join(&ownership_path), &ownership_path)?;
    let ownership = parse_ownership_state(root, &ownership_preimage)?;
    let ownership_needs_refresh =
        verify_generated_ownership(files, ownership.as_ref(), &preimages)?
            || !ownership_preimage.has_bytes(ownership_state_content(files).as_bytes());
    let stale_files = stale_owned_files(root, files, ownership.as_ref())?;
    let stale = stale_files
        .iter()
        .map(|file| file.path.clone())
        .collect::<Vec<_>>();
    let changed: Vec<PathBuf> = files
        .iter()
        .filter(|(relative, wanted)| {
            preimages
                .get(*relative)
                .is_none_or(|preimage| !preimage.has_bytes(wanted.as_bytes()))
        })
        .map(|(relative, _)| relative.clone())
        .collect::<Vec<_>>();
    let legacy = direct_legacy_workflows(root)?;
    let conflicts = changed
        .iter()
        .filter(|relative| root.join(relative).exists())
        .cloned()
        .collect::<Vec<_>>();

    // This generator owns CI only. A non-generated workflow can be a release,
    // deployment, or an otherwise repository-specific control plane; neither
    // its filename nor its contents are enough to safely migrate it here.
    // Refuse before `--force` can archive/remove an active publisher.
    if !legacy.is_empty() {
        return Err(GeneratorError::usage(format!(
            "existing workflows are outside this CI-only generator and will not be migrated, archived, or removed: {}; preserve them and use a separately reviewed release migration",
            display_paths(legacy.iter()),
        )));
    }
    let mut planned_files = files
        .keys()
        .map(|path| {
            let action = if changed.contains(path) {
                if root.join(path).exists() {
                    PlannedAction::Update
                } else {
                    PlannedAction::Create
                }
            } else {
                PlannedAction::Same
            };
            PlannedFile {
                path: path.clone(),
                action,
                preimage: preimages
                    .get(path)
                    .cloned()
                    .unwrap_or(FilePreimage::Missing),
            }
        })
        .collect::<Vec<_>>();
    planned_files.extend(stale_files);
    let ownership_action = if ownership.is_none() {
        PlannedAction::Create
    } else if ownership_needs_refresh || !changed.is_empty() || !stale.is_empty() {
        PlannedAction::Update
    } else {
        PlannedAction::Same
    };
    planned_files.push(PlannedFile {
        path: ownership_path,
        action: ownership_action,
        preimage: ownership_preimage,
    });
    Ok(GeneratedWritePlan {
        files: planned_files,
        changed,
        stale,
        conflicts,
        ownership_present: ownership.is_some(),
        ownership_needs_refresh,
    })
}

fn apply_generated_write_plan(
    root: &Path,
    files: &BTreeMap<PathBuf, String>,
    dry_run: bool,
    check: bool,
    force: bool,
    plan: &GeneratedWritePlan,
) -> Result<WriteOutcome, GeneratorError> {
    validate_plan_preimages(root, plan)?;
    if check {
        if !plan.has_drift() {
            return Ok(WriteOutcome::Unchanged);
        }
        if !plan.ownership_present && plan.changed.is_empty() && plan.stale.is_empty() {
            return Err(GeneratorError::usage(
                "generated files have no ownership state; rerun generate once to adopt the exact generated output",
            ));
        }
        return Err(GeneratorError::usage(format!(
            "generated files differ: {}; rerun generate",
            display_paths(plan.differences().iter()),
        )));
    }
    if dry_run {
        return Ok(WriteOutcome::DryRun(plan.differences()));
    }
    if !plan.conflicts.is_empty() && !force {
        return Err(GeneratorError::usage(format!(
            "would overwrite generated files: {}; rerun with --force after review",
            display_paths(plan.conflicts.iter()),
        )));
    }
    if !plan.has_drift() {
        return Ok(WriteOutcome::Unchanged);
    }
    let _generation_lock = GenerationLock::acquire(root)?;
    validate_plan_preimages(root, plan)?;
    // A pre-state version is safe to adopt only when every existing generated
    // file exactly matches this renderer's output. `verify_generated_ownership`
    // rejects any divergent file before this point, including under `--force`.
    if plan.changed.is_empty()
        && plan.stale.is_empty()
        && (!plan.ownership_present || plan.ownership_needs_refresh)
    {
        return apply_ownership_refresh(root, files, plan);
    }
    let created = plan
        .files
        .iter()
        .filter(|file| file.action == PlannedAction::Create)
        .map(|file| file.path.clone())
        .collect::<BTreeSet<_>>();
    let mut written = plan.changed.clone();
    written.extend(plan.stale.iter().cloned());
    let ownership_path = PathBuf::from(OWNERSHIP_STATE);
    if !written.contains(&ownership_path) {
        written.push(ownership_path.clone());
    }
    for relative in &plan.changed {
        let Some(content) = files.get(relative) else {
            return Err(GeneratorError::usage(format!(
                "generated plan references an unknown file: {}",
                relative.display()
            )));
        };
        let planned = plan
            .files
            .iter()
            .find(|file| &file.path == relative)
            .ok_or_else(|| GeneratorError::usage("generated plan has no file preimage"))?;
        write_reviewed_file(&root.join(relative), relative, content, &planned.preimage)?;
    }
    for relative in &plan.stale {
        let planned = plan
            .files
            .iter()
            .find(|file| &file.path == relative)
            .ok_or_else(|| GeneratorError::usage("generated plan has no stale-file preimage"))?;
        delete_reviewed_file(&root.join(relative), relative, &planned.preimage)?;
    }
    let ownership_file = plan
        .files
        .iter()
        .find(|file| file.path == ownership_path)
        .ok_or_else(|| GeneratorError::usage("generated plan has no ownership preimage"))?;
    write_reviewed_file(
        &root.join(&ownership_path),
        &ownership_path,
        &ownership_state_content(files),
        &ownership_file.preimage,
    )?;
    Ok(WriteOutcome::Written {
        changed: written,
        created,
    })
}

fn apply_ownership_refresh(
    root: &Path,
    files: &BTreeMap<PathBuf, String>,
    plan: &GeneratedWritePlan,
) -> Result<WriteOutcome, GeneratorError> {
    let ownership_path = PathBuf::from(OWNERSHIP_STATE);
    let ownership_file = plan
        .files
        .iter()
        .find(|file| file.path == ownership_path)
        .ok_or_else(|| GeneratorError::usage("generated plan has no ownership preimage"))?;
    let created = (ownership_file.action == PlannedAction::Create)
        .then(|| ownership_path.clone())
        .into_iter()
        .collect();
    write_reviewed_file(
        &root.join(&ownership_path),
        &ownership_path,
        &ownership_state_content(files),
        &ownership_file.preimage,
    )?;
    Ok(WriteOutcome::Written {
        changed: vec![ownership_path],
        created,
    })
}

fn reject_symlinked_output_root(root: &Path) -> Result<(), GeneratorError> {
    match fs::symlink_metadata(root) {
        Ok(metadata) if metadata.file_type().is_symlink() => Err(GeneratorError::usage(format!(
            "refusing symlinked output root: {}",
            root.display()
        ))),
        Ok(metadata) if !metadata.is_dir() => Err(GeneratorError::usage(format!(
            "output root is not a directory: {}",
            root.display()
        ))),
        Ok(_) => Ok(()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(GeneratorError::io("inspect output root", root, &error)),
    }
}

/// Generated paths are intentionally constrained beneath the target repository.
/// Refuse a symlinked managed directory instead of letting normal filesystem
/// resolution redirect a write outside that repository.
fn reject_managed_symlink_ancestors(root: &Path) -> Result<(), GeneratorError> {
    for relative in [".github", ".github/ci", ".github/workflows"] {
        let path = root.join(relative);
        match fs::symlink_metadata(&path) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(GeneratorError::usage(format!(
                    "refusing symlinked managed directory: {}",
                    path.display()
                )));
            }
            Ok(metadata) if !metadata.is_dir() => {
                return Err(GeneratorError::usage(format!(
                    "managed path is not a directory: {}",
                    path.display()
                )));
            }
            Ok(_) => (),
            Err(error) if error.kind() == io::ErrorKind::NotFound => (),
            Err(error) => {
                return Err(GeneratorError::io(
                    "inspect managed directory",
                    &path,
                    &error,
                ));
            }
        }
    }
    Ok(())
}

fn capture_file_preimage(path: &Path, relative: &Path) -> Result<FilePreimage, GeneratorError> {
    let observed = match fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            return Ok(FilePreimage::Missing);
        }
        Err(error) => return Err(GeneratorError::io("inspect generated file", path, &error)),
    };
    if !observed.file_type().is_file() {
        return Err(GeneratorError::usage(format!(
            "refusing non-regular generated file: {}",
            relative.display()
        )));
    }
    let observed_identity = file_identity(&observed);
    let mut file = fs::File::open(path)
        .map_err(|error| GeneratorError::io("open generated file", path, &error))?;
    let opened_identity = file
        .metadata()
        .map(|metadata| file_identity(&metadata))
        .map_err(|error| GeneratorError::io("inspect opened generated file", path, &error))?;
    if opened_identity != observed_identity {
        return Err(GeneratorError::usage(format!(
            "generated file changed during preflight: {}",
            relative.display()
        )));
    }
    let mut bytes = Vec::new();
    file.read_to_end(&mut bytes)
        .map_err(|error| GeneratorError::io("read generated file", path, &error))?;
    let final_identity = file
        .metadata()
        .map(|metadata| file_identity(&metadata))
        .map_err(|error| GeneratorError::io("reinspect generated file", path, &error))?;
    if final_identity != observed_identity || final_identity.length != bytes.len() as u64 {
        return Err(GeneratorError::usage(format!(
            "generated file changed during preflight: {}",
            relative.display()
        )));
    }
    Ok(FilePreimage::Regular {
        identity: observed_identity,
        bytes: bytes.into_boxed_slice(),
    })
}

fn file_identity(metadata: &fs::Metadata) -> FileIdentity {
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt as _;

        FileIdentity {
            length: metadata.len(),
            device: metadata.dev(),
            inode: metadata.ino(),
        }
    }
    #[cfg(not(unix))]
    {
        FileIdentity {
            length: metadata.len(),
        }
    }
}

fn validate_plan_preimages(root: &Path, plan: &GeneratedWritePlan) -> Result<(), GeneratorError> {
    reject_symlinked_output_root(root)?;
    reject_managed_symlink_ancestors(root)?;
    let mut changed = Vec::new();
    for file in &plan.files {
        let current = capture_file_preimage(&root.join(&file.path), &file.path)?;
        if current != file.preimage {
            changed.push(file.path.clone());
        }
    }
    if changed.is_empty() {
        return Ok(());
    }
    Err(GeneratorError::usage(format!(
        "generated files changed after preflight: {}; review again",
        display_paths(changed.iter()),
    )))
}

/// Verify that an existing generated file still matches the last generated
/// bytes before allowing a replacement. The state is accidental-loss
/// protection, not a security boundary: repository writers can alter it.
/// Returns whether exact current output needs its state refreshed.
fn verify_generated_ownership(
    files: &BTreeMap<PathBuf, String>,
    ownership: Option<&BTreeMap<PathBuf, u64>>,
    preimages: &BTreeMap<PathBuf, FilePreimage>,
) -> Result<bool, GeneratorError> {
    let mut needs_refresh = false;
    for (relative, wanted) in files {
        let Some(preimage) = preimages.get(relative) else {
            continue;
        };
        let Some(current) = preimage.bytes() else {
            continue;
        };
        match ownership.and_then(|state| state.get(relative)) {
            Some(digest) if *digest == content_digest_bytes(current) => (),
            Some(_) => {
                if current == wanted.as_bytes() {
                    needs_refresh = true;
                    continue;
                }
                return Err(GeneratorError::usage(format!(
                    "refusing to overwrite manually modified generated file: {}; restore its recorded generated content or reconcile it manually",
                    relative.display()
                )));
            }
            None if current == wanted.as_bytes() => (),
            None => {
                return Err(GeneratorError::usage(format!(
                    "cannot prove ownership of existing generated file: {}; it differs from current output and has no recorded state",
                    relative.display()
                )));
            }
        }
    }
    Ok(needs_refresh)
}

fn stale_owned_files(
    root: &Path,
    files: &BTreeMap<PathBuf, String>,
    ownership: Option<&BTreeMap<PathBuf, u64>>,
) -> Result<Vec<PlannedFile>, GeneratorError> {
    let Some(ownership) = ownership else {
        return Ok(Vec::new());
    };
    let mut stale = Vec::new();
    for (relative, expected) in ownership {
        if files.contains_key(relative) {
            continue;
        }
        let path = root.join(relative);
        if fs::symlink_metadata(&path).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
            return Err(GeneratorError::usage(format!(
                "refusing to remove symlinked stale generated file: {}",
                path.display()
            )));
        }
        let preimage = capture_file_preimage(&path, relative)?;
        let Some(current) = preimage.bytes() else {
            continue;
        };
        if content_digest_bytes(current) != *expected {
            return Err(GeneratorError::usage(format!(
                "stale generated file was manually modified: {}",
                relative.display()
            )));
        }
        stale.push(PlannedFile {
            path: relative.clone(),
            action: PlannedAction::Delete,
            preimage,
        });
    }
    Ok(stale)
}

fn parse_ownership_state(
    root: &Path,
    preimage: &FilePreimage,
) -> Result<Option<BTreeMap<PathBuf, u64>>, GeneratorError> {
    let path = root.join(OWNERSHIP_STATE);
    let Some(bytes) = preimage.bytes() else {
        return Ok(None);
    };
    let content = std::str::from_utf8(bytes).map_err(|_| {
        GeneratorError::usage(format!(
            "invalid generated ownership state: {}",
            path.display()
        ))
    })?;
    let mut lines = content.lines();
    if lines.next() != Some(OWNERSHIP_STATE_HEADER.trim_end()) || lines.next() != Some("schema = 1")
    {
        return Err(GeneratorError::usage(format!(
            "invalid generated ownership state: {}",
            path.display()
        )));
    }
    let mut state = BTreeMap::new();
    for line in lines {
        let (raw_path, raw_digest) = line.split_once('\t').ok_or_else(|| {
            GeneratorError::usage(format!(
                "invalid generated ownership state: {}",
                path.display()
            ))
        })?;
        let relative = managed_relative_path(raw_path)?;
        let digest = u64::from_str_radix(raw_digest, 16).map_err(|_| {
            GeneratorError::usage(format!(
                "invalid generated ownership state: {}",
                path.display()
            ))
        })?;
        if state.insert(relative, digest).is_some() {
            return Err(GeneratorError::usage(format!(
                "duplicate generated ownership state entry: {}",
                path.display()
            )));
        }
    }
    Ok(Some(state))
}

#[cfg(test)]
fn write_ownership_state(
    root: &Path,
    files: &BTreeMap<PathBuf, String>,
) -> Result<(), GeneratorError> {
    atomic_write(&root.join(OWNERSHIP_STATE), &ownership_state_content(files))
}

fn ownership_state_content(files: &BTreeMap<PathBuf, String>) -> String {
    let mut content = String::from(OWNERSHIP_STATE_HEADER);
    content.push_str("schema = 1\n");
    for (relative, generated) in files {
        let _ = writeln!(
            content,
            "{}\t{:016x}",
            relative.display(),
            content_digest(generated)
        );
    }
    content
}

fn managed_relative_path(value: &str) -> Result<PathBuf, GeneratorError> {
    let path = Path::new(value);
    if path
        .components()
        .all(|component| matches!(component, Component::Normal(_)))
        && value.starts_with(".github/")
    {
        return Ok(path.to_path_buf());
    }
    Err(GeneratorError::usage(
        "generated ownership state contains an unsafe path",
    ))
}

fn content_digest(content: &str) -> u64 {
    content_digest_bytes(content.as_bytes())
}

fn content_digest_bytes(content: &[u8]) -> u64 {
    // Stable FNV-1a; this catches accidental edits without a dependency.
    content
        .iter()
        .fold(0xcbf2_9ce4_8422_2325_u64, |hash, byte| {
            (hash ^ u64::from(*byte)).wrapping_mul(0x0000_0100_0000_01b3)
        })
}

fn display_paths<'a>(paths: impl Iterator<Item = &'a PathBuf>) -> String {
    paths
        .map(|path| path.display().to_string())
        .collect::<Vec<_>>()
        .join(", ")
}

fn direct_legacy_workflows(root: &Path) -> Result<Vec<PathBuf>, GeneratorError> {
    let workflows = root.join(".github/workflows");
    if !workflows.exists() {
        return Ok(Vec::new());
    }
    let entries = fs::read_dir(&workflows)
        .map_err(|error| GeneratorError::io("read workflows", &workflows, &error))?;
    let mut legacy = Vec::new();
    for entry in entries {
        let entry =
            entry.map_err(|error| GeneratorError::io("read workflow entry", &workflows, &error))?;
        let path = entry.path();
        let file_type = entry
            .file_type()
            .map_err(|error| GeneratorError::io("read workflow type", &path, &error))?;
        let extension = path.extension().and_then(|value| value.to_str());
        let generated_ci = fs::read_to_string(&path).is_ok_and(|content| {
            content.starts_with(GENERATED_HEADER)
                && path.file_name().is_some_and(|name| {
                    name.to_str().is_some_and(|name| {
                        name == "ci.yml"
                            || name.starts_with("ci-")
                            || matches!(
                                name,
                                "maintenance.yml" | "nightly.yml" | "preview.yml" | "release.yml"
                            )
                    })
                })
        });
        if file_type.is_file() && matches!(extension, Some("yml" | "yaml")) && !generated_ci {
            legacy.push(
                path.strip_prefix(root)
                    .map_err(|error| {
                        GeneratorError::usage(format!("make workflow path relative: {error}"))
                    })?
                    .to_path_buf(),
            );
        }
    }
    legacy.sort();
    Ok(legacy)
}

struct GenerationLock {
    _directory: fs::File,
}

impl GenerationLock {
    fn acquire(root: &Path) -> Result<Self, GeneratorError> {
        reject_symlinked_output_root(root)?;
        fs::create_dir_all(root)
            .map_err(|error| GeneratorError::io("create output root", root, &error))?;
        reject_managed_symlink_ancestors(root)?;
        let directory = fs::File::open(root)
            .map_err(|error| GeneratorError::io("open output root for locking", root, &error))?;
        match directory.try_lock() {
            Ok(()) => (),
            Err(fs::TryLockError::WouldBlock) => {
                return Err(GeneratorError::usage(
                    "another generation is in progress; retry after it finishes",
                ));
            }
            Err(fs::TryLockError::Error(error)) => {
                return Err(GeneratorError::io(
                    "lock output root for generation",
                    root,
                    &error,
                ));
            }
        }
        Ok(Self {
            _directory: directory,
        })
    }
}

fn write_reviewed_file(
    path: &Path,
    relative: &Path,
    content: &str,
    expected: &FilePreimage,
) -> Result<(), GeneratorError> {
    write_reviewed_file_observed(path, relative, content, expected, |_| Ok(()))
}

fn write_reviewed_file_observed<F>(
    path: &Path,
    relative: &Path,
    content: &str,
    expected: &FilePreimage,
    before_replace: F,
) -> Result<(), GeneratorError>
where
    F: FnOnce(&Path) -> Result<(), GeneratorError>,
{
    let current = capture_file_preimage(path, relative)?;
    if &current != expected {
        return Err(preimage_changed(relative));
    }
    let staged = stage_generated_file(path, content)?;
    match expected {
        FilePreimage::Missing => {
            if let Err(error) = fs::hard_link(&staged, path) {
                let _ = fs::remove_file(&staged);
                if error.kind() == io::ErrorKind::AlreadyExists {
                    return Err(preimage_changed(relative));
                }
                return Err(GeneratorError::io(
                    "install new generated file",
                    path,
                    &error,
                ));
            }
            fs::remove_file(&staged)
                .map_err(|error| GeneratorError::io("remove staged file", &staged, &error))?;
            Ok(())
        }
        FilePreimage::Regular { .. } => {
            let (backup_dir, backup) = reserve_backup_path(path)?;
            if let Err(error) = fs::hard_link(path, &backup) {
                let _ = fs::remove_file(&staged);
                let _ = fs::remove_dir(&backup_dir);
                return Err(GeneratorError::io(
                    "back up reviewed generated file",
                    path,
                    &error,
                ));
            }
            let backed_up = match capture_file_preimage(&backup, relative) {
                Ok(backed_up) => backed_up,
                Err(error) => {
                    let _ = fs::remove_file(&backup);
                    let _ = fs::remove_dir(&backup_dir);
                    let _ = fs::remove_file(&staged);
                    return Err(error);
                }
            };
            let live_matches =
                capture_file_preimage(path, relative).is_ok_and(|current| &current == expected);
            if &backed_up != expected || !live_matches {
                let _ = fs::remove_file(&backup);
                let _ = fs::remove_dir(&backup_dir);
                let _ = fs::remove_file(&staged);
                return Err(preimage_changed(relative));
            }
            if let Err(error) = before_replace(path) {
                let _ = fs::remove_file(&backup);
                let _ = fs::remove_dir(&backup_dir);
                let _ = fs::remove_file(&staged);
                return Err(error);
            }
            if let Err(error) = fs::rename(&staged, path) {
                let _ = fs::remove_file(&staged);
                let _ = fs::remove_file(&backup);
                let _ = fs::remove_dir(&backup_dir);
                return Err(GeneratorError::io(
                    "atomically replace reviewed generated file",
                    path,
                    &error,
                ));
            }
            // The atomic rename is the commit point. Cleanup cannot turn a
            // successful replacement into a reported failure that skips the
            // ownership-state update; a leftover backup remains recoverable.
            let _ = fs::remove_file(&backup);
            let _ = fs::remove_dir(&backup_dir);
            Ok(())
        }
    }
}

fn delete_reviewed_file(
    path: &Path,
    relative: &Path,
    expected: &FilePreimage,
) -> Result<(), GeneratorError> {
    if matches!(expected, FilePreimage::Missing) {
        return Err(preimage_changed(relative));
    }
    let current = capture_file_preimage(path, relative)?;
    if &current != expected {
        return Err(preimage_changed(relative));
    }
    let (backup_dir, backup) = reserve_backup_path(path)?;
    if let Err(error) = fs::rename(path, &backup) {
        let _ = fs::remove_dir(&backup_dir);
        return Err(GeneratorError::io(
            "reserve stale generated file",
            path,
            &error,
        ));
    }
    let moved = match capture_file_preimage(&backup, relative) {
        Ok(moved) => moved,
        Err(error) => {
            restore_reviewed_backup(path, &backup, &backup_dir)?;
            return Err(error);
        }
    };
    if &moved != expected {
        restore_reviewed_backup(path, &backup, &backup_dir)?;
        return Err(preimage_changed(relative));
    }
    // Removal of the reviewed pathname is committed. Keep ownership-state
    // progress monotonic even if cleanup leaves a recoverable hidden backup.
    let _ = fs::remove_file(&backup);
    let _ = fs::remove_dir(&backup_dir);
    Ok(())
}

fn stage_generated_file(path: &Path, content: &str) -> Result<PathBuf, GeneratorError> {
    let parent = path
        .parent()
        .ok_or_else(|| GeneratorError::usage(format!("path has no parent: {}", path.display())))?;
    fs::create_dir_all(parent)
        .map_err(|error| GeneratorError::io("create output directory", parent, &error))?;
    let filename = path
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or_else(|| GeneratorError::usage("invalid generated output filename"))?;
    for attempt in 0..16_u8 {
        let staged = parent.join(format!(
            ".{filename}.stage-{}-{}-{attempt}",
            std::process::id(),
            unique_suffix()
        ));
        match fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&staged)
        {
            Ok(mut file) => {
                file.write_all(content.as_bytes()).map_err(|error| {
                    GeneratorError::io("write staged generated file", &staged, &error)
                })?;
                file.sync_all().map_err(|error| {
                    GeneratorError::io("sync staged generated file", &staged, &error)
                })?;
                return Ok(staged);
            }
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => (),
            Err(error) => {
                return Err(GeneratorError::io(
                    "create staged generated file",
                    &staged,
                    &error,
                ));
            }
        }
    }
    Err(GeneratorError::usage(format!(
        "could not reserve a staged file for {}",
        path.display()
    )))
}

fn reserve_backup_path(path: &Path) -> Result<(PathBuf, PathBuf), GeneratorError> {
    let parent = path
        .parent()
        .ok_or_else(|| GeneratorError::usage(format!("path has no parent: {}", path.display())))?;
    let filename = path
        .file_name()
        .ok_or_else(|| GeneratorError::usage("invalid generated output filename"))?;
    for attempt in 0..16_u8 {
        let directory = parent.join(format!(
            ".velnor-workflow-backup-{}-{}-{attempt}",
            std::process::id(),
            unique_suffix()
        ));
        match fs::create_dir(&directory) {
            Ok(()) => return Ok((directory.clone(), directory.join(filename))),
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => (),
            Err(error) => {
                return Err(GeneratorError::io(
                    "reserve generated backup directory",
                    &directory,
                    &error,
                ));
            }
        }
    }
    Err(GeneratorError::usage(format!(
        "could not reserve a backup for {}",
        path.display()
    )))
}

fn restore_reviewed_backup(
    path: &Path,
    backup: &Path,
    backup_dir: &Path,
) -> Result<(), GeneratorError> {
    fs::hard_link(backup, path).map_err(|error| {
        GeneratorError::usage(format!(
            "generated file changed concurrently; preserved reviewed bytes at {} and refused to overwrite {}: {error}",
            backup.display(),
            path.display()
        ))
    })?;
    fs::remove_file(backup)
        .map_err(|error| GeneratorError::io("remove restored backup", backup, &error))?;
    fs::remove_dir(backup_dir)
        .map_err(|error| GeneratorError::io("remove restored backup directory", backup_dir, &error))
}

fn preimage_changed(relative: &Path) -> GeneratorError {
    GeneratorError::usage(format!(
        "generated file changed after preflight: {}; review again",
        relative.display()
    ))
}

