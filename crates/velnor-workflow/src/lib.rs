    let mut needs = vec![
        "plan".to_owned(),
        "policy".to_owned(),
        unit_group_job_id(unit),
    ];
    needs.extend(
        unit.depends_on
            .iter()
            .map(|dependency| unit_job_id(lane, dependency)),
    );
