/// Evidence produced by the read-only repository analysis pass.
///
/// This deliberately records both detected capabilities and the boundary of
/// what static inspection cannot prove. The renderer may consume positive
/// evidence, but it must not turn an unknown release or trust contract into a
/// guessed workflow.
#[derive(Clone, Debug, Eq, PartialEq)]
struct AnalysisSummary {
    method: String,
    detected: Vec<String>,
    limitations: Vec<String>,
}

/// Generated, editable CI policy. It is intentionally not tied to a repository name.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ProjectConfig {
    repository: String,
    profile: RepositoryProfile,
    analysis: AnalysisSummary,
    verified: bool,
    workflow_files: Vec<String>,
    notes: Vec<String>,
    default_branch: String,
    runners: RunnerMode,
    github_runner: String,
    velnor_labels: Vec<String>,
    release_enabled: bool,
    release_reason: String,
    release: Option<ReleaseSpec>,
    units: Vec<Unit>,
}

fn default_workflow_files() -> Vec<String> {
    vec![
        "ci-pr.yml".to_owned(),
        "ci-main.yml".to_owned(),
        "nightly.yml".to_owned(),
        "maintenance.yml".to_owned(),
    ]
}

impl ProjectConfig {
    fn toml(&self) -> String {
        let mut output = String::from(GENERATED_HEADER);
        output.push_str("schema = 1\n");
        if !self.repository.is_empty() {
            write_toml_string(&mut output, "repository", &self.repository);
        }
        write_toml_string(&mut output, "profile", self.profile.as_str());
        let _ = writeln!(output, "verified = {}", self.verified);
        write_toml_string(&mut output, "default_branch", &self.default_branch);
        write_toml_string(&mut output, "runners", self.runners.as_str());
        output.push('\n');
        output.push_str("[analysis]\n");
        write_toml_string(&mut output, "method", &self.analysis.method);
        write_toml_array(&mut output, "detected", &self.analysis.detected);
        write_toml_array(&mut output, "limitations", &self.analysis.limitations);
        output.push('\n');
        output.push_str("[workflow]\n");
        write_toml_string(&mut output, "github_runner", &self.github_runner);
        write_toml_array(&mut output, "velnor_labels", &self.velnor_labels);
        let generated_workflows = workflow_file_names(self);
        write_toml_array(&mut output, "files", &generated_workflows);
        if !self.notes.is_empty() {
            write_toml_array(&mut output, "notes", &self.notes);
        }
        output.push('\n');
        output.push_str("[release]\n");
        let _ = writeln!(output, "enabled = {}", self.release_enabled);
        write_toml_string(&mut output, "reason", &self.release_reason);
        if let Some(release) = &self.release {
            write_toml_string(&mut output, "kind", release.kind.as_str());
            if !release.package.is_empty() {
                write_toml_string(&mut output, "package", &release.package);
            }
            write_toml_array(&mut output, "packages", &release.packages);
            if !release.binary.is_empty() {
                write_toml_string(&mut output, "binary", &release.binary);
            }
            write_toml_array(&mut output, "targets", &release.targets);
            if !release.image.is_empty() {
                write_toml_string(&mut output, "image", &release.image);
            }
            if !release.source_repository.is_empty() {
                write_toml_string(&mut output, "source_repository", &release.source_repository);
            }
            if !release.consumer_repository.is_empty() {
                write_toml_string(
                    &mut output,
                    "consumer_repository",
                    &release.consumer_repository,
                );
            }
            if !release.artifact_path.is_empty() {
                write_toml_string(&mut output, "artifact_path", &release.artifact_path);
            }
            if !release.description.is_empty() {
                write_toml_string(&mut output, "description", &release.description);
            }
        }
        for unit in &self.units {
            output.push_str("\n[[unit]]\n");
            write_toml_string(&mut output, "id", &unit.id);
            write_toml_string(&mut output, "label", &unit.label);
            write_toml_string(&mut output, "kind", unit.kind.id_prefix());
            write_toml_string(&mut output, "root", &unit.root);
            write_toml_array(&mut output, "watch", &unit.watch);
            write_toml_array(&mut output, "pr_commands", &unit.pr_commands);
            write_toml_array(&mut output, "full_commands", &unit.full_commands);
            if !unit.depends_on.is_empty() {
                write_toml_array(&mut output, "depends_on", &unit.depends_on);
            }
            if let Some(version) = &unit.tool_version {
                write_toml_string(&mut output, "tool_version", version);
            }
            if let Some(cache) = &unit.cache {
                output.push_str("[unit.cache]\n");
                write_toml_array(&mut output, "key_files", &cache.key_files);
                write_toml_array(&mut output, "paths", &cache.paths);
            }
        }
        output
    }
}

fn write_toml_string(output: &mut String, name: &str, value: &str) {
    let escaped = value.replace('\\', "\\\\").replace('"', "\\\"");
    let _ = writeln!(output, "{name} = \"{escaped}\"");
}

fn write_toml_array(output: &mut String, name: &str, values: &[String]) {
    let values = values
        .iter()
        .map(|value| format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\"")))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(output, "{name} = [{values}]");
}

/// Scan a local repository without evaluating project-controlled files.
///
/// # Errors
/// Returns filesystem errors with the affected path.
#[expect(
    clippy::too_many_lines,
    reason = "the scan pass keeps generic detectors in one auditable pipeline"
)]
pub fn scan_repository(root: &Path, runners: RunnerMode) -> Result<ProjectConfig, GeneratorError> {
    let files = repository_files(root)?;
    let file_set: BTreeSet<String> = files.iter().cloned().collect();
    let mut units = Vec::new();
    let mut analysis = AnalysisSummary {
        method: "static-filesystem-and-manifest-inspection".to_owned(),
        detected: Vec::new(),
        limitations: vec![
            "Project code, build scripts, task runners, and commands are never executed during analysis.".to_owned(),
            "Release, signing, registry, deployment, branch-protection, and runner-capability contracts remain explicit manual inputs.".to_owned(),
        ],
    };

    let cargo_manifests = files_named(&files, "Cargo.toml");
    if !cargo_manifests.is_empty() {
        let rust = analyze_rust_manifests(root, &files, &file_set, &cargo_manifests)?;
        units.extend(rust.units);
        analysis.detected.extend(rust.detected);
        analysis.limitations.extend(rust.limitations);
    }

    if file_set.contains("deny.toml") || file_set.contains(".cargo/deny.toml") {
        analysis.detected.push("cargo-deny-policy".to_owned());
    }
    if file_set.contains(".config/nextest.toml") || file_set.contains("nextest.toml") {
        analysis.detected.push("cargo-nextest-policy".to_owned());
    }
    if file_set.contains("renovate.json") || root.join(".github/renovate.json").is_file() {
        analysis.detected.push("renovate-configuration".to_owned());
        analysis.limitations.push(
            "Renovate credentials, runner placement, and write permissions cannot be inferred from repository files.".to_owned(),
        );
    }

    let gradle_roots = gradle_roots(&file_set);
    for root in gradle_roots {
        let prefix = path_prefix(&root);
        let command_prefix = shell_change_dir(&root);
        let gradle = if file_set.contains(&join_repo_path(&root, "gradlew")) {
            "./gradlew"
        } else {
            "gradle"
        };
        units.push(unit(
            UnitKind::Gradle,
            &root,
            vec![
                format!("{prefix}**/*.gradle"),
                format!("{prefix}**/*.gradle.kts"),
                format!("{prefix}gradle/**"),
                format!("{prefix}src/**"),
            ],
            vec![format!("{command_prefix}{gradle} check --no-daemon")],
            Some(CacheSpec {
                key_files: vec![
                    join_repo_path(&root, "gradle/wrapper/gradle-wrapper.properties"),
                    join_repo_path(&root, "gradle/libs.versions.toml"),
                ],
                paths: vec![
                    "~/.gradle/caches".to_owned(),
                    "~/.gradle/wrapper".to_owned(),
                ],
            }),
        ));
    }

    let package_manifests = files_named(&files, "package.json");
    let mut package_units = Vec::<(String, String, BTreeSet<String>, String)>::new();
    let mut package_id_counts = BTreeMap::new();
    for package_root in roots_for_manifests(&package_manifests) {
        let prefix = path_prefix(&package_root);
        let manifest = join_repo_path(&package_root, "package.json");
        let contents = fs::read_to_string(root.join(&manifest)).map_err(|error| {
            GeneratorError::io("read package manifest", &root.join(&manifest), &error)
        })?;
        let Some(facts) = parse_package_json(root, &package_root, &contents, &file_set)? else {
            analysis.limitations.push(format!(
                "Skipped {manifest}: package manager is unsupported or unresolved; supported package managers are Bun and npm."
            ));
            continue;
        };
        let manager_lockfile = package_lockfile_path(&package_root, facts.manager, &file_set);
        let kind = if facts.manager == PackageManager::Bun {
            UnitKind::Bun
        } else {
            UnitKind::Node
        };
        analysis.detected.push(format!(
            "package-manager:{}:{}",
            facts.manager.detected(),
            package_root
        ));
        if facts.workspace_root {
            analysis
                .detected
                .push(format!("package-workspace:{package_root}"));
        }
        for script in ["lint", "typecheck", "build", "test"] {
            if facts.scripts.contains(script) {
                analysis
                    .detected
                    .push(format!("package-script:{package_root}:{script}"));
            }
        }
        if !facts.scripts.contains("test") {
            analysis.limitations.push(format!(
                "No test script is declared in {manifest}; no package test command was invented."
            ));
        }
        if manager_lockfile.is_none() {
            analysis.limitations.push(format!(
                "No {} lockfile is present for {manifest}; dependency installation is intentionally unlocked.",
                facts.manager.detected()
            ));
        }
        let lockfiles = ["bun.lock", "bun.lockb", "package-lock.json"]
            .into_iter()
            .filter(|lockfile| file_set.contains(&join_repo_path(&package_root, lockfile)))
            .count();
        if lockfiles > 1 {
            analysis.limitations.push(format!(
                "Multiple package lockfiles are present under {package_root}; the detected manager chooses one, review the package boundary."
            ));
        }
        let commands = package_commands(&package_root, &facts, manager_lockfile.is_some());
        let mut package_watch = vec![
            manifest.clone(),
            format!("{prefix}**/*.js"),
            format!("{prefix}**/*.jsx"),
            format!("{prefix}**/*.ts"),
            format!("{prefix}**/*.tsx"),
            format!("{prefix}**/*.json"),
            join_repo_path(&package_root, "bun.lock"),
            join_repo_path(&package_root, "bun.lockb"),
            join_repo_path(&package_root, "package-lock.json"),
        ];
        if let Some(lockfile) = &manager_lockfile {
            package_watch.push(lockfile.clone());
        }
        let package_cache = manager_lockfile.as_ref().map(|manager_lockfile| CacheSpec {
            key_files: vec![manifest.clone(), manager_lockfile.clone()],
            paths: vec![if facts.manager == PackageManager::Bun {
                "~/.bun/install/cache".to_owned()
            } else {
                "~/.npm".to_owned()
            }],
        });
        let mut package_unit = unit(kind, &package_root, package_watch, commands, package_cache);
        let base_id = format!("{}-{}", kind.id_prefix(), identifier_suffix(&facts.name));
        let count = package_id_counts.entry(base_id.clone()).or_insert(0_usize);
        *count += 1;
        package_unit.id = if *count == 1 {
            base_id
        } else {
            format!("{base_id}-{count}")
        };
        package_unit.label = format!("{} package ({})", kind.label(), facts.name);
        package_unit.tool_version.clone_from(&facts.manager_version);
        package_units.push((
            package_root,
            facts.name.clone(),
            facts.dependencies.clone(),
            package_unit.id.clone(),
        ));
        units.push(package_unit);
    }
    let mut package_ids = BTreeMap::new();
    let mut duplicate_package_names = BTreeSet::new();
    for (_, name, _, id) in &package_units {
        if package_ids.insert(name.clone(), id.clone()).is_some() {
            duplicate_package_names.insert(name.clone());
        }
    }
    if !duplicate_package_names.is_empty() {
        analysis.limitations.push(format!(
            "Duplicate package names ({}) prevent automatic internal dependency edges.",
            duplicate_package_names
                .iter()
                .cloned()
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    for unit in units
        .iter_mut()
        .filter(|unit| matches!(unit.kind, UnitKind::Bun | UnitKind::Node))
    {
        let Some((_, _, dependencies, _)) = package_units
            .iter()
            .find(|(root, _, _, _)| root == &unit.root)
        else {
            continue;
        };
        unit.depends_on = dependencies
            .iter()
            .filter(|dependency| !duplicate_package_names.contains(*dependency))
            .filter_map(|dependency| package_ids.get(dependency).cloned())
            .filter(|dependency| dependency != &unit.id)
            .collect();
    }

    for package_root in roots_for_manifests(&files_named(&files, "Package.swift")) {
        analysis
            .detected
            .push(format!("swift-package:{package_root}"));
        units.push(swift_package_unit(&package_root));
    }
    let mut xcode_units = xcode_scheme_units(root, &files);
    let has_xcode_schemes = !xcode_units.is_empty();
    if has_xcode_schemes {
        analysis
            .detected
            .push(format!("xcode-shared-schemes:{}", xcode_units.len()));
        units.append(&mut xcode_units);
    }
    let has_xcode_container = files.iter().any(|file| {
        file.ends_with(".xcodeproj/project.pbxproj")
            || file.ends_with(".xcworkspace/contents.xcworkspacedata")
    });
    if has_xcode_container && !units.iter().any(|unit| unit.kind == UnitKind::Swift) {
        analysis.limitations.push(
            "Xcode projects were found without shared schemes; no build or test command was guessed. Share a scheme or add an explicit catalog profile.".to_owned(),
        );
    }
    if has_xcode_schemes {
        analysis.limitations.push(
            "Apple test destinations use platform defaults; review the generated simulator destination when a project requires a named device or OS version.".to_owned(),
        );
    }

    if files
        .iter()
        .any(|file| has_extension(file, "tf") || has_extension(file, "tofu"))
    {
        units.push(unit(
            UnitKind::OpenTofu,
            ".",
            vec![
                "**/*.tf".to_owned(),
                "**/*.tofu".to_owned(),
                "**/.terraform.lock.hcl".to_owned(),
            ],
            vec![
                "tofu fmt -check -recursive -no-color".to_owned(),
                "TF_IN_AUTOMATION=1 TF_INPUT=0 tofu init -backend=false -input=false -no-color"
                    .to_owned(),
                "TF_IN_AUTOMATION=1 TF_INPUT=0 tofu validate -no-color".to_owned(),
            ],
            Some(CacheSpec {
                key_files: vec!["**/.terraform.lock.hcl".to_owned()],
                paths: vec!["~/.terraform.d/plugin-cache".to_owned()],
            }),
        ));
    }

    let mut dockerfiles_by_root: BTreeMap<String, Vec<&String>> = BTreeMap::new();
    for dockerfile in files.iter().filter(|file| {
        file.rsplit('/')
            .next()
            .is_some_and(|name| name.starts_with("Dockerfile"))
    }) {
        let docker_root = parent_path(dockerfile);
        dockerfiles_by_root
            .entry(docker_root)
            .or_default()
            .push(dockerfile);
    }
    for (docker_root, dockerfiles) in dockerfiles_by_root {
        let context = if docker_root == "." {
            "."
        } else {
            &docker_root
        };
        units.push(unit(
            UnitKind::Docker,
            &docker_root,
            if context == "." {
                vec!["**".to_owned()]
            } else {
                vec![format!("{context}/**")]
            },
            dockerfiles
                .into_iter()
                .map(|dockerfile| {
                    let tag = identifier_suffix(dockerfile);
                    format!(
                        "docker build --file {} --tag local-ci:{tag} {}",
                        shell_quote(dockerfile),
                        shell_quote(context)
                    )
                })
                .collect(),
            None,
        ));
    }

    if files.iter().any(|file| {
        file.starts_with("Formula/") || file.starts_with("Casks/") || file == "Brewfile"
    }) {
        units.push(unit(
            UnitKind::Homebrew,
            ".",
            vec![
                "Formula/**".to_owned(),
                "Casks/**".to_owned(),
                "Brewfile".to_owned(),
            ],
            vec!["brew audit --strict --online".to_owned()],
            None,
        ));
    }

    if files.iter().any(|file| has_extension(file, "md")) {
        units.push(unit(
            UnitKind::Docs,
            ".",
            vec![
                "**/*.md".to_owned(),
                "mkdocs.yml".to_owned(),
                "docs/**".to_owned(),
            ],
            vec![
                "npx --yes markdownlint-cli2@0.20.0 \"**/*.md\" \"#node_modules\" \"#**/AGENTS.md\" \"#**/CLAUDE.md\" \"#target\" \"#**/target/**\" \"#dist\" \"#coverage\" \"#**/.cache/**\"".to_owned(),
            ],
            Some(CacheSpec {
                key_files: vec!["package-lock.json".to_owned(), "bun.lock".to_owned()],
                paths: vec!["~/.npm".to_owned()],
            }),
        ));
    }

    units.sort_by(|left, right| left.id.cmp(&right.id));
    disambiguate_unit_ids(&mut units);
    analysis.detected.sort();
    analysis.detected.dedup();
    analysis.limitations.sort();
    analysis.limitations.dedup();
    Ok(ProjectConfig {
        repository: String::new(),
        profile: RepositoryProfile::Generic,
        analysis,
        verified: true,
        workflow_files: default_workflow_files(),
        notes: Vec::new(),
        default_branch: "main".to_owned(),
        runners,
        github_runner: "ubuntu-24.04".to_owned(),
        velnor_labels: vec!["self-hosted".to_owned(), "velnor-target-mvp".to_owned()],
        release_enabled: false,
        release_reason: "Release is fail-closed. Enable only after declaring immutable artifact, registry, provenance, and tag-protection policy.".to_owned(),
        release: None,
        units,
    })
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct CargoDependency {
    name: String,
    package_name: Option<String>,
    path: Option<String>,
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct CargoManifestFacts {
    root: String,
    has_package: bool,
    package_name: Option<String>,
    has_workspace: bool,
    workspace_members: Vec<String>,
    dependencies: Vec<CargoDependency>,
    build_script: Option<String>,
    binary_targets: Vec<String>,
    test_targets: Vec<String>,
    features: Vec<String>,
}

#[derive(Default)]
struct RustAnalysis {
    units: Vec<Unit>,
    detected: Vec<String>,
    limitations: Vec<String>,
}

#[expect(
    clippy::too_many_lines,
    reason = "Rust evidence normalization keeps graph construction together"
)]
fn analyze_rust_manifests(
    root: &Path,
    files: &[String],
    file_set: &BTreeSet<String>,
    manifests: &[String],
) -> Result<RustAnalysis, GeneratorError> {
    let mut facts = Vec::new();
    for manifest in manifests {
        let manifest_root = parent_path(manifest);
        let path = root.join(manifest);
        let contents = fs::read_to_string(&path)
            .map_err(|error| GeneratorError::io("read Cargo manifest", &path, &error))?;
        let parsed = parse_cargo_manifest(&manifest_root, &contents);
        for (field, value) in parsed
            .package_name
            .iter()
            .map(|value| ("package name", value))
            .chain(
                parsed
                    .build_script
                    .iter()
                    .map(|value| ("build script", value)),
            )
            .chain(
                parsed
                    .binary_targets
                    .iter()
                    .map(|value| ("binary target", value)),
            )
            .chain(
                parsed
                    .test_targets
                    .iter()
                    .map(|value| ("test target", value)),
            )
        {
            if value.chars().any(char::is_control) {
                return Err(GeneratorError::usage(format!(
                    "Cargo {field} contains control characters at {}",
                    path.display()
                )));
            }
        }
        facts.push(parsed);
    }

    let workspace_root = facts
        .iter()
        .find(|manifest| manifest.has_workspace)
        .map(|manifest| manifest.root.clone());
    let has_nextest =
        file_set.contains(".config/nextest.toml") || file_set.contains("nextest.toml");
    let has_cargo_deny = file_set.contains("deny.toml") || file_set.contains(".cargo/deny.toml");
    let has_cargo_audit = file_set.contains("audit.toml") || file_set.contains(".cargo/audit.toml");
    let mut result = RustAnalysis::default();

    if workspace_root.is_some() {
        let member_count = facts.iter().filter(|manifest| manifest.has_package).count();
        result
            .detected
            .push(format!("rust-workspace-members:{member_count}"));
    } else if facts.iter().any(|manifest| manifest.has_package) {
        result.detected.push("rust-package".to_owned());
    }
    if has_nextest {
        result.detected.push("cargo-nextest-policy".to_owned());
    }
    if has_cargo_deny {
        result.detected.push("cargo-deny-policy".to_owned());
    }
    if has_cargo_audit {
        result.detected.push("cargo-audit-policy".to_owned());
    }
    if files
        .iter()
        .any(|file| matches!(file.rsplit('/').next(), Some("mise.toml" | "mise.lock")))
        && facts.iter().any(|manifest| manifest.has_package)
    {
        result.detected.push("mise-rust-toolchain".to_owned());
    }

    let package_facts = facts
        .iter()
        .filter(|manifest| manifest.has_package)
        .collect::<Vec<_>>();
    let mut package_ids = BTreeMap::new();
    let mut roots_by_manifest = BTreeMap::new();
    let mut rust_id_counts = BTreeMap::new();
    for manifest in &package_facts {
        let suffix = manifest
            .package_name
            .as_deref()
            .map(identifier_suffix)
            .filter(|suffix| !suffix.is_empty())
            .unwrap_or_else(|| identifier_suffix(&manifest.root));
        let base_id = format!("rust-{suffix}");
        let count = rust_id_counts.entry(base_id.clone()).or_insert(0_usize);
        *count += 1;
        let id = if *count == 1 {
            base_id
        } else {
            format!("{base_id}-{count}")
        };
        roots_by_manifest.insert(join_repo_path(&manifest.root, "Cargo.toml"), id.clone());
        if let Some(package_name) = &manifest.package_name {
            package_ids.insert(package_name.clone(), id);
        }
    }

    let workspace_manifest = workspace_root
        .as_deref()
        .map(|workspace| join_repo_path(workspace, "Cargo.toml"));
    for manifest in &package_facts {
        let manifest_path = join_repo_path(&manifest.root, "Cargo.toml");
        let prefix = path_prefix(&manifest.root);
        let command_prefix = shell_change_dir(&manifest.root);
        let default_build_script = join_repo_path(&manifest.root, "build.rs");
        let build_script = manifest.build_script.as_deref().or_else(|| {
            file_set
                .contains(&default_build_script)
                .then_some("build.rs")
        });
        let has_test_sources = file_set.iter().any(|file| {
            file.starts_with(&format!("{prefix}tests/"))
                || file.starts_with(&format!("{prefix}benches/"))
        });
        let package_selector = manifest.package_name.as_deref().map_or_else(
            || format!("--manifest-path {}", shell_quote("Cargo.toml")),
            |name| format!("--package {}", shell_quote(name)),
        );
        let cargo_lock_flag = if file_set.contains("Cargo.lock") {
            "--locked"
        } else {
            ""
        };
        let test_command = if has_nextest {
            format!(
                "{command_prefix}cargo nextest run {cargo_lock_flag} --all-features {package_selector}"
            )
        } else {
            format!(
                "{command_prefix}cargo test {cargo_lock_flag} --all-features {package_selector}"
            )
        };
        let commands = vec![
            format!(
                "{command_prefix}cargo fmt --manifest-path {} -- --check",
                shell_quote("Cargo.toml")
            ),
            format!(
                "{command_prefix}cargo clippy {cargo_lock_flag} --all-targets --all-features {package_selector} -- -D warnings"
            ),
            test_command,
        ];
        let mut watch = vec![
            manifest_path.clone(),
            "Cargo.lock".to_owned(),
            "rust-toolchain.toml".to_owned(),
            "rust-toolchain".to_owned(),
            ".cargo/**".to_owned(),
            format!("{prefix}**/*.rs"),
            format!("{prefix}src/**"),
            format!("{prefix}tests/**"),
            format!("{prefix}examples/**"),
            format!("{prefix}benches/**"),
        ];
        if let Some(workspace_manifest) = &workspace_manifest
            && workspace_manifest != &manifest_path
        {
            watch.push(workspace_manifest.clone());
        }
        if let Some(build_script) = build_script {
            if let Some(build_path) = resolve_repo_path(&manifest.root, build_script) {
                watch.push(build_path);
            }
            result.detected.push(format!(
                "rust-build-script:{}",
                manifest.package_name.as_deref().unwrap_or(&manifest.root)
            ));
        }
        if !manifest.binary_targets.is_empty() {
            result.detected.push(format!(
                "rust-binaries:{}:{}",
                manifest.package_name.as_deref().unwrap_or(&manifest.root),
                manifest.binary_targets.len()
            ));
        }
        if !manifest.test_targets.is_empty() || has_test_sources {
            result.detected.push(format!(
                "rust-test-targets:{}:{}",
                manifest.package_name.as_deref().unwrap_or(&manifest.root),
                manifest
                    .test_targets
                    .len()
                    .max(usize::from(has_test_sources))
            ));
        }
        if !manifest.features.is_empty() {
            result.detected.push(format!(
                "rust-features:{}:{}",
                manifest.package_name.as_deref().unwrap_or(&manifest.root),
                manifest.features.len()
            ));
        }
        let cache_key_files = vec![
            manifest_path.clone(),
            "Cargo.lock".to_owned(),
            "rust-toolchain.toml".to_owned(),
            "rust-toolchain".to_owned(),
        ];
        result.units.push(Unit {
            id: roots_by_manifest
                .get(&manifest_path)
                .cloned()
                .unwrap_or_else(|| format!("rust-{}", identifier_suffix(&manifest.root))),
            label: format!(
                "Rust crate ({})",
                manifest.package_name.as_deref().unwrap_or(&manifest.root)
            ),
            kind: UnitKind::Rust,
            root: manifest.root.clone(),
            watch,
            pr_commands: commands.clone(),
            full_commands: commands,
            depends_on: Vec::new(),
            cache: Some(CacheSpec {
                key_files: cache_key_files,
                paths: vec!["~/.cargo/registry".to_owned(), "~/.cargo/git".to_owned()],
            }),
            tool_version: None,
        });
    }

    if has_cargo_deny || has_cargo_audit {
        let mut commands = Vec::new();
        if has_cargo_deny {
            let command = if cargo_deny_has_license_policy(root, file_set) {
                "cargo deny check"
            } else {
                result.limitations.push(
                    "Cargo deny license checks are skipped because deny.toml declares no [licenses] policy.".to_owned(),
                );
                "cargo deny check advisories bans sources"
            };
            commands.push(command.to_owned());
        }
        if has_cargo_audit {
            commands.push("cargo audit".to_owned());
        }
        result.units.push(Unit {
            id: "rust-policy".to_owned(),
            label: "Rust dependency policy".to_owned(),
            kind: UnitKind::Rust,
            root: ".".to_owned(),
            watch: vec![
                "Cargo.toml".to_owned(),
                "Cargo.lock".to_owned(),
                "deny.toml".to_owned(),
                ".cargo/deny.toml".to_owned(),
                "audit.toml".to_owned(),
                ".cargo/audit.toml".to_owned(),
            ],
            pr_commands: commands.clone(),
            full_commands: commands,
            depends_on: Vec::new(),
            cache: Some(CacheSpec {
                key_files: vec!["Cargo.toml".to_owned(), "Cargo.lock".to_owned()],
                paths: vec!["~/.cargo/registry".to_owned(), "~/.cargo/git".to_owned()],
            }),
            tool_version: None,
        });
    }

    for manifest in &package_facts {
        let owner = roots_by_manifest
            .get(&join_repo_path(&manifest.root, "Cargo.toml"))
            .cloned()
            .unwrap_or_default();
        let Some(unit) = result.units.iter_mut().find(|unit| unit.id == owner) else {
            continue;
        };
        let mut dependencies = BTreeSet::new();
        for dependency in &manifest.dependencies {
            let dependency_root = dependency
                .path
                .as_deref()
                .and_then(|path| resolve_repo_path(&manifest.root, path))
                .map(|path| join_repo_path(&path, "Cargo.toml"));
            let dependency_id = dependency_root
                .and_then(|path| roots_by_manifest.get(&path).cloned())
                .or_else(|| {
                    dependency
                        .package_name
                        .as_ref()
                        .and_then(|name| package_ids.get(name).cloned())
                })
                .or_else(|| package_ids.get(&dependency.name).cloned());
            if let Some(dependency_id) = dependency_id.filter(|id| id != &owner) {
                dependencies.insert(dependency_id);
            }
        }
        unit.depends_on = dependencies.into_iter().collect();
    }

    if facts.iter().any(|manifest| {
        manifest.build_script.is_some()
            || file_set.contains(&join_repo_path(&manifest.root, "build.rs"))
    }) {
        result.limitations.push(
            "Rust build scripts are watched but their system dependencies and generated outputs are not inferred.".to_owned(),
        );
    }
    if files.iter().any(|file| file == "Cargo.lock") {
        result.detected.push("cargo-lockfile".to_owned());
    }
    result.detected.sort();
    result.detected.dedup();
    result.limitations.sort();
    result.limitations.dedup();
    Ok(result)
}

#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
enum PackageManager {
    Bun,
    Npm,
}

impl PackageManager {
    fn from_name(name: &str) -> Option<Self> {
        match name {
            "bun" => Some(Self::Bun),
            "npm" => Some(Self::Npm),
            _ => None,
        }
    }

    fn command(self) -> &'static str {
        match self {
            Self::Bun => "bun",
            Self::Npm => "npm",
        }
    }

    fn detected(self) -> &'static str {
        match self {
            Self::Bun => "bun",
            Self::Npm => "npm",
        }
    }

    fn lockfiles(self) -> &'static [&'static str] {
        match self {
            Self::Bun => &["bun.lock", "bun.lockb"],
            Self::Npm => &["package-lock.json"],
        }
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
struct PackageJsonFacts {
    name: String,
    scripts: BTreeSet<String>,
    dependencies: BTreeSet<String>,
    manager: PackageManager,
    manager_version: Option<String>,
    workspace_root: bool,
}

fn parse_package_json(
    root: &Path,
    relative_root: &str,
    contents: &str,
    file_set: &BTreeSet<String>,
) -> Result<Option<PackageJsonFacts>, GeneratorError> {
    let value: Value = serde_json::from_str(contents).map_err(|error| {
        GeneratorError::usage(format!(
            "invalid package.json at {}: {error}",
            root.join(relative_root).display()
        ))
    })?;
    let object = value.as_object().ok_or_else(|| {
        GeneratorError::usage(format!(
            "package.json must contain an object at {}",
            root.join(relative_root).display()
        ))
    })?;
    let name = object
        .get("name")
        .and_then(Value::as_str)
        .filter(|name| !name.is_empty())
        .map_or_else(|| relative_root.to_owned(), str::to_owned);
    if name.chars().any(char::is_control) {
        return Err(GeneratorError::usage(format!(
            "package name contains control characters at {}",
            root.join(relative_root).display()
        )));
    }
    let scripts = object
        .get("scripts")
        .and_then(Value::as_object)
        .map(|scripts| scripts.keys().cloned().collect())
        .unwrap_or_default();
    let mut dependencies = BTreeSet::new();
    for field in [
        "dependencies",
        "devDependencies",
        "optionalDependencies",
        "peerDependencies",
    ] {
        if let Some(entries) = object.get(field).and_then(Value::as_object) {
            dependencies.extend(entries.keys().cloned());
        }
    }
    let package_manager_spec = object
        .get("packageManager")
        .and_then(Value::as_str)
        .map(str::to_owned);
    if package_manager_spec
        .as_deref()
        .is_some_and(|value| value.chars().any(char::is_control))
    {
        return Err(GeneratorError::usage(format!(
            "packageManager contains control characters at {}",
            root.join(relative_root).display()
        )));
    }
    let package_manager = package_manager_spec
        .as_deref()
        .map(|value| value.split_once('@').map_or(value, |(name, _)| name))
        .and_then(PackageManager::from_name);
    if package_manager_spec.is_some() && package_manager.is_none() {
        return Ok(None);
    }
    let manager =
        package_manager.or_else(|| package_manager_from_ancestors(root, relative_root, file_set));
    let Some(manager) = manager else {
        return Ok(None);
    };
    let manager_version = package_manager_spec
        .as_deref()
        .and_then(|value| value.split_once('@').map(|(_, version)| version.to_owned()))
        .or_else(|| {
            package_manager
                .is_none()
                .then(|| package_manager_version_from_ancestors(root, relative_root, manager))?
        });
    if manager_version
        .as_deref()
        .is_some_and(|value| value.chars().any(char::is_control))
    {
        return Err(GeneratorError::usage(format!(
            "packageManager version contains control characters at {}",
            root.join(relative_root).display()
        )));
    }
    let workspace_root = object.contains_key("workspaces");
    Ok(Some(PackageJsonFacts {
        name,
        scripts,
        dependencies,
        manager,
        manager_version,
        workspace_root,
    }))
}

fn package_manager_from_ancestors(
    root: &Path,
    relative_root: &str,
    file_set: &BTreeSet<String>,
) -> Option<PackageManager> {
    let mut current = relative_root.to_owned();
    loop {
        let manifest = root.join(join_repo_path(&current, "package.json"));
        if let Ok(contents) = fs::read_to_string(manifest)
            && let Ok(value) = serde_json::from_str::<Value>(&contents)
            && let Some(spec) = value
                .as_object()
                .and_then(|object| object.get("packageManager"))
                .and_then(Value::as_str)
            && let Some((name, _)) = spec.split_once('@')
            && let Some(manager) = PackageManager::from_name(name)
        {
            return Some(manager);
        }
        if let Some(manager) =
            [PackageManager::Bun, PackageManager::Npm]
                .into_iter()
                .find(|manager| {
                    manager
                        .lockfiles()
                        .iter()
                        .any(|lockfile| file_set.contains(&join_repo_path(&current, lockfile)))
                })
        {
            return Some(manager);
        }
        if current == "." {
            return None;
        }
        current = parent_path(&current);
    }
}

fn package_manager_version_from_ancestors(
    root: &Path,
    relative_root: &str,
    manager: PackageManager,
) -> Option<String> {
    let mut current = relative_root.to_owned();
    loop {
        let manifest = root.join(join_repo_path(&current, "package.json"));
        if let Ok(contents) = fs::read_to_string(manifest)
            && let Ok(value) = serde_json::from_str::<Value>(&contents)
            && let Some(spec) = value
                .as_object()
                .and_then(|object| object.get("packageManager"))
                .and_then(Value::as_str)
            && let Some((name, version)) = spec.split_once('@')
            && PackageManager::from_name(name) == Some(manager)
        {
            return Some(version.to_owned());
        }
        if current == "." {
            return None;
        }
        current = parent_path(&current);
    }
}

fn package_lockfile_path(
    relative_root: &str,
    manager: PackageManager,
    file_set: &BTreeSet<String>,
) -> Option<String> {
    let mut current = relative_root.to_owned();
    loop {
        if let Some(lockfile) = manager
            .lockfiles()
            .iter()
            .map(|lockfile| join_repo_path(&current, lockfile))
            .find(|lockfile| file_set.contains(lockfile))
        {
            return Some(lockfile);
        }
        if current == "." {
            return None;
        }
        current = parent_path(&current);
    }
}

fn package_commands(root: &str, facts: &PackageJsonFacts, locked: bool) -> Vec<String> {
    let prefix = shell_change_dir(root);
    let install = match facts.manager {
        PackageManager::Bun if locked => format!("{prefix}bun install --frozen-lockfile"),
        PackageManager::Bun => format!("{prefix}bun install"),
        PackageManager::Npm if locked => format!("{prefix}npm ci"),
        PackageManager::Npm => format!("{prefix}npm install"),
    };
    let command = facts.manager.command();
    let mut commands = vec![install];
    for script in ["lint", "typecheck", "build"] {
        if facts.scripts.contains(script) {
            commands.push(format!("{prefix}{command} run {script}"));
        }
    }
    if facts.scripts.contains("test") {
        commands.push(format!("{prefix}{command} run test"));
    }
    commands
}

