/// Clap-owned command-line syntax. Conversion into [`Cli`] preserves the
/// public domain boundary used by generation and tests.
#[expect(
    clippy::struct_excessive_bools,
    reason = "these independent flags map directly to stable CLI switches"
)]
#[derive(Debug, Parser)]
#[command(
        name = "velnor-workflow",
    version,
        about = "Scan a repository and generate safe, unified GitHub Actions CI",
    long_about = None
)]
struct RawCli {
    /// Local path, GitHub URL, owner/repository, or `estate`. Prefix with
    /// `generate` for the explicit `generate TARGET` form.
    #[arg(value_name = "TARGET")]
    target: Option<OsString>,

    /// Repository target when the explicit `generate` prefix is used.
    #[arg(value_name = "TARGET")]
    generate_target: Option<OsString>,

    /// Root directory for generated files.
    #[arg(long, value_name = "PATH")]
    output: Option<PathBuf>,

    /// Default branch used for generated branch gates. If omitted, resolve it
    /// from the repository's static Git remote metadata.
    #[arg(long, value_name = "BRANCH")]
    default_branch: Option<String>,

    /// Runner lanes to generate.
    #[arg(long, value_enum, default_value_t = RunnerMode::Both, value_name = "MODE")]
    runners: RunnerMode,

    /// Inspect changes without writing files.
    #[arg(long, conflicts_with = "check")]
    dry_run: bool,

    /// Fail if generated files would change.
    #[arg(long, conflicts_with = "dry_run")]
    check: bool,

    /// Replace only recorded, unmodified generator-owned files.
    #[arg(long)]
    force: bool,

    /// Adopt existing workflow bodies after review, store them as generator
    /// templates, and emit Velnor-owned workflow output; implies --force.
    #[arg(long)]
    adopt: bool,

    /// Use the line-oriented CLI report instead of the default interactive TUI.
    #[arg(long)]
    plain: bool,
}

impl Cli {
    /// Parse the documented target syntax, options, and flags.
    ///
    /// # Errors
    /// Returns an error for invalid command-line syntax or target forms.
    pub fn parse_args(
        arguments: impl IntoIterator<Item = OsString>,
    ) -> Result<Self, GeneratorError> {
        parse_clap(arguments)?.try_into()
    }
}

impl TryFrom<RawCli> for Cli {
    type Error = GeneratorError;

    fn try_from(raw: RawCli) -> Result<Self, Self::Error> {
        let target = match (raw.target, raw.generate_target) {
            (Some(prefix), Some(target)) if prefix == "generate" => target,
            (_, Some(_)) => {
                return Err(GeneratorError::usage(
                    "only `generate TARGET` accepts two positional values",
                ));
            }
            (Some(target), None) if target == "generate" => {
                return Err(GeneratorError::usage("generate needs a repository target"));
            }
            (Some(target), None) => target,
            (None, None) => OsString::from("."),
        };
        let target = target
            .into_string()
            .map_err(|_| GeneratorError::usage("repository target must be valid UTF-8"))?;

        Ok(Self {
            target,
            default_branch: raw.default_branch,
            output: raw.output,
            runners: raw.runners,
            dry_run: raw.dry_run,
            check: raw.check,
            force: raw.force || raw.adopt,
            adopt: raw.adopt,
            plain: raw.plain,
        })
    }
}

fn parse_raw_clap(arguments: impl IntoIterator<Item = OsString>) -> Result<RawCli, clap::Error> {
    let mut values = vec![OsString::from("velnor-workflow")];
    values.extend(arguments);
    RawCli::try_parse_from(values)
}

fn parse_clap(arguments: impl IntoIterator<Item = OsString>) -> Result<RawCli, GeneratorError> {
    parse_raw_clap(arguments).map_err(|error| clap_usage_error(&error))
}

fn clap_usage_error(error: &clap::Error) -> GeneratorError {
    let rendered = error.to_string();
    let message = rendered
        .strip_prefix("error: ")
        .unwrap_or(&rendered)
        .trim_end()
        .to_owned();
    GeneratorError::usage(message)
}

/// Generator error with user-actionable context; the CLI never panics on input.
#[derive(Debug)]
pub struct GeneratorError {
    message: String,
}

impl GeneratorError {
    fn usage(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
        }
    }

    fn io(operation: &str, path: &Path, source: &io::Error) -> Self {
        Self {
            message: format!("{operation} {}: {source}", path.display()),
        }
    }
}

impl std::fmt::Display for GeneratorError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.message)
    }
}

impl std::error::Error for GeneratorError {}

