    #[test]
    fn generation_lock_serializes_mutating_writers() {
        use std::sync::mpsc;
        use std::time::Duration;

        let root = temporary_repository("generation-lock");
        let first = must(GenerationLock::acquire(&root, []), "acquire first lock");
        let (started_tx, started_rx) = mpsc::channel();
        let (acquired_tx, acquired_rx) = mpsc::channel();
        let waiter_root = root.clone();
        let waiter = std::thread::spawn(move || {
            assert!(started_tx.send(()).is_ok(), "report waiter start");
            let lock = GenerationLock::acquire(&waiter_root, []);
            assert!(acquired_tx.send(()).is_ok(), "report waiter acquisition");
            drop(lock);
        });
        must(started_rx.recv(), "wait for waiter to start");
        // One-sided guarantee check: while the first holder keeps the lock,
        // a blocking acquire must not complete. Flock cannot succeed here,
        // so a short wait cannot produce a false failure — only a real
        // locking defect can.
        std::thread::sleep(Duration::from_millis(100));
        assert!(
            acquired_rx.recv_timeout(Duration::from_millis(1)).is_err(),
            "a blocking lock acquired while another writer still holds it"
        );
        drop(first);
        must(acquired_rx.recv(), "waiter proceeds after release");
        assert!(
            waiter.join().is_ok(),
            "waiter thread must finish without panicking"
        );
        let third = GenerationLock::acquire(&root, []);
        assert!(third.is_ok());
        drop(third);
        let _ = fs::remove_dir_all(root);
    }
