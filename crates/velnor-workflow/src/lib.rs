/// Run the generator from the process argument vector.
///
/// # Errors
/// Reports parsing, clone, scanning, and write failures without replacing a
/// manually edited file unless explicit adoption was requested. Individual
/// generated files are replaced atomically.
pub fn run_from_env() -> Result<(), GeneratorError> {
    let arguments = env::args_os().skip(1).collect::<Vec<_>>();
    if runtime::try_run(&arguments)? {
        return Ok(());
    }
    let raw = match parse_raw_clap(arguments) {
        Ok(raw) => raw,
        Err(error)
            if matches!(
                error.kind(),
                clap::error::ErrorKind::DisplayHelp | clap::error::ErrorKind::DisplayVersion
            ) =>
        {
            print!("{error}");
            return Ok(());
        }
        Err(error) => return Err(clap_usage_error(&error)),
    };
    let cli = raw.try_into()?;
    run(&cli)
}

fn run(cli: &Cli) -> Result<(), GeneratorError> {
    if cli.target == "estate" {
        return estate::run_estate(cli);
    }
    if !cli.plain && io::stdin().is_terminal() && io::stdout().is_terminal() {
        return tui::run(cli);
    }
    let source = RepositorySource::parse(&cli.target)?;
    let checkout = source.checkout()?;
    let default_branch = match cli.default_branch.as_deref() {
        Some(branch) => validate_default_branch(branch)?.to_owned(),
        None => source.default_branch(checkout.path())?,
    };
    let output_root = match cli.output.as_deref() {
        Some(path) => resolve_output_path(path)?,
        None => source.output_root(checkout.path())?,
    };
    let mut scanned = scan_target(checkout.path(), cli.runners, &default_branch)?;
    if cli.adopt {
        scanned.config = adopt_existing_workflow_templates(&output_root, scanned.config)?;
    }
    if scanned.config.units.is_empty() && scanned.config.workflow_templates.is_empty() {
        return Err(GeneratorError::usage(
            "scanner found no supported manifest or project shape; add project.toml manually only after defining a safe command",
        ));
    }
    let mut config = scanned.config;
    let surface = primitives::generate(
        checkout.path(),
        &scanned.shape,
        &config,
        scanned.generation.as_ref(),
    )?;
    config.units.clone_from(&surface.units);
    // A declared release-side family can add a workflow file the scan did not
    // own; declaring it is what makes it part of the owned surface.
    for file in &surface.added_files {
        if !config.workflow_files.contains(file) {
            config.workflow_files.push(file.clone());
        }
    }
    let files = generated_files_with_surface(&config, Some(&surface))?;
    let inputs = scanned.inputs;
    let outcome = write_generated_with_options(
        &output_root,
        &files,
        &inputs,
        cli.dry_run,
        cli.check,
        cli.force,
        cli.adopt,
    )?;
    print_report(&cli.target, &config, &files, &outcome, &output_root);
    Ok(())
}

fn generated_files(config: &ProjectConfig) -> Result<BTreeMap<PathBuf, String>, GeneratorError> {
    generated_files_with_surface(config, None)
}

/// The generated surface, with the workflow families the declared primitives
/// own taken from the rendered surface instead of the legacy renderer.
fn generated_files_with_surface(
    config: &ProjectConfig,
    surface: Option<&primitives::Surface>,
) -> Result<BTreeMap<PathBuf, String>, GeneratorError> {
    let workflow = WorkflowIr::from_config(config);
    primitives::validate_cache_transports(&workflow)?;
    // The toolchain contract is a generation precondition, checked here so no
    // rendering path — scanned, declared, or catalog — can emit a Rust job
    // without a pin or a release matrix the pin does not declare.
    validate_rust_units_are_pinned(config)?;
    validate_release_targets_are_pinned(config)?;
    let mut files = BTreeMap::new();
    files.insert(
        PathBuf::from(".github/actionlint.yaml"),
        render_actionlint_config(config),
    );
    files.insert(PathBuf::from(".github/ci/project.toml"), config.toml());
    for workflow_file in &config.workflow_files {
        let path = PathBuf::from(".github/workflows").join(workflow_file);
        if let Some(content) = surface.and_then(|surface| surface.files.get(&path)) {
            files.insert(path, content.clone());
            continue;
        }
        let content = config
            .workflow_templates
            .get(workflow_file)
            .map(|template| render_static_template_for_config(config, workflow_file, template))
            .transpose()?
            .or_else(|| match workflow_file.as_str() {
                "ci-pr.yml" => Some(generated_ci_pr(&workflow)),
                "ci-policy.yml" => Some(generated_ci_policy()),
                "ci-release-package-signer.yml" => Some(generated_release_package_signer()),
                "ci-main.yml" => Some(generated_ci_main(&workflow)),
                "nightly.yml" => Some(generated_nightly(&workflow)),
                "maintenance.yml" => Some(generated_maintenance(config)),
                "preview.yml" => Some(generated_preview(config)),
                "release.yml" => generated_release(config),
                // Catalog data is code-owned; ignore no unknown runtime path and never
                // let configuration turn into an arbitrary filesystem write.
                _ => None,
            });
        if let Some(content) = content {
            files.insert(path, content);
        }
    }
    for (name, template) in &config.workflow_templates {
        files.insert(
            PathBuf::from(WORKFLOW_TEMPLATE_DIR).join(name),
            render_static_template_for_config(config, name, template)?,
        );
    }
    if !config.adopted_workflow_surface {
        for unit in &config.units {
            files.insert(
                PathBuf::from(".github/workflows").join(nested_unit_workflow_file(unit)),
                workflow.render_nested_unit(unit, WorkflowKind::Main),
            );
        }
    }
    for owned in &config.static_files {
        files.insert(PathBuf::from(&owned.path), owned.content.clone());
    }
    Ok(files)
}

