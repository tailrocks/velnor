fn repository_files(root: &Path) -> Result<Vec<String>, GeneratorError> {
    if !root.is_dir() {
        return Err(GeneratorError::usage(format!(
            "not a repository directory: {}",
            root.display()
        )));
    }
    let mut files = Vec::new();
    collect_files(root, root, &mut files)?;
    files.sort();
    Ok(files)
}

fn collect_files(
    root: &Path,
    directory: &Path,
    files: &mut Vec<String>,
) -> Result<(), GeneratorError> {
    let entries = fs::read_dir(directory)
        .map_err(|error| GeneratorError::io("read directory", directory, &error))?;
    for entry in entries {
        let entry =
            entry.map_err(|error| GeneratorError::io("read directory entry", directory, &error))?;
        let path = entry.path();
        let name = entry.file_name();
        let name = name.to_string_lossy();
        let kind = entry
            .file_type()
            .map_err(|error| GeneratorError::io("read file type", &path, &error))?;
        if kind.is_symlink() {
            continue;
        }
        if kind.is_dir() {
            // Generated `.github` content is output, not project input.
            if matches!(
                name.as_ref(),
                ".git"
                    | ".github"
                    | ".output"
                    | "target"
                    | "node_modules"
                    | ".build"
                    | ".gradle"
                    | ".terraform"
                    | "dist"
                    | "coverage"
            ) {
                continue;
            }
            collect_files(root, &path, files)?;
        } else if kind.is_file() {
            let relative = path.strip_prefix(root).map_err(|error| {
                GeneratorError::usage(format!("make repository path relative: {error}"))
            })?;
            files.push(normalize_relative_path(relative)?);
        }
    }
    Ok(())
}

fn normalize_relative_path(path: &Path) -> Result<String, GeneratorError> {
    let mut parts = Vec::new();
    for component in path.components() {
        match component {
            Component::Normal(part) => {
                let part = part.to_string_lossy();
                if part.chars().any(char::is_control) {
                    return Err(GeneratorError::usage(format!(
                        "unsafe control character in repository path: {}",
                        path.display()
                    )));
                }
                parts.push(part.into_owned());
            }
            Component::CurDir => (),
            Component::ParentDir | Component::RootDir | Component::Prefix(_) => {
                return Err(GeneratorError::usage(format!(
                    "unsafe repository path: {}",
                    path.display()
                )));
            }
        }
    }
    Ok(parts.join("/"))
}

fn files_named(files: &[String], name: &str) -> Vec<String> {
    files
        .iter()
        .filter(|file| file.rsplit('/').next() == Some(name))
        .cloned()
        .collect()
}

fn has_extension(file: &str, extension: &str) -> bool {
    Path::new(file)
        .extension()
        .and_then(|value| value.to_str())
        .is_some_and(|value| value.eq_ignore_ascii_case(extension))
}

fn roots_for_manifests(manifests: &[String]) -> Vec<String> {
    let mut roots = BTreeSet::new();
    for manifest in manifests {
        roots.insert(parent_path(manifest));
    }
    roots.into_iter().collect()
}

fn gradle_roots(files: &BTreeSet<String>) -> Vec<String> {
    let manifests = files
        .iter()
        .filter(|file| {
            matches!(
                file.rsplit('/').next(),
                Some(
                    "settings.gradle" | "settings.gradle.kts" | "build.gradle" | "build.gradle.kts"
                )
            )
        })
        .cloned()
        .collect::<Vec<_>>();
    roots_for_manifests(&manifests)
}

fn parent_path(path: &str) -> String {
    path.rsplit_once('/')
        .map_or_else(|| ".".to_owned(), |(parent, _)| parent.to_owned())
}

fn join_repo_path(root: &str, child: &str) -> String {
    if root == "." {
        child.to_owned()
    } else {
        format!("{root}/{child}")
    }
}

fn path_prefix(root: &str) -> String {
    if root == "." {
        String::new()
    } else {
        format!("{root}/")
    }
}

fn identifier_suffix(value: &str) -> String {
    value
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect::<String>()
        .trim_matches('-')
        .to_owned()
}

fn disambiguate_unit_ids(units: &mut [Unit]) {
    let mut counts = BTreeMap::new();
    for unit in units {
        let base_id = unit.id.clone();
        let count = counts.entry(base_id.clone()).or_insert(0_usize);
        *count += 1;
        if *count > 1 {
            unit.id = format!("{base_id}-{count}");
        }
    }
}

fn unit(
    kind: UnitKind,
    root: &str,
    watch: Vec<String>,
    commands: Vec<String>,
    cache: Option<CacheSpec>,
) -> Unit {
    let suffix = if root == "." {
        String::new()
    } else {
        format!("-{}", identifier_suffix(root))
    };
    Unit {
        id: format!("{}{}", kind.id_prefix(), suffix),
        label: if root == "." {
            kind.label().to_owned()
        } else {
            format!("{} ({root})", kind.label())
        },
        kind,
        root: root.to_owned(),
        watch,
        pr_commands: commands.clone(),
        full_commands: commands,
        depends_on: Vec::new(),
        cache,
        tool_version: None,
    }
}

fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

fn shell_change_dir(root: &str) -> String {
    if root == "." {
        String::new()
    } else {
        format!("cd -- {} && ", shell_quote(root))
    }
}

/// Workflow intermediate representation. Rendering is kept separate from
/// scanning so output policy is inspectable and unit-tested.
#[derive(Debug)]
struct WorkflowIr {
    default_branch: String,
    github_runner: String,
    velnor_labels: Vec<String>,
    runners: RunnerMode,
    tools: BTreeSet<ToolRequirement>,
    mise_rust: bool,
    units: Vec<Unit>,
}

#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
enum ToolRequirement {
    OpenTofu,
    Homebrew,
    Bun,
    Node,
    Nextest,
    CargoDeny,
    CargoAudit,
    Gradle,
    Sccache,
    Mold,
    DockerBuildx,
    Mise,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum WorkflowKind {
    PullRequest,
    Main,
    Nightly,
}

#[allow(dead_code)]
impl WorkflowIr {
    fn from_config(config: &ProjectConfig) -> Self {
        let mut tools = BTreeSet::new();
        if config
            .units
            .iter()
            .any(|unit| unit.kind == UnitKind::OpenTofu)
        {
            tools.insert(ToolRequirement::OpenTofu);
        }
        if config
            .units
            .iter()
            .any(|unit| unit.kind == UnitKind::Homebrew)
        {
            tools.insert(ToolRequirement::Homebrew);
        }
        if config.units.iter().any(|unit| unit.kind == UnitKind::Bun) {
            tools.insert(ToolRequirement::Bun);
        }
        if config.units.iter().any(|unit| unit.kind == UnitKind::Node) {
            tools.insert(ToolRequirement::Node);
        }
        if config
            .units
            .iter()
            .any(|unit| unit.kind == UnitKind::Gradle)
        {
            tools.insert(ToolRequirement::Gradle);
        }
        if config.units.iter().any(|unit| unit.kind == UnitKind::Rust) {
            tools.insert(ToolRequirement::Sccache);
            tools.insert(ToolRequirement::Mold);
        }
        let mise_rust = config
            .analysis
            .detected
            .iter()
            .any(|item| item == "mise-rust-toolchain");
        if mise_rust {
            tools.insert(ToolRequirement::Mise);
        }
        if config
            .units
            .iter()
            .any(|unit| unit.kind == UnitKind::Docker)
        {
            tools.insert(ToolRequirement::DockerBuildx);
        }
        Self {
            default_branch: config.default_branch.clone(),
            github_runner: config.github_runner.clone(),
            velnor_labels: config.velnor_labels.clone(),
            runners: config.runners,
            tools,
            mise_rust,
            units: config.units.clone(),
        }
    }

    fn render(&self, kind: WorkflowKind) -> String {
        let mut output = String::from(GENERATED_HEADER);
        let (workflow_name, run_name, triggers, cancel_in_progress) = match kind {
            WorkflowKind::PullRequest => (
                "CI",
                "CI / PR",
                "on:\n  pull_request:\n  merge_group:".to_owned(),
                "true",
            ),
            WorkflowKind::Main => (
                "CI",
                "CI / main",
                format!(
                    "on:\n  push:\n    branches: [{}]\n  workflow_dispatch:",
                    yaml_scalar(&self.default_branch)
                ),
                "false",
            ),
            WorkflowKind::Nightly => (
                "Nightly",
                "Nightly",
                "on:\n  schedule:\n    - cron: '17 3 * * *'\n  workflow_dispatch:".to_owned(),
                "false",
            ),
        };
        let _ = writeln!(
            output,
            "name: {workflow_name}\nrun-name: {run_name} · ${{{{ github.event_name }}}} · ${{{{ github.ref_name }}}}\n\n{triggers}\n\nconcurrency:\n  group: ci-${{{{ github.workflow }}}}-${{{{ github.event.pull_request.number || github.ref }}}}\n  cancel-in-progress: {cancel_in_progress}\n\npermissions:\n  contents: read\n\n"
        );
        if self.tools.contains(&ToolRequirement::Sccache)
            || self.tools.contains(&ToolRequirement::OpenTofu)
        {
            output.push_str("env:\n");
            if self.tools.contains(&ToolRequirement::Sccache) {
                output.push_str(
                    "  CARGO_INCREMENTAL: \"0\"\n  RUSTC_WRAPPER: sccache\n  SCCACHE_GHA_ENABLED: \"true\"\n",
                );
            }
            if self.tools.contains(&ToolRequirement::OpenTofu) {
                output.push_str("  TF_PLUGIN_CACHE_DIR: ~/.terraform.d/plugin-cache\n");
            }
            output.push('\n');
        }
        output.push_str("jobs:\n");
        // Runner mode is global; only trusted-event jobs receive the extra
        // default-branch gate needed for Velnor execution.
        let trusted_event = kind != WorkflowKind::PullRequest;
        let runners = self.runners;
        // Planning and policy execute on a GitHub-hosted runner even when the
        // selected verification lane is self-hosted. They execute checked-in
        // shell files and must never expose untrusted PR code to that runner.
        self.render_plan(&mut output, RunnerMode::Github, false);
        self.render_policy(&mut output, RunnerMode::Github, false);
        self.render_hierarchy_groups(&mut output);
        let cache_save = kind != WorkflowKind::PullRequest;
        match runners {
            RunnerMode::Github => self.render_verify_github(&mut output, None, cache_save),
            RunnerMode::Velnor => self.render_verify_velnor(&mut output, cache_save),
            RunnerMode::Both => {
                self.render_verify_github(&mut output, None, cache_save);
                self.render_verify_velnor(&mut output, false);
            }
        }
        // Auxiliary schedules must not create or satisfy the branch-protection
        // check. Only the PR and main workflows own the stable required check.
        if kind != WorkflowKind::Nightly {
            self.render_required(
                &mut output,
                runners,
                kind == WorkflowKind::PullRequest,
                trusted_event,
            );
        }
        while output.ends_with("\n\n") {
            output.pop();
        }
        output = output
            .lines()
            .map(|line| {
                line.split_once(" · Runner:")
                    .filter(|_| line.trim_start().starts_with("name:"))
                    .map_or_else(
                        || line.to_owned(),
                        |(name, _)| {
                            if name.contains("name: \"") {
                                format!("{name}\"")
                            } else {
                                name.to_owned()
                            }
                        },
                    )
            })
            .collect::<Vec<_>>()
            .join("\n");
        output
    }

    /// Render one reusable-workflow call per sidebar group. GitHub flattens
    /// nested reusable workflows, so an intermediate stack workflow would hide
    /// unit names and place every terminal runner job directly under the stack.
    fn render_nested(&self, kind: WorkflowKind) -> String {
        let mut output = String::from(GENERATED_HEADER);
        let (workflow_name, run_name, triggers, cancel_in_progress) = match kind {
            WorkflowKind::PullRequest => (
                "CI",
                "CI / PR",
                "on:\n  pull_request:\n  merge_group:".to_owned(),
                "true",
            ),
            WorkflowKind::Main => (
                "CI",
                "CI / main",
                format!(
                    "on:\n  push:\n    branches: [{}]\n  workflow_dispatch:",
                    yaml_scalar(&self.default_branch)
                ),
                "false",
            ),
            WorkflowKind::Nightly => (
                "Nightly",
                "Nightly",
                "on:\n  schedule:\n    - cron: '17 3 * * *'\n  workflow_dispatch:".to_owned(),
                "false",
            ),
        };
        let _ = writeln!(
            output,
            "name: {workflow_name}\nrun-name: {run_name} · ${{{{ github.event_name }}}} · ${{{{ github.ref_name }}}}\n\n{triggers}\n\nconcurrency:\n  group: ci-${{{{ github.workflow }}}}-${{{{ github.event.pull_request.number || github.ref }}}}\n  cancel-in-progress: {cancel_in_progress}\n\npermissions:\n  contents: read\n\njobs:"
        );
        self.render_plan(&mut output, RunnerMode::Github, false);
        self.render_policy(&mut output, RunnerMode::Github, false);
        self.render_nested_unit_callers(&mut output);
        if kind != WorkflowKind::Nightly {
            self.render_nested_required(&mut output, kind == WorkflowKind::PullRequest);
        }
        while output.ends_with("\n\n") {
            output.pop();
        }
        output
    }

    fn render_nested_unit_callers(&self, output: &mut String) {
        for unit in &self.units {
            let mut needs = vec!["plan".to_owned(), "policy".to_owned()];
            needs.extend(unit.depends_on.iter().map(|dependency| {
                self.units
                    .iter()
                    .find(|candidate| candidate.id == *dependency)
                    .map_or_else(|| unit_group_job_id(unit), unit_group_job_id)
            }));
            let id = unit_group_job_id(unit);
            let name = sidebar_group_name(unit);
            let _ = writeln!(
                output,
                "  {id}:\n    name: {}\n    needs: [{}]\n    uses: ./.github/workflows/{}\n    with:\n      scope: ${{{{ needs.plan.outputs.scope }}}}",
                yaml_scalar(&name),
                needs.join(", "),
                nested_unit_workflow_file(unit)
            );
        }
    }

    fn render_nested_required(&self, output: &mut String, pull_request: bool) {
        let units = self.units.iter().map(unit_group_job_id).collect::<Vec<_>>();
        let needs = std::iter::once("plan".to_owned())
            .chain(std::iter::once("policy".to_owned()))
            .chain(units)
            .collect::<Vec<_>>();
        let statuses = needs
            .iter()
            .map(|job| format!("needs['{job}'].result == 'success'"))
            .collect::<Vec<_>>()
            .join(" && ");
        let check_name = if pull_request { "required" } else { "main" };
        let _ = writeln!(
            output,
            "  required:\n    name: {check_name}\n    if: ${{{{ always() && {statuses} }}}}\n    needs: [{}]\n    runs-on: {}\n    timeout-minutes: 5\n    steps:\n      - name: All generated stack workflows passed\n        run: echo 'all generated CI stacks passed'",
            needs.join(", "),
            yaml_scalar(&self.github_runner)
        );
    }

    fn render_nested_unit(&self, unit: &Unit, kind: WorkflowKind) -> String {
        let mut output = String::from(GENERATED_HEADER);
        let _ = writeln!(
            output,
            "name: {}\non:\n  workflow_call:\n    inputs:\n      scope:\n        required: true\n        type: string",
            yaml_scalar(&sidebar_group_name(unit))
        );
        self.render_workflow_env(&mut output, unit);
        output.push_str("\njobs:\n");
        let cache_save = kind != WorkflowKind::PullRequest;
        if lane_supports_unit(RunnerMode::Github, unit)
            && matches!(self.runners, RunnerMode::Github | RunnerMode::Both)
        {
            self.render_nested_lane(&mut output, RunnerMode::Github, unit, cache_save, false);
        }
        if lane_supports_unit(RunnerMode::Velnor, unit)
            && matches!(self.runners, RunnerMode::Velnor | RunnerMode::Both)
        {
            self.render_nested_lane(&mut output, RunnerMode::Velnor, unit, false, true);
        }
        output
    }

    fn render_workflow_env(&self, output: &mut String, unit: &Unit) {
        let tools = Self::tools_for_unit(unit, self.mise_rust);
        if tools.contains(&ToolRequirement::Sccache) || tools.contains(&ToolRequirement::OpenTofu) {
            output.push_str("\nenv:\n");
            if tools.contains(&ToolRequirement::Sccache) {
                output.push_str(
                    "  CARGO_INCREMENTAL: \"0\"\n  RUSTC_WRAPPER: sccache\n  SCCACHE_GHA_ENABLED: \"true\"\n",
                );
            }
            if tools.contains(&ToolRequirement::OpenTofu) {
                output.push_str("  TF_PLUGIN_CACHE_DIR: ~/.terraform.d/plugin-cache\n");
            }
        }
    }

    fn render_nested_lane(
        &self,
        output: &mut String,
        lane: RunnerMode,
        unit: &Unit,
        cache_save: bool,
        trusted: bool,
    ) {
        let id = lane.as_str();
        let _ = writeln!(output, "  {id}:\n    name: {}", lane.display_name());
        if trusted {
            let _ = writeln!(
                output,
                "    if: ${{{{ github.ref == 'refs/heads/{}' && (github.event_name == 'push' || github.event_name == 'schedule' || github.event_name == 'workflow_dispatch') }}}}",
                self.default_branch
            );
        }
        let _ = writeln!(
            output,
            "    runs-on: {}\n    timeout-minutes: 45\n    steps:",
            self.runner_for_unit(lane, unit)
        );
        let _ = writeln!(
            output,
            "      - name: Checkout\n        uses: {}\n        with:\n          persist-credentials: false",
            ActionPin::Checkout.reference()
        );
        Self::render_workflow_runtime_setup(output, lane);
        self.render_tool_provisioning(output, unit);
        if let Some(cache) = &unit.cache {
            let (paths, key) = rendered_cache_values(cache);
            let cache_key = format!(
                "ci-${{{{ runner.os }}}}-{}-${{{{ hashFiles({key}) }}}}",
                unit.id
            );
            let _ = writeln!(
                output,
                "      - name: Restore {} cache\n        id: cache\n        uses: {}\n        with:\n          path: |\n{paths}\n          key: {cache_key}\n          restore-keys: |\n            ci-${{{{ runner.os }}}}-{}-",
                yaml_scalar(&unit.label),
                ActionPin::CacheRestore.reference(),
                unit.id
            );
        }
        let _ = writeln!(
            output,
            "      - name: Run {} checks\n        env:\n          CI_SCOPE: ${{{{ inputs.scope }}}}\n          CI_UNIT_ID: {}\n          EVENT_NAME: ${{{{ github.event_name }}}}\n          BASE_SHA: ${{{{ github.event.pull_request.base.sha || github.event.merge_group.base_sha || github.event.before }}}}\n          HEAD_SHA: ${{{{ github.sha }}}}\n        run: velnor-workflow run --config .github/ci/project.toml --scope \"$CI_SCOPE\" --unit {}",
            yaml_scalar(&unit.label),
            yaml_scalar(&unit.id),
            yaml_scalar(&unit.id)
        );
        if cache_save
            && lane == RunnerMode::Github
            && let Some(cache) = unit.cache.as_ref()
        {
            let trusted_cache = format!(
                "(github.event_name == 'push' && github.ref == 'refs/heads/{}') || github.event_name == 'schedule' || (github.event_name == 'workflow_dispatch' && github.ref == 'refs/heads/{}')",
                self.default_branch, self.default_branch
            );
            let (paths, key) = rendered_cache_values(cache);
            let cache_key = format!(
                "ci-${{{{ runner.os }}}}-{}-${{{{ hashFiles({key}) }}}}",
                unit.id
            );
            let _ = writeln!(
                output,
                "      - name: Save {} cache\n        if: ({trusted_cache}) && steps.cache.outputs.cache-hit != 'true'\n        uses: {}\n        with:\n          path: |\n{paths}\n          key: {cache_key}",
                yaml_scalar(&unit.label),
                ActionPin::CacheSave.reference()
            );
        }
        output.push('\n');
    }

    fn runner_for(&self, lane: RunnerMode) -> String {
        match lane {
            RunnerMode::Github | RunnerMode::Both => yaml_scalar(&self.github_runner),
            RunnerMode::Velnor => velnor_runner(&self.velnor_labels),
        }
    }

    fn render_workflow_runtime_setup(output: &mut String, lane: RunnerMode) {
        output.push_str(&workflow_runtime_setup(lane));
    }

    fn render_plan(&self, output: &mut String, runners: RunnerMode, trusted: bool) {
        let gate = self.trusted_runner_gate(runners, trusted);
        let _ = writeln!(
            output,
            "  plan:\n    name: Planning\n{gate}    runs-on: {}\n    outputs:\n      scope: ${{{{ steps.plan.outputs.scope }}}}\n    steps:\n      - name: Checkout\n        uses: {}\n        with:\n          fetch-depth: 0\n          persist-credentials: false\n      - name: Install Velnor workflow runtime\n        if: ${{{{ runner.environment == 'github-hosted' }}}}\n        run: cargo install --locked --git {} --rev {} --package velnor-workflow --bin velnor-workflow\n      - name: Select affected units\n        id: plan\n        env:\n          EVENT_NAME: ${{{{ github.event_name }}}}\n          BASE_SHA: ${{{{ github.event.pull_request.base.sha || github.event.merge_group.base_sha || github.event.before }}}}\n          HEAD_SHA: ${{{{ github.sha }}}}\n        run: velnor-workflow plan --config .github/ci/project.toml\n",
            self.runner_for(runners),
            ActionPin::Checkout.reference(),
            VELNOR_WORKFLOW_REPOSITORY,
            VELNOR_WORKFLOW_SOURCE_REV,
        );
    }

    fn render_policy(&self, output: &mut String, runners: RunnerMode, trusted: bool) {
        let gate = self.trusted_runner_gate(runners, trusted);
        let _ = writeln!(
            output,
            "  policy:\n    name: Policy\n{gate}    runs-on: {}\n    steps:\n      - name: Checkout workflow data\n        uses: {}\n        with:\n          persist-credentials: false\n      - name: Install Velnor workflow runtime\n        if: ${{{{ runner.environment == 'github-hosted' }}}}\n        run: cargo install --locked --git {} --rev {} --package velnor-workflow --bin velnor-workflow\n      - name: Checkout trusted policy\n        uses: {}\n        continue-on-error: true\n        with:\n          ref: ${{{{ github.event.pull_request.base.sha || github.event.merge_group.base_sha || github.sha }}}}\n          path: .github-policy\n          persist-credentials: false\n      - name: Enforce workflow policy\n        env:\n          EVENT_NAME: ${{{{ github.event_name }}}}\n        run: velnor-workflow policy --workflow-root \"$GITHUB_WORKSPACE\"\n      - name: Enforce trusted workflow policy\n        env:\n          EVENT_NAME: ${{{{ github.event_name }}}}\n        run: velnor-workflow policy --workflow-root .github-policy",
            self.runner_for(runners),
            ActionPin::Checkout.reference(),
            VELNOR_WORKFLOW_REPOSITORY,
            VELNOR_WORKFLOW_SOURCE_REV,
            ActionPin::Checkout.reference(),
        );
    }

    fn trusted_runner_gate(&self, runners: RunnerMode, trusted: bool) -> String {
        if runners == RunnerMode::Velnor && trusted {
            format!(
                "    if: ${{{{ github.ref == 'refs/heads/{}' && (github.event_name == 'push' || github.event_name == 'schedule' || github.event_name == 'workflow_dispatch') }}}}\n",
                self.default_branch
            )
        } else {
            String::new()
        }
    }

    fn render_verify_github(&self, output: &mut String, condition: Option<&str>, cache_save: bool) {
        self.render_verify_lane(output, RunnerMode::Github, condition, cache_save);
    }

    fn render_verify_velnor(&self, output: &mut String, cache_save: bool) {
        // Self-hosted runners never receive untrusted pull-request code.
        let condition = Some(format!(
            "github.ref == 'refs/heads/{}' && (github.event_name == 'push' || github.event_name == 'schedule' || github.event_name == 'workflow_dispatch')",
            self.default_branch
        ));
        self.render_verify_lane(output, RunnerMode::Velnor, condition.as_deref(), cache_save);
    }

    fn render_hierarchy_groups(&self, output: &mut String) {
        let kinds = self
            .units
            .iter()
            .map(|unit| unit.kind)
            .collect::<BTreeSet<_>>();
        for kind in kinds {
            let group_id = stack_group_job_id(kind);
            let group_name = yaml_scalar(unit_group(kind));
            let _ = writeln!(output, "  {group_id}:\n    name: {group_name}");
            let _ = writeln!(
                output,
                "    needs: [plan, policy]\n    runs-on: {}\n    timeout-minutes: 5\n    steps:\n      - name: Admit {} jobs\n        run: echo 'group ready'\n",
                self.github_runner,
                unit_group(kind),
            );
            for unit in self.units.iter().filter(|unit| unit.kind == kind) {
                let child_id = unit_group_job_id(unit);
                let child_label = unit
                    .label
                    .strip_prefix("Rust crate (")
                    .and_then(|value| value.strip_suffix(')'))
                    .unwrap_or(&unit.label);
                let child_name = yaml_scalar(child_label);
                let _ = writeln!(
                    output,
                    "  {child_id}:\n    name: {child_name}\n    needs: [{group_id}]\n    runs-on: {}\n    timeout-minutes: 5\n    steps:\n      - name: Admit runner jobs\n        run: echo 'crate group ready'\n",
                    self.github_runner,
                );
            }
        }
    }

    fn render_verify_lane(
        &self,
        output: &mut String,
        lane: RunnerMode,
        condition: Option<&str>,
        cache_save: bool,
    ) {
        for unit in self
            .units
            .iter()
            .filter(|unit| lane_supports_unit(lane, unit))
        {
            let id = unit_job_id(lane, &unit.id);
            let lane_label = lane.display_name();
            let needs = unit_needs(lane, unit);
            let runner = self.runner_for_unit(lane, unit);
            let group = unit_group(unit.kind);
            let label = unit
                .label
                .strip_prefix("Rust crate (")
                .and_then(|value| value.strip_suffix(')'))
                .unwrap_or(&unit.label);
            let job_name = yaml_scalar(&format!("{lane_label} / {group} / {label}"));
            let verify_name = yaml_scalar(&unit.label);
            let _ = writeln!(output, "  {id}:\n    name: {job_name}");
            if let Some(condition) = condition {
                let _ = writeln!(output, "    if: ${{{{ {condition} }}}}");
            }
            let _ = writeln!(output, "    needs: [{}]", needs.join(", "));
            let _ = writeln!(
                output,
                "    runs-on: {runner}\n    timeout-minutes: 45\n    steps:",
            );
            let _ = writeln!(
                output,
                "      - name: Checkout\n        uses: {}\n        with:\n          persist-credentials: false",
                ActionPin::Checkout.reference(),
            );
            Self::render_workflow_runtime_setup(output, lane);
            self.render_tool_provisioning(output, unit);
            if let Some(cache) = &unit.cache {
                let (paths, key) = rendered_cache_values(cache);
                let cache_key = format!(
                    "ci-${{{{ runner.os }}}}-{}-${{{{ hashFiles({key}) }}}}",
                    unit.id
                );
                let _ = writeln!(
                    output,
                    "      - name: Restore {} cache\n        id: cache\n        uses: {}\n        with:\n          path: |\n{paths}\n          key: {cache_key}\n          restore-keys: |\n            ci-${{{{ runner.os }}}}-{}-",
                    verify_name,
                    ActionPin::CacheRestore.reference(),
                    unit.id,
                );
            }
            let _ = writeln!(
                output,
                "      - name: Run {} checks\n        env:\n          CI_SCOPE: ${{{{ needs.plan.outputs.scope }}}}\n          CI_UNIT_ID: {}\n          EVENT_NAME: ${{{{ github.event_name }}}}\n          BASE_SHA: ${{{{ github.event.pull_request.base.sha || github.event.merge_group.base_sha || github.event.before }}}}\n          HEAD_SHA: ${{{{ github.sha }}}}\n        run: velnor-workflow run --config .github/ci/project.toml --scope \"$CI_SCOPE\" --unit {}",
                verify_name,
                yaml_scalar(&unit.id),
                yaml_scalar(&unit.id),
            );
            if cache_save
                && lane == RunnerMode::Github
                && let Some(cache) = &unit.cache
            {
                let (paths, key) = rendered_cache_values(cache);
                let trusted_cache = format!(
                    "(github.event_name == 'push' && github.ref == 'refs/heads/{}') || github.event_name == 'schedule' || (github.event_name == 'workflow_dispatch' && github.ref == 'refs/heads/{}')",
                    self.default_branch, self.default_branch
                );
                let cache_key = format!(
                    "ci-${{{{ runner.os }}}}-{}-${{{{ hashFiles({key}) }}}}",
                    unit.id
                );
                let _ = writeln!(
                    output,
                    "      - name: Save {} cache\n        if: ({trusted_cache}) && steps.cache.outputs.cache-hit != 'true'\n        uses: {}\n        with:\n          path: |\n{paths}\n          key: {cache_key}",
                    verify_name,
                    ActionPin::CacheSave.reference(),
                );
            }
            output.push('\n');
        }
    }

    fn runner_for_unit(&self, lane: RunnerMode, unit: &Unit) -> String {
        if unit.kind == UnitKind::Swift && lane == RunnerMode::Github {
            return "macos-15".to_owned();
        }
        self.runner_for(lane)
    }

    fn tools_for_unit(unit: &Unit, mise_rust: bool) -> BTreeSet<ToolRequirement> {
        let mut tools = BTreeSet::new();
        match unit.kind {
            UnitKind::OpenTofu => {
                tools.insert(ToolRequirement::OpenTofu);
            }
            UnitKind::Homebrew => {
                tools.insert(ToolRequirement::Homebrew);
            }
            UnitKind::Bun => {
                tools.insert(ToolRequirement::Bun);
            }
            UnitKind::Node => {
                tools.insert(ToolRequirement::Node);
            }
            UnitKind::Gradle => {
                tools.insert(ToolRequirement::Gradle);
            }
            UnitKind::Rust => {
                if mise_rust {
                    tools.insert(ToolRequirement::Mise);
                }
                tools.insert(ToolRequirement::Sccache);
                tools.insert(ToolRequirement::Mold);
                let commands = unit.pr_commands.iter().chain(&unit.full_commands);
                if commands
                    .clone()
                    .any(|command| command.contains("cargo nextest"))
                {
                    tools.insert(ToolRequirement::Nextest);
                }
                if unit
                    .pr_commands
                    .iter()
                    .chain(&unit.full_commands)
                    .any(|command| command.contains("cargo deny"))
                {
                    tools.insert(ToolRequirement::CargoDeny);
                }
                if unit
                    .pr_commands
                    .iter()
                    .chain(&unit.full_commands)
                    .any(|command| command.contains("cargo audit"))
                {
                    tools.insert(ToolRequirement::CargoAudit);
                }
            }
            UnitKind::Docker => {
                tools.insert(ToolRequirement::DockerBuildx);
            }
            UnitKind::Swift | UnitKind::Docs => {}
        }
        tools
    }

    fn render_tool_provisioning(&self, output: &mut String, unit: &Unit) {
        let tools = Self::tools_for_unit(unit, self.mise_rust);
        if tools.contains(&ToolRequirement::Mise) {
            let _ = writeln!(
                output,
                "      - name: Set up Mise Rust toolchain\n        uses: {}\n        with:\n          install_args: rust\n          cache: true",
                ActionPin::Mise.reference()
            );
        }
        if tools.contains(&ToolRequirement::Bun) {
            if let Some(bun_version) = unit.tool_version.as_deref() {
                let _ = writeln!(
                    output,
                    "      - name: Set up Bun\n        uses: {}\n        with:\n          bun-version: {bun_version}",
                    ActionPin::Bun.reference()
                );
            } else {
                let _ = writeln!(
                    output,
                    "      - name: Set up Bun\n        uses: {}",
                    ActionPin::Bun.reference()
                );
            }
        }
        if tools.contains(&ToolRequirement::Node) {
            let cache_manager = "npm";
            let cache_dependency_path = unit.cache.as_ref().and_then(|cache| {
                cache
                    .key_files
                    .iter()
                    .find(|path| path.ends_with("package-lock.json"))
            });
            let cache_options = cache_dependency_path.map_or_else(
                || "\n          package-manager-cache: false".to_owned(),
                |path| {
                    format!(
                        "\n          cache: {cache_manager}\n          cache-dependency-path: {}",
                        yaml_scalar(path)
                    )
                },
            );
            let _ = writeln!(
                output,
                "      - name: Set up Node.js\n        uses: {}\n        with:\n          node-version: lts/*{cache_options}",
                ActionPin::Node.reference()
            );
        }
        if tools.contains(&ToolRequirement::Nextest) {
            let _ = writeln!(
                output,
                "      - name: Set up cargo-nextest\n        uses: {}\n        with:\n          tool: nextest\n          fallback: none",
                ActionPin::RustTool.reference()
            );
        }
        if tools.contains(&ToolRequirement::CargoDeny) {
            let _ = writeln!(
                output,
                "      - name: Set up cargo-deny\n        uses: {}\n        with:\n          tool: cargo-deny\n          fallback: none",
                ActionPin::RustTool.reference()
            );
        }
        if tools.contains(&ToolRequirement::CargoAudit) {
            let _ = writeln!(
                output,
                "      - name: Set up cargo-audit\n        uses: {}\n        with:\n          tool: cargo-audit\n          fallback: none",
                ActionPin::RustTool.reference()
            );
        }
        if tools.contains(&ToolRequirement::Gradle) {
            let _ = writeln!(
                output,
                "      - name: Set up Gradle\n        uses: {}",
                ActionPin::Gradle.reference()
            );
        }
        if tools.contains(&ToolRequirement::Sccache) {
            let _ = writeln!(
                output,
                "      - name: Set up sccache\n        uses: {}\n        with:\n          version: v0.16.0",
                ActionPin::Sccache.reference()
            );
        }
        if tools.contains(&ToolRequirement::Mold) {
            let _ = writeln!(
                output,
                "      - name: Set up mold\n        uses: {}\n        with:\n          make-default: true",
                ActionPin::Mold.reference()
            );
        }
        if tools.contains(&ToolRequirement::DockerBuildx) {
            let _ = writeln!(
                output,
                "      - name: Set up Docker Buildx\n        uses: {}",
                ActionPin::DockerBuildx.reference()
            );
        }
        if tools.contains(&ToolRequirement::OpenTofu) {
            let _ = writeln!(
                output,
                "      - name: Set up OpenTofu\n        uses: {}\n        with:\n          tofu_version: {}\n          tofu_wrapper: false",
                ActionPin::OpenTofuSetup.reference(),
                OPEN_TOFU_VERSION,
            );
        }
        if tools.contains(&ToolRequirement::Homebrew) {
            output.push_str(
                "      - name: Prepare Linuxbrew path\n        shell: bash\n        run: |\n          set -euo pipefail\n          if command -v brew >/dev/null 2>&1; then\n            exit 0\n          fi\n          linuxbrew_bin=/home/linuxbrew/.linuxbrew/bin\n          linuxbrew_sbin=/home/linuxbrew/.linuxbrew/sbin\n          if [[ ! -x \"$linuxbrew_bin/brew\" ]]; then\n            printf '%s\\n' 'Homebrew unavailable: install brew or expose it on PATH' >&2\n            exit 1\n          fi\n          [[ -n \"${GITHUB_PATH:-}\" ]] || { printf '%s\\n' 'GITHUB_PATH is unavailable' >&2; exit 1; }\n          printf '%s\\n%s\\n' \"$linuxbrew_bin\" \"$linuxbrew_sbin\" >> \"$GITHUB_PATH\"\n",
            );
        }
    }

    fn render_required(
        &self,
        output: &mut String,
        runners: RunnerMode,
        stable: bool,
        trusted: bool,
    ) {
        let check_name = if stable { "required" } else { "main" };
        let lanes = match runners {
            RunnerMode::Github => vec![RunnerMode::Github],
            RunnerMode::Velnor => vec![RunnerMode::Velnor],
            RunnerMode::Both => vec![RunnerMode::Github, RunnerMode::Velnor],
        };
        let mut needs = vec!["plan".to_owned(), "policy".to_owned()];
        let mut statuses = Vec::new();
        for lane in lanes {
            for unit in self
                .units
                .iter()
                .filter(|unit| lane_supports_unit(lane, unit))
            {
                let id = unit_job_id(lane, &unit.id);
                needs.push(id.clone());
                let status = format!("needs['{id}'].result");
                statuses.push(if lane == RunnerMode::Velnor {
                    format!("({status} == 'success' || {status} == 'skipped')")
                } else {
                    format!("{status} == 'success'")
                });
            }
        }
        let status_condition = if statuses.is_empty() {
            "true".to_owned()
        } else {
            statuses.join(" && ")
        };
        let gate = if runners == RunnerMode::Velnor && trusted {
            format!(
                "always() && github.ref == 'refs/heads/{}' && (github.event_name == 'push' || github.event_name == 'schedule' || github.event_name == 'workflow_dispatch') && {status_condition}",
                self.default_branch
            )
        } else {
            format!("always() && {status_condition}")
        };
        let _ = writeln!(
            output,
            "  required:\n    name: {check_name}\n    if: ${{{{ {gate} }}}}\n    needs: [{}]\n    runs-on: {}\n    timeout-minutes: 5\n    steps:\n      - name: All unit jobs passed\n        run: echo 'all generated CI units passed'",
            needs.join(", "),
            self.runner_for(runners),
        );
    }
}

