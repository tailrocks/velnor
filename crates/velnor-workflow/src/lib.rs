/// The static-template placeholder for the pinned-toolchain steps a lane
/// provisions without saving the cache, and the placeholder for the steps a
/// trusted default-branch push also saves under. Both are filled from the one
/// shared renderer every other rendering path uses, so a static workflow body
/// can never hand-write its own toolchain contract.
const PINNED_TOOLCHAIN_STEPS_PLACEHOLDER: &str = "__VELNOR_PINNED_TOOLCHAIN_STEPS__";
const TRUSTED_PINNED_TOOLCHAIN_STEPS_PLACEHOLDER: &str =
    "__VELNOR_TRUSTED_PINNED_TOOLCHAIN_STEPS__";

/// The Rust toolchain a config's units record, when any Rust unit does. The
/// scan stamps every Rust unit with the repository's parsed pin, so this is
/// `None` only for a config that carries no Rust units or no recorded pin —
/// and every consumer of the fact fails closed on the latter.
pub(crate) fn config_rust_toolchain(config: &ProjectConfig) -> Option<RustToolchain> {
    config
        .units
        .iter()
        .find_map(|unit| {
            (unit.kind == UnitKind::Rust)
                .then_some(unit.toolchain.as_ref())
                .flatten()
        })
        .cloned()
}

/// The `__VELNOR_…__` markers a rendered template still carries. A marker a
/// body misspells survives rendering untouched, and `--check` stays green
/// because both sides regenerate from the same typo — so the renderer itself
/// must refuse it. The marker ends at the closing `__`, or at the end of the
/// line when the closing delimiter is missing.
fn unresolved_velnor_markers(rendered: &str) -> Vec<String> {
    let mut markers = Vec::new();
    let mut rest = rendered;
    while let Some(start) = rest.find("__VELNOR_") {
        let tail = &rest[start..];
        let end = tail
            .split_once('\n')
            .map_or(tail.len(), |(line, _)| line.len())
            .min(tail[2..].find("__").map_or(tail.len(), |offset| offset + 4));
        let marker = tail[..end].to_owned();
        if !markers.contains(&marker) {
            markers.push(marker);
        }
        rest = &rest[start + end..];
    }
    markers
}

/// Fill the pinned-toolchain placeholders a static template declares with the
/// steps the shared renderer emits for the repository's own pin. Templates
/// without a placeholder render unchanged, so only a body that declares the
/// toolchain contract can demand a pin — and it fails closed when the
/// repository records none.
///
/// # Errors
/// Returns a usage error when the repository records no Rust pin despite a
/// template demanding one, or when any `__VELNOR_` marker survives rendering.
pub(crate) fn render_pinned_toolchain_fill(
    config: &ProjectConfig,
    template: &str,
) -> Result<String, GeneratorError> {
    let rendered = if template.contains(PINNED_TOOLCHAIN_STEPS_PLACEHOLDER)
        || template.contains(TRUSTED_PINNED_TOOLCHAIN_STEPS_PLACEHOLDER)
    {
        let Some(toolchain) = config_rust_toolchain(config) else {
            return Err(GeneratorError::usage(
                "a static workflow template declares the pinned Rust toolchain contract, but the \
                 repository pins no Rust toolchain; add rust-toolchain.toml with a [toolchain] \
                 channel (plus any components and targets) so every workflow provisions exactly \
                 that toolchain",
            ));
        };
        let mut pinned = String::new();
        primitives::render_pinned_toolchain_steps(
            &mut pinned,
            ActionPin::CacheRestore.reference(),
            ActionPin::CacheSave.reference(),
            &toolchain,
            None,
        );
        // Preview builds run only from trusted pushes to the default branch, so
        // that — and nothing broader — is what may save the toolchain cache.
        let mut trusted = String::new();
        primitives::render_pinned_toolchain_steps(
            &mut trusted,
            ActionPin::CacheRestore.reference(),
            ActionPin::CacheSave.reference(),
            &toolchain,
            Some(&format!(
                "github.event_name == 'push' && github.ref == 'refs/heads/{}' && steps.rustup-toolchain.outputs.cache-hit != 'true'",
                config.default_branch
            )),
        );
        template
            .replace(
                TRUSTED_PINNED_TOOLCHAIN_STEPS_PLACEHOLDER,
                trusted.trim_end_matches('\n'),
            )
            .replace(
                PINNED_TOOLCHAIN_STEPS_PLACEHOLDER,
                pinned.trim_end_matches('\n'),
            )
    } else {
        template.to_owned()
    };
    let markers = unresolved_velnor_markers(&rendered);
    if markers.is_empty() {
        return Ok(rendered);
    }
    Err(GeneratorError::usage(format!(
        "the rendered workflow still contains unresolved template markers ({}); a misspelled \
         placeholder would ship its literal text into a committed workflow and stay invisible \
         to regeneration checks, so generation refuses it",
        markers.join(", ")
    )))
}

/// Every Rust unit renders the pinned-toolchain contract on its hosted lane; a
/// unit without a recorded pin would silently render steps that provision
/// whatever rustup resolves. The scan refuses an unpinned Rust repository, so
/// generation is the last point at which a hand-built config can be caught.
fn validate_rust_units_are_pinned(config: &ProjectConfig) -> Result<(), GeneratorError> {
    if config
        .units
        .iter()
        .any(|unit| unit.kind == UnitKind::Rust && unit.toolchain.is_none())
    {
        return Err(GeneratorError::usage(
            "a Rust unit records no toolchain pin; add rust-toolchain.toml with a [toolchain] \
             channel (plus any components and targets) so every workflow provisions exactly \
             that toolchain",
        ));
    }
    Ok(())
}

/// The release matrices build for the targets the contract names, so the
/// repository's pin must declare every one of them: the file-driven install
/// provisions the pin's targets, and a target the pin omits would surface as
/// a broken build lane instead of a refused contract.
fn validate_release_targets_are_pinned(config: &ProjectConfig) -> Result<(), GeneratorError> {
    let Some(release) = &config.release else {
        return Ok(());
    };
    if release.targets.is_empty() {
        return Ok(());
    }
    let Some(toolchain) = config_rust_toolchain(config) else {
        return Err(GeneratorError::usage(format!(
            "the release contract builds for {} but the repository pins no Rust toolchain; add \
             rust-toolchain.toml with a [toolchain] channel declaring those targets",
            release.targets.join(", ")
        )));
    };
    let missing = release
        .targets
        .iter()
        .filter(|target| !toolchain.targets.iter().any(|pinned| pinned == *target))
        .map(String::as_str)
        .collect::<Vec<_>>()
        .join(", ");
    if !missing.is_empty() {
        return Err(GeneratorError::usage(format!(
            "the release contract builds for {} but the pinned Rust toolchain does not declare \
             {}; add the missing targets to rust-toolchain.toml so every build lane provisions \
             them",
            release.targets.join(", "),
            missing
        )));
    }
    Ok(())
}

/// # Errors
/// Returns a usage error when the template declares the pinned-toolchain
/// contract and the repository records no Rust pin.
fn render_static_template_for_config(
    config: &ProjectConfig,
    workflow_file: &str,
    template: &str,
) -> Result<String, GeneratorError> {
    let template = if workflow_file == PACKAGE_UPDATER_WORKFLOW {
        estate::render_apt_package_updater_template(
            template,
            &config.default_branch,
            &config.github_runner,
            &config.velnor_labels,
            velnor_runner_group(config),
        )
    } else if workflow_file == PACKAGE_UPDATE_WORKFLOW {
        estate::render_apt_package_update_template(config, template)
    } else {
        template.to_owned()
    };
    let template = if let Some(group) = velnor_runner_group(config) {
        let labels = config
            .velnor_labels
            .iter()
            .map(|label| yaml_scalar(label))
            .collect::<Vec<_>>()
            .join(",");
        let selector = format!(
            "fromJSON('{{\"group\":{group},\"labels\":[{labels}]}}')",
            group = yaml_scalar(group)
        );
        template.replace(crate::estate::LEGACY_VELNOR_RUNNER_SELECTOR, &selector)
    } else {
        template
    };
    render_pinned_toolchain_fill(config, &render_static_template(&template))
}

