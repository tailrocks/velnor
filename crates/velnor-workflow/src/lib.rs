/// Why a cache entry exists. Caches are classified by purpose, never by one
/// mutually exclusive backend: a compiler-object transport and a Cargo-source
/// cache answer different questions and must be able to coexist.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
pub(crate) enum CachePurpose {
    /// Registry archives, extracted sources, and Git dependencies. Restoring
    /// them never duplicates a compiler cache: no build outputs travel here.
    CargoSources,
    /// Raw build outputs (`target` trees and friends). Alongside a
    /// compiler-object transport this duplicates workspace state, so the
    /// generator rejects it unless `mbx_output_cache_justification` records
    /// why both transports are kept.
    Outputs,
    /// Tool or package-manager state unrelated to Rust compilation.
    Generic,
    /// The rustup-provisioned toolchain tree (`~/.rustup`). Generator-internal:
    /// it is keyed by the repository's toolchain pin and never appears in a
    /// unit's declared cache contract, so it never reaches the cache-transport
    /// validation a unit contract passes through.
    Toolchains,
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize)]
struct CacheSpec {
    pub(crate) key_files: Vec<String>,
    pub(crate) paths: Vec<String>,
    pub(crate) purpose: CachePurpose,
    /// Why an [`CachePurpose::Outputs`] cache is kept alongside the
    /// Mr. Boxington object transport. Required and non-empty in that
    /// combination; the justification is rendered next to the cache steps.
    pub(crate) mbx_output_cache_justification: Option<String>,
}

impl CacheSpec {
    /// Whether this spec keeps a raw output cache alongside the Mr. Boxington
    /// object transport, with the justification that makes that legal.
    pub(crate) fn justified_output_alongside_mr_boxington(&self) -> bool {
        self.purpose == CachePurpose::Outputs
            && self
                .mbx_output_cache_justification
                .as_deref()
                .is_some_and(|justification| !justification.trim().is_empty())
    }
}

