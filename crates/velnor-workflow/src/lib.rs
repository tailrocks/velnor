    /// Every file under `.github`, by relative path, so a test can prove the
    /// generated bytes did not move across a state-file migration.
    fn generated_tree(root: &Path) -> BTreeMap<String, String> {
        let mut tree = BTreeMap::new();
        let mut pending = vec![PathBuf::from(".github")];
        while let Some(relative) = pending.pop() {
            let path = root.join(&relative);
            let metadata = must(fs::symlink_metadata(&path), "inspect generated path");
            if metadata.is_dir() {
                for entry in must(fs::read_dir(&path), "read generated directory") {
                    let entry = must(entry, "read generated directory entry");
                    pending.push(relative.join(entry.file_name()));
                }
            } else if metadata.is_file() {
                tree.insert(
                    relative.display().to_string(),
                    must(fs::read_to_string(&path), "read generated file"),
                );
            }
        }
        tree
    }

