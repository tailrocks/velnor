/// The generated workflow file name for a class: `ci-<class>.yml`.
#[must_use]
pub fn callable_file_name(class: RepositoryClass) -> String {
    format!("ci-{}.yml", class.code())
}

struct Builder {
    lines: Vec<String>,
}

impl Builder {
    fn new() -> Builder {
        Builder { lines: Vec::new() }
    }

    fn line(&mut self, indent: usize, text: &str) {
        if text.is_empty() {
            self.lines.push(String::new());
        } else {
            self.lines.push(format!("{}{}", " ".repeat(indent), text));
        }
    }

    fn blank(&mut self) {
        self.lines.push(String::new());
    }

    /// Emit a `run: |` block: the key at `indent`, script body at `indent + 2`.
    fn run_block(&mut self, indent: usize, script: &str) {
        self.line(indent, "run: |");
        for l in script.lines() {
            if l.is_empty() {
                self.lines.push(String::new());
            } else {
                self.lines.push(format!("{}{}", " ".repeat(indent + 2), l));
            }
        }
    }

    fn finish(self) -> String {
        let mut out = self.lines.join("\n");
        out.push('\n');
        out
    }
}

/// Render the committed consumer template for a class. The three owner-local
/// reusable-workflow calls bind their owner-local mirror commit and share one
/// anchored `@CALVER@`; `render_consumer` replaces all four tokens together.
#[must_use]
pub fn consumer_template(class: RepositoryClass) -> String {
    let file = callable_file_name(class);
    let mut b = Builder::new();
    b.line(0, "# Generated by velnor-actions-generator. DO NOT EDIT.");
    b.line(0, "#");
    b.line(
        0,
        &format!(
            "# Canonical consumer template for the {} class. Every {} repository renders",
            class.code(),
            class.code()
        ),
    );
    b.line(
        0,
        "# this same file (byte-identical within the class) as .github/workflows/ci.yml.",
    );
    b.line(
        0,
        "# The three owner-local reusable-workflow calls are selected solely by",
    );
    b.line(
        0,
        "# github.repository_owner: exactly one runs and the other two skip. The shared",
    );
    b.line(
        0,
        "# owner-local release SHA pins and one CalVer version identify one mirrored release",
    );
    b.line(
        0,
        "# and are replaced together at release time by render-consumer.",
    );
    b.line(0, "name: CI");
    b.line(0, "run-name: ${{ inputs.recovery_proof_id != '' && format('CI recovery {0}', inputs.recovery_proof_id) || inputs.benchmark_campaign != '' && format('CI benchmark {0}/{1}', inputs.benchmark_campaign, inputs.benchmark_wave) || inputs.cache_proof_id != '' && format('CI cache proof {0}', inputs.cache_proof_id) || 'CI' }}");
    b.blank();
    b.line(0, "on:");
    b.line(2, "pull_request:");
    b.line(2, "push:");
    b.line(4, "branches:");
    b.line(6, "- main");
    b.line(4, "tags:");
    b.line(6, "- \"**\"");
    b.line(2, "merge_group:");
    b.line(2, "schedule:");
    b.line(4, "- cron: \"23 3 * * 0\"");
    b.line(2, "workflow_dispatch:");
    b.line(4, "inputs:");
    b.line(6, "lane:");
    b.line(8, "description: \"Optional CI lane: github, velnor, or both. Empty uses organization default.\"");
    b.line(8, "required: false");
    b.line(8, "type: string");
    b.line(8, "default: \"\"");
    consumer_auxiliary_inputs(&mut b);
    b.blank();
    b.line(0, "permissions:");
    b.line(2, "actions: read");
    b.line(2, "contents: read");
    b.line(2, "pull-requests: read");
    b.blank();
    b.line(0, "concurrency:");
    b.line(2, "group: ${{ inputs.benchmark_campaign != '' && format('{0}-{1}-{2}', github.workflow, inputs.benchmark_campaign, inputs.benchmark_wave) || format('{0}-{1}', github.workflow, github.ref) }}");
    b.line(
        2,
        "cancel-in-progress: ${{ inputs.benchmark_campaign == '' }}",
    );
    b.blank();
    b.line(0, "jobs:");

    for (owner, release_placeholder) in OWNERS.iter().zip(OWNER_SHA_PLACEHOLDERS) {
        b.line(2, &format!("{owner}:"));
        b.line(4, &format!("name: {owner}"));
        b.line(
            4,
            &format!("if: ${{{{ github.repository_owner == '{owner}' }}}}"),
        );
        b.line(4, "permissions:");
        b.line(6, "actions: read");
        b.line(6, "contents: read");
        b.line(6, "pull-requests: read");
        b.line(
            4,
            &format!(
                "uses: {owner}/{ACTIONS_REPO}/.github/workflows/{file}{release_placeholder} # {CALVER_PLACEHOLDER}"
            ),
        );
        b.line(4, "with:");
        b.line(
            6,
            "lane: ${{ (github.event_name == 'schedule' && 'both') || (github.event_name == 'workflow_dispatch' && inputs.lane != '' && inputs.lane) || (github.repository_owner == 'jackin-project' && 'github') || ((github.repository_owner == 'tailrocks' || github.repository_owner == 'ChainArgos') && 'velnor') || 'invalid' }}",
        );
        for input in AUXILIARY_INPUTS {
            b.line(6, &format!("{input}: ${{{{ inputs.{input} || '' }}}}"));
        }
        b.blank();
    }

    // ci-required aggregator: fail-closed positive truth table.
    b.line(2, "ci-required:");
    b.line(4, "name: ci-required");
    b.line(4, "needs:");
    for owner in OWNERS {
        b.line(6, &format!("- {owner}"));
    }
    b.line(4, "if: ${{ always() }}");
    // actionlint v1.7.12 does not yet recognize the Ubuntu 26.04 hosted label
    // when it is a literal. Keep the exact runtime binding while allowing
    // every consumer repository to lint the generated caller without local
    // actionlint configuration.
    b.line(4, "runs-on: ${{ 'ubuntu-26.04' }}");
    b.line(4, "timeout-minutes: 10");
    b.line(4, "permissions:");
    b.line(6, "contents: read");
    b.line(4, "steps:");
    b.line(6, "- name: Enforce fleet contract");
    b.line(8, "env:");
    b.line(10, "OWNER: ${{ github.repository_owner }}");
    b.line(
        10,
        "JACKIN_PROJECT_RESULT: ${{ needs.jackin-project.result }}",
    );
    b.line(
        10,
        "JACKIN_PROJECT_CONTRACT: ${{ needs.jackin-project.outputs.contract }}",
    );
    b.line(10, "TAILROCKS_RESULT: ${{ needs.tailrocks.result }}");
    b.line(
        10,
        "TAILROCKS_CONTRACT: ${{ needs.tailrocks.outputs.contract }}",
    );
    b.line(10, "CHAINARGOS_RESULT: ${{ needs.ChainArgos.result }}");
    b.line(
        10,
        "CHAINARGOS_CONTRACT: ${{ needs.ChainArgos.outputs.contract }}",
    );
    b.line(8, "shell: bash");
    b.run_block(8, CI_REQUIRED_SCRIPT);

    b.finish()
}

/// Render the owner-local callable workflow for a class, pinning its internal
/// composite closure to `block_sha` (a validated 40-hex SHA).
#[must_use]
pub fn callable_workflow(
    contract: &ClassContract,
    caches: &CacheContract,
    block_sha: &str,
) -> String {
    let class = contract.class;
    let run_gate = format!("{CANONICAL_OWNER}/{ACTIONS_REPO}/actions/run-gate@{block_sha}");
    let aggregate = format!("{CANONICAL_OWNER}/{ACTIONS_REPO}/actions/aggregate@{block_sha}");

    let mut b = Builder::new();
    b.line(0, "# Generated by velnor-actions-generator. DO NOT EDIT.");
    b.line(
        0,
        &format!(
            "# Cache declaration SHA-256: {}",
            caches.declaration_sha256()
        ),
    );
    b.line(0, "#");
    b.line(
        0,
        &format!(
            "# Owner-local reusable CI workflow for the {} class. Consumers call their own",
            class.code()
        ),
    );
    b.line(
        0,
        "# organization's mirror of this file. It owns the lane jobs, runs identical gate",
    );
    b.line(
        0,
        "# commands on either lane through the run-gate building block, and emits the lane",
    );
    b.line(
        0,
        "# contract only after every applicable gate genuinely succeeds. It inherits no",
    );
    b.line(
        0,
        "# secrets and no environment. The internal composite closure is pinned to the",
    );
    b.line(0, "# immutable block SHA recorded in fleet/block-sha.");
    b.line(0, &format!("name: ci-{}", class.code()));
    b.blank();
    b.line(0, "on:");
    b.line(2, "workflow_call:");
    b.line(4, "inputs:");
    b.line(6, "lane:");
    b.line(
        8,
        "description: \"CI lane: github, velnor, or both; empty derives from owner.\"",
    );
    b.line(8, "required: false");
    b.line(8, "type: string");
    b.line(8, "default: \"\"");
    callable_auxiliary_inputs(&mut b);
    b.line(4, "outputs:");
    b.line(6, "contract:");
    b.line(
        8,
        "description: \"'success' only when every selected lane passed its applicable gates.\"",
    );
    b.line(8, "value: ${{ jobs.contract.outputs.contract }}");
    b.line(6, "correlation:");
    b.line(
        8,
        "description: \"Authenticated recovery, benchmark, or cache-proof correlation.\"",
    );
    b.line(8, "value: ${{ jobs.validate-request.outputs.correlation }}");
    b.line(6, "workflow_blob:");
    b.line(
        8,
        "description: \"Git blob identity of the authenticated generated caller.\"",
    );
    b.line(
        8,
        "value: ${{ jobs.validate-request.outputs.workflow_blob }}",
    );
    b.blank();
    b.line(0, "permissions:");
    b.line(2, "actions: read");
    b.line(2, "contents: read");
    b.blank();
    b.line(0, "jobs:");
    b.line(2, "validate-request:");
    b.line(4, "name: validate request");
    b.line(4, "runs-on: ubuntu-26.04");
    b.line(4, "timeout-minutes: 5");
    b.line(4, "permissions:");
    b.line(6, "actions: read");
    b.line(6, "contents: read");
    b.line(6, "pull-requests: read");
    b.line(4, "outputs:");
    b.line(6, "correlation: ${{ steps.validate.outputs.correlation }}");
    b.line(
        6,
        "workflow_blob: ${{ steps.validate.outputs.workflow_blob }}",
    );
    b.line(
        6,
        "cache_namespace: ${{ steps.validate.outputs.cache_namespace }}",
    );
    b.line(4, "steps:");
    b.line(6, "- name: Authenticate optional operation");
    b.line(8, "id: validate");
    b.line(8, "shell: bash");
    b.line(8, "env:");
    for input in AUXILIARY_INPUTS {
        b.line(
            10,
            &format!("{}: ${{{{ inputs.{input} }}}}", input.to_ascii_uppercase()),
        );
    }
    b.line(10, "EVENT_NAME: ${{ github.event_name }}");
    b.line(10, "REF_TYPE: ${{ github.ref_type }}");
    b.line(10, "REF_PROTECTED: ${{ github.ref_protected }}");
    b.line(10, "REF_NAME: ${{ github.ref_name }}");
    b.line(10, "HEAD_SHA: ${{ github.sha }}");
    b.line(10, "WORKFLOW_SHA: ${{ github.workflow_sha }}");
    b.line(10, "GH_TOKEN: ${{ github.token }}");
    b.line(10, "REPOSITORY: ${{ github.repository }}");
    b.line(10, "RUN_ID: ${{ github.run_id }}");
    b.line(
        10,
        &format!(
            "EXPECTED_CALLER_TEMPLATE_SHA256: {}",
            hex::encode(Sha256::digest(consumer_template(class).as_bytes()))
        ),
    );
    let cache_ids = caches
        .declarations()
        .iter()
        .filter(|cache| cache.class == class)
        .map(|cache| cache.id.as_str())
        .collect::<Vec<_>>()
        .join(",");
    b.line(10, &format!("DECLARED_CACHE_IDS: {cache_ids}"));
    b.run_block(8, VALIDATE_REQUEST_SCRIPT);
    b.blank();

    // Velnor lane.
    b.line(2, "velnor-lane:");
    b.line(4, "name: velnor lane");
    b.line(4, "needs: validate-request");
    b.line(
        4,
        "if: ${{ inputs.benchmark_campaign == '' && inputs.cache_proof_id == '' && (inputs.lane == 'velnor' || inputs.lane == 'both' || (inputs.lane == '' && (github.repository_owner == 'tailrocks' || github.repository_owner == 'ChainArgos'))) }}",
    );
    b.line(
        4,
        "# Public unmerged-code events (pull_request, merge_group) route the Velnor lane",
    );
    b.line(
        4,
        "# to GitHub-hosted execution until a live-proven lower-trust Velnor pool exists.",
    );
    b.line(4, "# This is explicit policy routing, not silent failover.");
    b.line(
        4,
        "runs-on: ${{ (github.event_name == 'pull_request' || github.event_name == 'merge_group') && 'ubuntu-26.04' || 'velnor-trusted' }}",
    );
    b.line(4, "timeout-minutes: 30");
    b.line(4, "outputs:");
    b.line(6, "contract: ${{ steps.aggregate.outputs.contract }}");
    b.line(4, "steps:");
    b.line(6, "- name: Report Velnor lane routing policy");
    b.line(
        8,
        "if: ${{ github.event_name == 'pull_request' || github.event_name == 'merge_group' }}",
    );
    b.line(8, "shell: bash");
    b.run_block(
        8,
        "echo 'policy: public unmerged-code routes the Velnor lane to GitHub-hosted execution'",
    );
    lane_steps(
        &mut b,
        contract,
        caches,
        Lane::Velnor,
        &run_gate,
        &aggregate,
    );
    b.blank();

    // GitHub-hosted lane.
    b.line(2, "github-lane:");
    b.line(4, "name: github lane");
    b.line(4, "needs: validate-request");
    b.line(
        4,
        "if: ${{ inputs.benchmark_campaign == '' && inputs.cache_proof_id == '' && (inputs.lane == 'github' || inputs.lane == 'both' || (inputs.lane == '' && github.repository_owner == 'jackin-project')) }}",
    );
    b.line(4, "runs-on: ubuntu-26.04");
    b.line(4, "timeout-minutes: 30");
    b.line(4, "outputs:");
    b.line(6, "contract: ${{ steps.aggregate.outputs.contract }}");
    b.line(4, "steps:");
    lane_steps(
        &mut b,
        contract,
        caches,
        Lane::GitHub,
        &run_gate,
        &aggregate,
    );
    b.blank();

    if contract.platform_only {
        let platform_name = contract
            .platform_name
            .as_deref()
            .expect("validated platform class has a check name");
        let platform_runner = contract
            .platform_runner
            .as_deref()
            .expect("validated platform class has a runner");
        b.line(2, "platform-lane:");
        b.line(4, &format!("name: {platform_name}"));
        b.line(4, "needs: validate-request");
        b.line(4, &format!("runs-on: {platform_runner}"));
        b.line(4, "timeout-minutes: 30");
        b.line(4, "outputs:");
        b.line(6, "contract: ${{ steps.aggregate.outputs.contract }}");
        b.line(4, "steps:");
        b.line(6, "- name: Check out repository");
        b.line(
            8,
            &format!("uses: actions/checkout@{CHECKOUT_REF} # {CHECKOUT_VERSION}"),
        );
        b.line(6, "- name: Set up mise toolchain");
        b.line(
            8,
            &format!("uses: jdx/mise-action@{MISE_ACTION_REF} # {MISE_ACTION_VERSION}"),
        );
        for gate in &contract.gates {
            if gate.applicability == crate::model::Applicability::Github {
                gate_step(&mut b, gate, &run_gate);
            }
        }
        b.line(6, "- name: Emit platform contract");
        b.line(8, "id: aggregate");
        b.line(8, &format!("uses: {aggregate}"));
        b.blank();
    }

    render_cache_proof_jobs(&mut b, contract, caches, block_sha, &run_gate, &aggregate);

    // Lane-verdict aggregator: fail-closed positive per-lane truth table.
    b.line(2, "contract:");
    b.line(4, "name: contract");
    b.line(4, "needs:");
    b.line(6, "- velnor-lane");
    b.line(6, "- github-lane");
    if contract.platform_only {
        b.line(6, "- platform-lane");
    }
    b.line(6, "- cache-proof-contract");
    b.line(4, "if: ${{ always() }}");
    b.line(4, "runs-on: ubuntu-26.04");
    b.line(4, "timeout-minutes: 10");
    b.line(4, "outputs:");
    b.line(6, "contract: ${{ steps.verdict.outputs.contract }}");
    b.line(4, "steps:");
    b.line(6, "- name: Aggregate lane verdict");
    b.line(8, "id: verdict");
    b.line(8, "env:");
    b.line(10, "LANE: ${{ inputs.lane != '' && inputs.lane || (github.repository_owner == 'jackin-project' && 'github') || ((github.repository_owner == 'tailrocks' || github.repository_owner == 'ChainArgos') && 'velnor') || 'invalid' }}");
    b.line(10, "VELNOR_RESULT: ${{ needs.velnor-lane.result }}");
    b.line(
        10,
        "VELNOR_CONTRACT: ${{ needs.velnor-lane.outputs.contract }}",
    );
    b.line(10, "GITHUB_RESULT: ${{ needs.github-lane.result }}");
    b.line(
        10,
        "GITHUB_CONTRACT: ${{ needs.github-lane.outputs.contract }}",
    );
    b.line(
        10,
        &format!("PLATFORM_REQUIRED: {}", contract.platform_only),
    );
    if contract.platform_only {
        b.line(10, "PLATFORM_RESULT: ${{ needs.platform-lane.result }}");
        b.line(
            10,
            "PLATFORM_CONTRACT: ${{ needs.platform-lane.outputs.contract }}",
        );
    } else {
        b.line(10, "PLATFORM_RESULT: skipped");
        b.line(10, "PLATFORM_CONTRACT: \"\"");
    }
    b.line(10, "OPERATION: ${{ inputs.benchmark_campaign != '' && 'benchmark' || inputs.cache_proof_id != '' && 'cache-proof' || 'ordinary' }}");
    b.line(
        10,
        "CACHE_PROOF_RESULT: ${{ needs.cache-proof-contract.result }}",
    );
    b.line(
        10,
        "CACHE_PROOF_CONTRACT: ${{ needs.cache-proof-contract.outputs.contract }}",
    );
    b.line(8, "shell: bash");
    b.run_block(8, CONTRACT_VERDICT_SCRIPT);

    b.finish()
}

