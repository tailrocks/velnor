fn fixed_roots(cache: &CacheDeclaration) -> String {
    cache
        .paths
        .iter()
        .map(|path| format!("'{path}'"))
        .collect::<Vec<_>>()
        .join(" ")
}

fn clean_cache_script(cache: &CacheDeclaration) -> String {
    format!(
        "set -euo pipefail\nshopt -s globstar nullglob\nfor root in {}; do rm -rf -- \"${{root}}\"; done",
        fixed_roots(cache)
    )
}

fn package_cache_script(cache: &CacheDeclaration, lane: &str, phase: &str) -> String {
    let destination = format!(".velnor-proof/{phase}/{lane}/{}", cache.id);
    format!(
        r#"set -euo pipefail
safe_link_target() {{
  local base="$1" target="$2" component; local -a stack=(workspace) parts
  IFS=/ read -ra parts <<<"${{base}}/${{target}}"
  for component in "${{parts[@]}}"; do
    case "${{component}}" in ''|.) ;; ..) (( ${{#stack[@]}} > 1 )) || return 1; unset 'stack[-1]' ;; *) stack+=("${{component}}") ;; esac
  done
}}
shopt -s globstar nullglob
destination='{destination}'
rm -rf -- "${{destination}}"
mkdir -p -- "${{destination}}"
: > "${{destination}}/files.nul"
for root in {roots}; do
  if [[ -e "${{root}}" || -L "${{root}}" ]]; then
    find "${{root}}" \( -type f -o -type l -o \( -type d -empty \) \) -print0
  fi
done | LC_ALL=C sort -zu > "${{destination}}/files.nul"
: > "${{destination}}/manifest.txt"
while IFS= read -r -d '' file; do
  [[ "${{file}}" != *$'\n'* && "${{file}}" != /* && "/${{file}}/" != */../* ]] || {{ echo 'unsafe cache path' >&2; exit 1; }}
  mode="$(stat -c '%a' -- "${{file}}" 2>/dev/null || stat -f '%Lp' -- "${{file}}")"
  encoded="$(printf '%s' "${{file}}" | openssl base64 -A)"
  if [[ -L "${{file}}" ]]; then
    kind=l; target="$(readlink -- "${{file}}")"
    [[ -n "${{target}}" && "${{target}}" != /* && "${{target}}" != *$'\n'* ]] || {{ echo 'unsafe cache symlink target' >&2; exit 1; }}
    safe_link_target "$(dirname -- "${{file}}")" "${{target}}" || {{ echo 'escaping cache symlink target' >&2; exit 1; }}
    digest="$(printf '%s' "${{target}}" | sha256sum | cut -d' ' -f1)"
    target_encoded="$(printf '%s' "${{target}}" | openssl base64 -A)"
  elif [[ -f "${{file}}" ]]; then
    kind=f; digest="$(sha256sum -- "${{file}}" | cut -d' ' -f1)"; target_encoded=-
  elif [[ -d "${{file}}" ]]; then
    kind=d; digest="$(printf '' | sha256sum | cut -d' ' -f1)"; target_encoded=-
  else
    echo 'unsupported cache entry type' >&2; exit 1
  fi
  printf '%s %s %s %s %s\n' "${{kind}}" "${{mode}}" "${{digest}}" "${{encoded}}" "${{target_encoded}}"
done < "${{destination}}/files.nul" | LC_ALL=C sort > "${{destination}}/manifest.txt"
tar --null --no-recursion --files-from="${{destination}}/files.nul" --sort=name --mtime='@0' --owner=0 --group=0 --numeric-owner -cf "${{destination}}/cache.tar"
sha256sum "${{destination}}/manifest.txt" | cut -d' ' -f1 > "${{destination}}/manifest.sha256"
sha256sum "${{destination}}/cache.tar" | cut -d' ' -f1 > "${{destination}}/archive.sha256"
restore_started="${{RESTORE_STARTED_MS-0}}"; restore_finished="${{RESTORE_FINISHED_MS-0}}"
for value in "${{restore_started}}" "${{restore_finished}}"; do [[ "${{value}}" =~ ^[0-9]+$ ]]; done
(( restore_finished >= restore_started ))
printf '%s\n' "$((restore_finished - restore_started))" > "${{destination}}/restore-ms"
[[ "${{CACHE_LOCK_WAIT_MS}}" =~ ^[0-9]+$ ]]
printf '%s\n' "${{CACHE_LOCK_WAIT_MS}}" > "${{destination}}/lock-wait-ms"
stat -c '%s' -- "${{destination}}/cache.tar" > "${{destination}}/cache-bytes"
wc -l < "${{destination}}/manifest.txt" | tr -d ' ' > "${{destination}}/cache-files"
if [[ "${{CACHE_HIT}}" == true ]]; then printf 'exact\n'; else printf 'miss\n'; fi > "${{destination}}/hit-source"
printf '%s\n' '-1' > "${{destination}}/age-seconds"
printf '%s\n' 'unknown' > "${{destination}}/eviction-risk"
printf '%s\n' "${{CACHE_HIT}}" > "${{destination}}/hit"
printf '%s\n' '{id}' > "${{destination}}/cache-id"
printf '%s\n' '{lane}' > "${{destination}}/lane""#,
        destination = destination,
        roots = fixed_roots(cache),
        id = cache.id,
        lane = lane,
    )
}

fn cache_action_with(
    b: &mut Builder,
    class: RepositoryClass,
    cache: &CacheDeclaration,
    include_restore_prefix: bool,
) {
    // A/B cohorts give only the selected target a fresh generation. Every
    // non-target cache inherits the stable production namespace so its warm
    // state can be proven without pre-populating the fresh target identity.
    let namespace = format!(
        "${{{{ inputs.benchmark_campaign != '' && inputs.benchmark_cache_mode != 'normal' && inputs.benchmark_cache_id != '{}' && 'ci-v1' || needs.validate-request.outputs.cache_namespace }}}}",
        cache.id
    );
    b.line(8, "with:");
    b.line(10, "path: |");
    for path in &cache.paths {
        b.line(12, path);
    }
    let globs = cache
        .lock_globs
        .iter()
        .map(|glob| format!("'{glob}'"))
        .collect::<Vec<_>>()
        .join(", ");
    let phase = hex::encode(Sha256::digest(cache.phase.as_bytes()));
    b.line(
        10,
        &format!(
            "key: {namespace}/{}/{}/${{{{ runner.os }}}}-${{{{ runner.arch }}}}/${{{{ hashFiles('mise.lock', 'mise.toml', 'rust-toolchain.toml') }}}}/${{{{ hashFiles({globs}) }}}}/{phase}",
            class.code(), cache.id
        ),
    );
    if include_restore_prefix && cache.compatible_phase_prefix {
        b.line(10, "restore-keys: |");
        b.line(
            12,
            &format!(
                "{namespace}/{}/{}/${{{{ runner.os }}}}-${{{{ runner.arch }}}}/${{{{ hashFiles('mise.lock', 'mise.toml', 'rust-toolchain.toml') }}}}/${{{{ hashFiles({globs}) }}}}/",
                class.code(), cache.id
            ),
        );
    }
}

pub fn barrier_script(declarations: &[&CacheDeclaration]) -> String {
    let mut script = format!(
        "set -euo pipefail\n{EVIDENCE_VERIFIER}\n{CACHE_TEMPERATURE_FUNCTION}\nselected=0\npublish_needed=false\n"
    );
    for cache in declarations {
        let env = cache.id.replace('-', "_").to_ascii_uppercase();
        script.push_str(&format!("{env}_publish=false\n"));
    }
    for cache in declarations {
        let id = cache.id.as_str();
        let env = id.replace('-', "_").to_ascii_uppercase();
        script.push_str(&format!(
            "if [[ -n \"${{CACHE_PROOF_ID}}\" || -n \"${{BENCHMARK_MODE}}\" ]]; then\n  selected=$((selected + 1))\n  for identity in \"${{{env}_github_ARTIFACT_ID}}\" \"${{{env}_velnor_ARTIFACT_ID}}\"; do [[ \"${{identity}}\" =~ ^[1-9][0-9]*$ ]]; done\n  for digest in \"${{{env}_github_ARTIFACT_DIGEST}}\" \"${{{env}_velnor_ARTIFACT_DIGEST}}\"; do [[ \"${{digest}}\" =~ ^sha256:[0-9a-f]{{64}}$ ]]; done\n  [[ \"${{{env}_github_ARTIFACT_ID}}\" != \"${{{env}_velnor_ARTIFACT_ID}}\" ]]\n  github='.velnor-proof/barrier/github/{id}'\n  velnor='.velnor-proof/barrier/velnor/{id}'\n  verify_evidence \"${{github}}\" github '{id}'\n  verify_evidence \"${{velnor}}\" velnor '{id}'\n  test \"$(cat \"${{github}}/archive.sha256\")\" = \"$(cat \"${{velnor}}/archive.sha256\")\"\n  test \"$(cat \"${{github}}/manifest.sha256\")\" = \"$(cat \"${{velnor}}/manifest.sha256\")\"\n  github_hit=\"$(cat \"${{github}}/hit\")\"\n  velnor_hit=\"$(cat \"${{velnor}}/hit\")\"\n  if [[ -n \"${{CACHE_PROOF_ID}}\" ]]; then\n    verify_cache_temperature \"${{CACHE_TEMPERATURE}}\" \"${{github_hit}}\" \"${{velnor_hit}}\"\n    [[ \"${{CACHE_TEMPERATURE}}\" == cold ]] && {env}_publish=true\n  else\n    role=non-target; [[ \"${{BENCHMARK_MODE}}\" == normal || \"${{BENCHMARK_CACHE_ID}}\" == '{id}' ]] && role=target\n    state=\"$(benchmark_cache_state \"${{BENCHMARK_MODE}}\" \"${{role}}\" \"${{github_hit}}\" \"${{velnor_hit}}\")\"\n    [[ \"${{state}}\" == miss ]] && {env}_publish=true\n  fi\nfi\n"
        ));
    }
    script.push_str(
        "[[ ${selected} -gt 0 ]] || { echo 'zero applicable cache proof work' >&2; exit 1; }\n",
    );
    for cache in declarations {
        let output = cache.id.replace('-', "_");
        let env = output.to_ascii_uppercase();
        script.push_str(&format!(
            "[[ \"${{{env}_publish}}\" == true ]] && publish_needed=true\n"
        ));
    }
    script.push_str("{\n  printf 'publish_needed=%s\\n' \"${publish_needed}\"\n");
    for cache in declarations {
        let output = cache.id.replace('-', "_");
        let env = output.to_ascii_uppercase();
        script.push_str(&format!(
            "  printf 'publish_{output}=%s\\n' \"${{{env}_publish}}\"\n"
        ));
    }
    script.push_str("} >> \"${GITHUB_OUTPUT}\"\n");
    script
}

pub const CACHE_TEMPERATURE_FUNCTION: &str = r#"verify_cache_temperature() {
  local temperature="$1" github_hit="$2" velnor_hit="$3"
  case "${temperature}" in
    cold) [[ "${github_hit}" != true && "${velnor_hit}" != true ]] ;;
    warm) [[ "${github_hit}" == true && "${velnor_hit}" == true ]] ;;
    *) return 1 ;;
  esac
}
benchmark_cache_state() {
  local mode="$1" role="$2" github_hit="$3" velnor_hit="$4"
  [[ "${mode}" =~ ^(normal|enabled|disabled)$ && "${role}" =~ ^(target|non-target)$ ]]
  [[ "${github_hit}" == "${velnor_hit}" ]]
  if [[ "${mode}" == normal || ( "${mode}" == enabled && "${role}" == target ) ]]; then
    if [[ "${github_hit}" == true ]]; then printf 'hit\n'; else printf 'miss\n'; fi
  elif [[ "${mode}" == disabled && "${role}" == target ]]; then
    [[ "${github_hit}" != true ]]; printf 'ignored\n'
  else
    [[ "${github_hit}" == true ]]; printf 'ignored\n'
  fi
}"#;

/// Fail-closed verifier shared by every cache-evidence boundary.
pub const EVIDENCE_VERIFIER: &str = r#"safe_link_target() {
  local base="$1" target="$2" component; local -a stack=(workspace) parts
  IFS=/ read -ra parts <<<"${base}/${target}"
  for component in "${parts[@]}"; do
    case "${component}" in ''|.) ;; ..) (( ${#stack[@]} > 1 )) || return 1; unset 'stack[-1]' ;; *) stack+=("${component}") ;; esac
  done
}
verify_evidence() {
  local root="$1" expected_lane="$2" expected_id="$3" required
  for required in cache.tar archive.sha256 manifest.txt manifest.sha256 hit cache-id lane restore-ms lock-wait-ms cache-bytes cache-files hit-source age-seconds eviction-risk; do
    [[ -f "${root}/${required}" && ! -L "${root}/${required}" ]] || return 1
  done
  [[ "$(cat "${root}/cache-id")" == "${expected_id}" ]]
  [[ "$(cat "${root}/lane")" == "${expected_lane}" ]]
  [[ "$(cat "${root}/restore-ms")" =~ ^[0-9]+$ ]]
  [[ "$(cat "${root}/lock-wait-ms")" =~ ^[0-9]+$ ]]
  [[ "$(cat "${root}/cache-bytes")" =~ ^[0-9]+$ ]]
  [[ "$(cat "${root}/cache-files")" =~ ^[0-9]+$ ]]
  [[ "$(cat "${root}/hit-source")" =~ ^(exact|miss)$ ]]
  [[ "$(cat "${root}/age-seconds")" =~ ^-?[0-9]+$ ]]
  [[ "$(cat "${root}/eviction-risk")" =~ ^(low|medium|high|unknown)$ ]]
  [[ "$(sha256sum "${root}/cache.tar" | cut -d' ' -f1)" == "$(cat "${root}/archive.sha256")" ]]
  [[ "$(sha256sum "${root}/manifest.txt" | cut -d' ' -f1)" == "$(cat "${root}/manifest.sha256")" ]]
  local scratch="${root}.verified" kind mode digest encoded target_encoded extra path target actual_mode
  rm -rf -- "${scratch}"
  mkdir -p -- "${scratch}/tree"
  : > "${scratch}/expected"
  while read -r kind mode digest encoded target_encoded extra; do
    [[ -z "${extra}" && "${kind}" =~ ^(f|l|d)$ && "${mode}" =~ ^[0-7]{3,4}$ && "${digest}" =~ ^[0-9a-f]{64}$ && -n "${encoded}" ]]
    path="$(printf '%s' "${encoded}" | openssl base64 -d -A)"
    [[ "$(printf '%s' "${path}" | openssl base64 -A)" == "${encoded}" ]]
    [[ -n "${path}" && "${path}" != /* && "${path}" != *$'\n'* && "/${path}/" != */../* ]]
    if [[ "${kind}" == l ]]; then
      target="$(printf '%s' "${target_encoded}" | openssl base64 -d -A)"
      [[ -n "${target}" && "${target}" != /* && "${target}" != *$'\n'* && "$(printf '%s' "${target}" | openssl base64 -A)" == "${target_encoded}" ]]
      safe_link_target "$(dirname -- "${path}")" "${target}"
      [[ "$(printf '%s' "${target}" | sha256sum | cut -d' ' -f1)" == "${digest}" ]]
    else
      [[ "${target_encoded}" == - ]]
    fi
    printf '%s\n' "${path}" >> "${scratch}/expected"
  done < "${root}/manifest.txt"
  LC_ALL=C sort -u -o "${scratch}/expected" "${scratch}/expected"
  [[ "$(wc -l < "${root}/manifest.txt" | tr -d ' ')" == "$(wc -l < "${scratch}/expected" | tr -d ' ')" ]]
  tar -tf "${root}/cache.tar" | sed 's:/$::' | LC_ALL=C sort -u > "${scratch}/actual"
  diff -u "${scratch}/expected" "${scratch}/actual"
  tar -xf "${root}/cache.tar" -C "${scratch}/tree"
  while read -r kind mode digest encoded target_encoded extra; do
    path="$(printf '%s' "${encoded}" | openssl base64 -d -A)"
    actual_mode="$(stat -c '%a' -- "${scratch}/tree/${path}" 2>/dev/null || stat -f '%Lp' -- "${scratch}/tree/${path}")"
    [[ "${actual_mode}" == "${mode}" ]]
    if [[ "${kind}" == f ]]; then
      [[ -f "${scratch}/tree/${path}" && ! -L "${scratch}/tree/${path}" && "$(sha256sum -- "${scratch}/tree/${path}" | cut -d' ' -f1)" == "${digest}" ]]
    elif [[ "${kind}" == l ]]; then
      target="$(printf '%s' "${target_encoded}" | openssl base64 -d -A)"
      [[ -L "${scratch}/tree/${path}" && "$(readlink -- "${scratch}/tree/${path}")" == "${target}" ]]
    else
      [[ -d "${scratch}/tree/${path}" && -z "$(find "${scratch}/tree/${path}" -mindepth 1 -maxdepth 1 -print -quit)" ]]
    fi
  done < "${root}/manifest.txt"
  rm -rf -- "${scratch}"
}"#;

