fn cache_step(
    b: &mut Builder,
    class: RepositoryClass,
    cache: &CacheDeclaration,
    mode: &str,
    condition: Option<&str>,
) {
    b.line(
        6,
        &format!(
            "- name: {} {} cache",
            if mode == "restore" {
                "Restore-only"
            } else if mode == "save" {
                "Publish isolated unmerged"
            } else {
                "Restore and publish"
            },
            cache.id
        ),
    );
    if let Some(condition) = condition {
        b.line(8, &format!("if: {condition}"));
    }
    let path = if mode == "restore" || mode == "save" {
        format!("/{mode}")
    } else {
        String::new()
    };
    b.line(
        8,
        &format!("uses: actions/cache{path}@{CACHE_ACTION_REF} # {CACHE_ACTION_VERSION}"),
    );
    b.line(8, "with:");
    b.line(10, "path: |");
    for path in &cache.paths {
        b.line(12, path);
    }
    let id = cache.id.as_str();
    if mode == "save" {
        b.line(10, &format!("key: ci-v1/{}/{id}/${{{{ runner.os }}}}-${{{{ runner.arch }}}}/${{{{ steps.cache-keys.outputs['{id}-current-toolchain'] }}}}/${{{{ steps.cache-keys.outputs['{id}-current-lock'] }}}}/${{{{ steps.cache-keys.outputs['{id}-phase'] }}}}", class.code()));
    } else {
        b.line(10, &format!("key: ci-v1/{}/{id}/${{{{ runner.os }}}}-${{{{ runner.arch }}}}/${{{{ steps.cache-keys.outputs['{id}-toolchain'] }}}}/${{{{ steps.cache-keys.outputs['{id}-lock'] }}}}/${{{{ steps.cache-keys.outputs['{id}-phase'] }}}}", class.code()));
    }
    if mode == "full" && cache.compatible_phase_prefix {
        b.line(10, "restore-keys: |");
        b.line(
            12,
            &format!(
                "ci-v1/{}/{id}/${{{{ runner.os }}}}-${{{{ runner.arch }}}}/${{{{ steps.cache-keys.outputs['{id}-toolchain'] }}}}/${{{{ steps.cache-keys.outputs['{id}-lock'] }}}}/",
                class.code()
            ),
        );
    }
}

