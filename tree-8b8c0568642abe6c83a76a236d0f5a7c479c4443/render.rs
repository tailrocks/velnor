//! Deterministic workflow rendering.
//!
//! Every rendered file is byte-stable: Unix (LF) line endings, UTF-8, a single
//! final newline, no trailing whitespace, and content that depends only on
//! declared data — never on timestamps, host paths, repository slug, or
//! environment. The two consumer-facing release tokens (`@FLEET_SHA@` and
//! `@CALVER@`) are the only non-executable placeholders; `render_consumer`
//! replaces them atomically.

use crate::RepositoryClass;
use crate::model::{ClassContract, Gate, Lane, OWNERS};

/// The canonical fleet owner. Callable workflows pin their internal composite
/// closure to this owner at the immutable block SHA; mirrors carry the identical
/// bytes.
pub const CANONICAL_OWNER: &str = "tailrocks";
/// The fleet repository name shared across all three owner-local mirrors.
pub const ACTIONS_REPO: &str = "velnor-actions";

/// The `@FLEET_SHA@` release-pin placeholder (the consumer's immutable ref).
pub const FLEET_SHA_PLACEHOLDER: &str = "@FLEET_SHA@";
/// The `@CALVER@` release-version-comment placeholder.
pub const CALVER_PLACEHOLDER: &str = "@CALVER@";

/// Pinned checkout action (full 40-hex SHA) and its version comment.
const CHECKOUT_REF: &str = "3d3c42e5aac5ba805825da76410c181273ba90b1";
const CHECKOUT_VERSION: &str = "v7.0.1";
/// Pinned mise setup action (full 40-hex SHA) and its version comment.
const MISE_ACTION_REF: &str = "dad1bfd3df957f44999b559dd69dc1671cb4e9ea";
const MISE_ACTION_VERSION: &str = "v4.2.1";

/// The generated workflow file name for a class: `ci-<class>.yml`.
#[must_use]
pub fn callable_file_name(class: RepositoryClass) -> String {
    format!("ci-{}.yml", class.code())
}

struct Builder {
    lines: Vec<String>,
}

impl Builder {
    fn new() -> Builder {
        Builder { lines: Vec::new() }
    }

    fn line(&mut self, indent: usize, text: &str) {
        if text.is_empty() {
            self.lines.push(String::new());
        } else {
            self.lines.push(format!("{}{}", " ".repeat(indent), text));
        }
    }

    fn blank(&mut self) {
        self.lines.push(String::new());
    }

    /// Emit a `run: |` block: the key at `indent`, script body at `indent + 2`.
    fn run_block(&mut self, indent: usize, script: &str) {
        self.line(indent, "run: |");
        for l in script.lines() {
            if l.is_empty() {
                self.lines.push(String::new());
            } else {
                self.lines.push(format!("{}{}", " ".repeat(indent + 2), l));
            }
        }
    }

    fn finish(self) -> String {
        let mut out = self.lines.join("\n");
        out.push('\n');
        out
    }
}

/// Render the committed consumer template for a class. The three owner-local
/// reusable-workflow calls share the same anchored `@FLEET_SHA@ # @CALVER@`
/// release pin; `render_consumer` replaces both tokens together at release time.
#[must_use]
pub fn consumer_template(class: RepositoryClass) -> String {
    let file = callable_file_name(class);
    let mut b = Builder::new();
    b.line(0, "# Generated by velnor-actions-generator. DO NOT EDIT.");
    b.line(0, "#");
    b.line(
        0,
        &format!(
            "# Canonical consumer template for the {} class. Every {} repository renders",
            class.code(),
            class.code()
        ),
    );
    b.line(
        0,
        "# this same file (byte-identical within the class) as .github/workflows/ci.yml.",
    );
    b.line(
        0,
        "# The three owner-local reusable-workflow calls are selected solely by",
    );
    b.line(
        0,
        "# github.repository_owner: exactly one runs and the other two skip. The shared",
    );
    b.line(
        0,
        "# release SHA pin and CalVer version comment are identical across all three",
    );
    b.line(
        0,
        "# calls and are replaced together at release time by render-consumer.",
    );
    b.line(0, "name: CI");
    b.blank();
    b.line(0, "on:");
    b.line(2, "pull_request:");
    b.line(2, "push:");
    b.line(2, "merge_group:");
    b.line(2, "workflow_dispatch:");
    b.line(4, "inputs:");
    b.line(6, "lane:");
    b.line(
        8,
        "description: \"CI lane: velnor (default), github, or both.\"",
    );
    b.line(8, "type: choice");
    b.line(8, "default: velnor");
    b.line(8, "options:");
    b.line(10, "- velnor");
    b.line(10, "- github");
    b.line(10, "- both");
    b.blank();
    b.line(0, "permissions:");
    b.line(2, "contents: read");
    b.blank();
    b.line(0, "concurrency:");
    b.line(2, "group: ${{ github.workflow }}-${{ github.ref }}");
    b.line(2, "cancel-in-progress: true");
    b.blank();
    b.line(0, "jobs:");

    for owner in OWNERS {
        b.line(2, &format!("{owner}:"));
        b.line(4, &format!("name: {owner}"));
        b.line(
            4,
            &format!("if: ${{{{ github.repository_owner == '{owner}' }}}}"),
        );
        b.line(4, "permissions:");
        b.line(6, "contents: read");
        b.line(
            4,
            &format!(
                "uses: {owner}/{ACTIONS_REPO}/.github/workflows/{file}@{FLEET_SHA_PLACEHOLDER} # {CALVER_PLACEHOLDER}"
            ),
        );
        b.line(4, "with:");
        b.line(
            6,
            "lane: ${{ (github.event_name == 'workflow_dispatch' && inputs.lane) || 'velnor' }}",
        );
        b.blank();
    }

    // ci-required aggregator: fail-closed positive truth table.
    b.line(2, "ci-required:");
    b.line(4, "name: ci-required");
    b.line(4, "needs:");
    for owner in OWNERS {
        b.line(6, &format!("- {owner}"));
    }
    b.line(4, "if: ${{ always() }}");
    b.line(4, "runs-on: ubuntu-latest");
    b.line(4, "timeout-minutes: 10");
    b.line(4, "permissions:");
    b.line(6, "contents: read");
    b.line(4, "steps:");
    b.line(6, "- name: Enforce fleet contract");
    b.line(8, "env:");
    b.line(10, "OWNER: ${{ github.repository_owner }}");
    b.line(
        10,
        "JACKIN_PROJECT_RESULT: ${{ needs.jackin-project.result }}",
    );
    b.line(
        10,
        "JACKIN_PROJECT_CONTRACT: ${{ needs.jackin-project.outputs.contract }}",
    );
    b.line(10, "TAILROCKS_RESULT: ${{ needs.tailrocks.result }}");
    b.line(
        10,
        "TAILROCKS_CONTRACT: ${{ needs.tailrocks.outputs.contract }}",
    );
    b.line(10, "CHAINARGOS_RESULT: ${{ needs.ChainArgos.result }}");
    b.line(
        10,
        "CHAINARGOS_CONTRACT: ${{ needs.ChainArgos.outputs.contract }}",
    );
    b.line(8, "shell: bash");
    b.run_block(8, CI_REQUIRED_SCRIPT);

    b.finish()
}

/// Render the owner-local callable workflow for a class, pinning its internal
/// composite closure to `block_sha` (a validated 40-hex SHA).
#[must_use]
pub fn callable_workflow(contract: &ClassContract, block_sha: &str) -> String {
    let class = contract.class;
    let run_gate = format!("{CANONICAL_OWNER}/{ACTIONS_REPO}/actions/run-gate@{block_sha}");
    let aggregate = format!("{CANONICAL_OWNER}/{ACTIONS_REPO}/actions/aggregate@{block_sha}");

    let mut b = Builder::new();
    b.line(0, "# Generated by velnor-actions-generator. DO NOT EDIT.");
    b.line(0, "#");
    b.line(
        0,
        &format!(
            "# Owner-local reusable CI workflow for the {} class. Consumers call their own",
            class.code()
        ),
    );
    b.line(
        0,
        "# organization's mirror of this file. It owns the lane jobs, runs identical gate",
    );
    b.line(
        0,
        "# commands on either lane through the run-gate building block, and emits the lane",
    );
    b.line(
        0,
        "# contract only after every applicable gate genuinely succeeds. It inherits no",
    );
    b.line(
        0,
        "# secrets and no environment. The internal composite closure is pinned to the",
    );
    b.line(0, "# immutable block SHA recorded in fleet/block-sha.");
    b.line(0, &format!("name: ci-{}", class.code()));
    b.blank();
    b.line(0, "on:");
    b.line(2, "workflow_call:");
    b.line(4, "inputs:");
    b.line(6, "lane:");
    b.line(
        8,
        "description: \"CI lane: velnor (default), github, or both.\"",
    );
    b.line(8, "required: false");
    b.line(8, "type: string");
    b.line(8, "default: velnor");
    b.line(4, "outputs:");
    b.line(6, "contract:");
    b.line(
        8,
        "description: \"'success' only when every selected lane passed its applicable gates.\"",
    );
    b.line(8, "value: ${{ jobs.contract.outputs.contract }}");
    b.blank();
    b.line(0, "permissions:");
    b.line(2, "contents: read");
    b.blank();
    b.line(0, "jobs:");

    // Velnor lane.
    b.line(2, "velnor-lane:");
    b.line(4, "name: velnor lane");
    b.line(
        4,
        "if: ${{ inputs.lane == 'velnor' || inputs.lane == 'both' }}",
    );
    b.line(
        4,
        "# Public unmerged-code events (pull_request, merge_group) route the Velnor lane",
    );
    b.line(
        4,
        "# to GitHub-hosted execution until a live-proven lower-trust Velnor pool exists.",
    );
    b.line(4, "# This is explicit policy routing, not silent failover.");
    b.line(
        4,
        "runs-on: ${{ (github.event_name == 'pull_request' || github.event_name == 'merge_group') && 'ubuntu-latest' || 'velnor-trusted' }}",
    );
    b.line(4, "timeout-minutes: 30");
    b.line(4, "outputs:");
    b.line(6, "contract: ${{ steps.aggregate.outputs.contract }}");
    b.line(4, "steps:");
    b.line(6, "- name: Report Velnor lane routing policy");
    b.line(
        8,
        "if: ${{ github.event_name == 'pull_request' || github.event_name == 'merge_group' }}",
    );
    b.line(8, "shell: bash");
    b.run_block(
        8,
        "echo 'policy: public unmerged-code routes the Velnor lane to GitHub-hosted execution'",
    );
    lane_steps(&mut b, contract, Lane::Velnor, &run_gate, &aggregate);
    b.blank();

    // GitHub-hosted lane.
    b.line(2, "github-lane:");
    b.line(4, "name: github lane");
    b.line(
        4,
        "if: ${{ inputs.lane == 'github' || inputs.lane == 'both' }}",
    );
    b.line(4, "runs-on: ubuntu-latest");
    b.line(4, "timeout-minutes: 30");
    b.line(4, "outputs:");
    b.line(6, "contract: ${{ steps.aggregate.outputs.contract }}");
    b.line(4, "steps:");
    lane_steps(&mut b, contract, Lane::GitHub, &run_gate, &aggregate);
    b.blank();

    // Lane-verdict aggregator: fail-closed positive per-lane truth table.
    b.line(2, "contract:");
    b.line(4, "name: contract");
    b.line(4, "needs:");
    b.line(6, "- velnor-lane");
    b.line(6, "- github-lane");
    b.line(4, "if: ${{ always() }}");
    b.line(4, "runs-on: ubuntu-latest");
    b.line(4, "timeout-minutes: 10");
    b.line(4, "outputs:");
    b.line(6, "contract: ${{ steps.verdict.outputs.contract }}");
    b.line(4, "steps:");
    b.line(6, "- name: Aggregate lane verdict");
    b.line(8, "id: verdict");
    b.line(8, "env:");
    b.line(10, "LANE: ${{ inputs.lane }}");
    b.line(10, "VELNOR_RESULT: ${{ needs.velnor-lane.result }}");
    b.line(
        10,
        "VELNOR_CONTRACT: ${{ needs.velnor-lane.outputs.contract }}",
    );
    b.line(10, "GITHUB_RESULT: ${{ needs.github-lane.result }}");
    b.line(
        10,
        "GITHUB_CONTRACT: ${{ needs.github-lane.outputs.contract }}",
    );
    b.line(8, "shell: bash");
    b.run_block(8, CONTRACT_VERDICT_SCRIPT);

    b.finish()
}

fn lane_steps(
    b: &mut Builder,
    contract: &ClassContract,
    lane: Lane,
    run_gate: &str,
    aggregate: &str,
) {
    b.line(6, "- name: Check out repository");
    b.line(
        8,
        &format!("uses: actions/checkout@{CHECKOUT_REF} # {CHECKOUT_VERSION}"),
    );
    b.line(6, "- name: Set up mise toolchain");
    b.line(
        8,
        &format!("uses: jdx/mise-action@{MISE_ACTION_REF} # {MISE_ACTION_VERSION}"),
    );
    for gate in contract.applicable_gates(lane) {
        gate_step(b, gate, run_gate);
    }
    b.line(6, "- name: Emit lane contract");
    b.line(8, "id: aggregate");
    b.line(8, &format!("uses: {aggregate}"));
}

fn gate_step(b: &mut Builder, gate: &Gate, run_gate: &str) {
    b.line(6, &format!("- name: {} gate", gate.name));
    b.line(8, &format!("uses: {run_gate}"));
    b.line(8, "with:");
    b.line(10, &format!("name: {}", gate.name));
    b.line(10, &format!("command: {}", gate.command));
}

/// Materialize a consumer file from a committed template by atomically replacing
/// every `@FLEET_SHA@` with `release_sha` and every `@CALVER@` with `calver`.
///
/// Refuses output that still contains either placeholder or that leaves a mixed
/// pin (a `@FLEET_SHA@` without an accompanying replaced `@CALVER@` on the same
/// reference, or vice versa).
///
/// # Errors
///
/// Returns `Err` if the inputs are invalid or any placeholder survives.
pub fn render_consumer(template: &str, release_sha: &str, calver: &str) -> Result<String, String> {
    if !crate::model::is_sha40(release_sha) {
        return Err(format!(
            "release SHA {release_sha:?} is not 40 lowercase hex"
        ));
    }
    if calver.trim().is_empty() {
        return Err("CalVer must be non-empty".to_string());
    }
    if calver.contains('\n') || calver.contains('#') {
        return Err(format!("CalVer {calver:?} contains a forbidden character"));
    }
    let expected_refs = template.matches(FLEET_SHA_PLACEHOLDER).count();
    let out = template
        .replace(FLEET_SHA_PLACEHOLDER, release_sha)
        .replace(CALVER_PLACEHOLDER, calver);
    if out.contains(FLEET_SHA_PLACEHOLDER) || out.contains(CALVER_PLACEHOLDER) {
        return Err("materialized output still contains a placeholder".to_string());
    }
    // Every rendered reference must carry the same replaced SHA and CalVer: the
    // count of pinned refs must match the count of version comments.
    let sha_refs = out.matches(&format!("@{release_sha} # {calver}")).count();
    if sha_refs != expected_refs {
        return Err(format!(
            "mixed pin: expected {expected_refs} coherent @<sha> # <calver> references, found {sha_refs}"
        ));
    }
    Ok(out)
}

const CI_REQUIRED_SCRIPT: &str = r#"set -euo pipefail
# Positive truth table: accept ONLY a recognized owner whose selected call
# succeeded with an explicit contract=success output, and whose two other owner
# calls skipped with empty outputs. No "no failure found" logic; skipped-success
# is never acceptance.
case "${OWNER}" in
  jackin-project)
    sel_result="${JACKIN_PROJECT_RESULT}"; sel_contract="${JACKIN_PROJECT_CONTRACT}"
    a_result="${TAILROCKS_RESULT}"; a_contract="${TAILROCKS_CONTRACT}"
    b_result="${CHAINARGOS_RESULT}"; b_contract="${CHAINARGOS_CONTRACT}"
    ;;
  tailrocks)
    sel_result="${TAILROCKS_RESULT}"; sel_contract="${TAILROCKS_CONTRACT}"
    a_result="${JACKIN_PROJECT_RESULT}"; a_contract="${JACKIN_PROJECT_CONTRACT}"
    b_result="${CHAINARGOS_RESULT}"; b_contract="${CHAINARGOS_CONTRACT}"
    ;;
  ChainArgos)
    sel_result="${CHAINARGOS_RESULT}"; sel_contract="${CHAINARGOS_CONTRACT}"
    a_result="${JACKIN_PROJECT_RESULT}"; a_contract="${JACKIN_PROJECT_CONTRACT}"
    b_result="${TAILROCKS_RESULT}"; b_contract="${TAILROCKS_CONTRACT}"
    ;;
  *)
    echo "ci-required: unrecognized owner '${OWNER}'" >&2
    exit 1
    ;;
esac
if [ "${sel_result}" != "success" ]; then
  echo "ci-required: selected owner result is '${sel_result}', expected 'success'" >&2
  exit 1
fi
if [ "${sel_contract}" != "success" ]; then
  echo "ci-required: selected owner contract is '${sel_contract}', expected 'success'" >&2
  exit 1
fi
if [ "${a_result}" != "skipped" ] || [ "${b_result}" != "skipped" ]; then
  echo "ci-required: a non-selected owner ran (results '${a_result}', '${b_result}'), expected both 'skipped'" >&2
  exit 1
fi
if [ -n "${a_contract}" ] || [ -n "${b_contract}" ]; then
  echo "ci-required: a non-selected owner produced a contract output, expected empty" >&2
  exit 1
fi
echo "ci-required: fleet contract satisfied for owner '${OWNER}'""#;

const CONTRACT_VERDICT_SCRIPT: &str = r#"set -euo pipefail
# Positive per-lane truth table: emit contract=success ONLY when every selected
# lane succeeded with contract=success and every non-selected lane is skipped with
# an empty output. A failed, unavailable, or skipped selected lane is never
# credited, and one lane never substitutes for the other.
case "${LANE}" in
  velnor)
    if [ "${VELNOR_RESULT}" != "success" ] || [ "${VELNOR_CONTRACT}" != "success" ]; then
      echo "contract: velnor lane did not pass (result '${VELNOR_RESULT}', contract '${VELNOR_CONTRACT}')" >&2
      exit 1
    fi
    if [ "${GITHUB_RESULT}" != "skipped" ] || [ -n "${GITHUB_CONTRACT}" ]; then
      echo "contract: github lane must be skipped for lane=velnor (result '${GITHUB_RESULT}')" >&2
      exit 1
    fi
    ;;
  github)
    if [ "${GITHUB_RESULT}" != "success" ] || [ "${GITHUB_CONTRACT}" != "success" ]; then
      echo "contract: github lane did not pass (result '${GITHUB_RESULT}', contract '${GITHUB_CONTRACT}')" >&2
      exit 1
    fi
    if [ "${VELNOR_RESULT}" != "skipped" ] || [ -n "${VELNOR_CONTRACT}" ]; then
      echo "contract: velnor lane must be skipped for lane=github (result '${VELNOR_RESULT}')" >&2
      exit 1
    fi
    ;;
  both)
    if [ "${VELNOR_RESULT}" != "success" ] || [ "${VELNOR_CONTRACT}" != "success" ]; then
      echo "contract: velnor lane did not pass (result '${VELNOR_RESULT}', contract '${VELNOR_CONTRACT}')" >&2
      exit 1
    fi
    if [ "${GITHUB_RESULT}" != "success" ] || [ "${GITHUB_CONTRACT}" != "success" ]; then
      echo "contract: github lane did not pass (result '${GITHUB_RESULT}', contract '${GITHUB_CONTRACT}')" >&2
      exit 1
    fi
    ;;
  *)
    echo "contract: unrecognized lane '${LANE}'" >&2
    exit 1
    ;;
esac
echo "contract=success" >> "${GITHUB_OUTPUT}"
echo "contract: lane '${LANE}' passed""#;
