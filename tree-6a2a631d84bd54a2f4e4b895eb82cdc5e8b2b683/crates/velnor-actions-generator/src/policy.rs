/// Render the generator-owned task block for one repository class.
#[must_use]
pub fn fleet_tasks(metadata: &CensusMetadata, class: RepositoryClass) -> String {
    let activation = "test -f repolint.toml && grep -q '^\\[repo\\]$' repolint.toml".to_owned();
    let alint = FLEET_TOOL_WARNING_EXIT
        .replace("{activation}", &activation)
        .replace("{command}", "alint check --fail-on-warning")
        .replace("{tool}", "alint")
        .replace("{statuses}", "1|2");
    let zizmor = FLEET_TOOL_WARNING_EXIT
        .replace("{activation}", &activation)
        .replace("{command}", "zizmor .github/workflows")
        .replace("{tool}", "zizmor")
        .replace("{statuses}", "11|12|13|14");
    let census = format!(
        "printf 'repository class: {}\\ntier: {}\\nkind: {}\\nvisibility: {}\\nresearch: {}\\nfirst_seen: {}\\n'",
        class.code(),
        metadata.tier.token(),
        metadata.kind.token(),
        metadata.visibility.token(),
        metadata.research,
        metadata.first_seen
    );
    format!(
        r#"[tasks."fleet:check"]
description = "Run the fleet structure, repository-shape, and workflow security gates"
run = [
  "repolint check",
  {alint:?},
  {zizmor:?},
]

[tasks."fleet:map"]
description = "Regenerate the linter-owned README repository map"
run = "repolint map --write"

[tasks."fleet:census"]
description = "Print this repository's authoritative fleet census row"
run = {census:?}
"#,
        alint = alint,
        zizmor = zizmor,
    )
}

/// Render the generator-owned `[repo]` cache. Other repolint sections are
/// intentionally not represented here and therefore cannot be overwritten.
#[must_use]
pub fn repolint_repo_table(metadata: &CensusMetadata) -> String {
    format!(
        "[repo]\ntier = \"{}\"\nkind = \"{}\"\nvisibility = \"{}\"\nresearch = {}\n",
        metadata.tier.token().to_ascii_lowercase(),
        metadata.kind.token().to_ascii_lowercase(),
        metadata.visibility.token(),
        metadata.research
    )
}

/// Update only `[repo]` in an existing repolint config.
pub fn render_repolint(existing: &str, metadata: &CensusMetadata) -> String {
    let table = repolint_repo_table(metadata);
    let mut output = String::new();
    let mut in_repo = false;
    let mut replaced = false;
    for line in existing.lines() {
        let trimmed = line.trim();
        if trimmed == "[repo]" {
            if !replaced {
                output.push_str(&table);
                replaced = true;
            }
            in_repo = true;
            continue;
        }
        if in_repo && trimmed.starts_with('[') && trimmed.ends_with(']') {
            in_repo = false;
        }
        if !in_repo {
            output.push_str(line);
            output.push('\n');
        }
    }
    if !replaced {
        let mut prefix = table;
        prefix.push('\n');
        prefix.push_str(existing);
        return normalize_newline(&prefix);
    }
    normalize_newline(&output)
}

/// Render exact census output for the root `fleet:census` task.
#[must_use]
pub fn census_output(manifest: &crate::model::FleetManifest) -> String {
    let counts = manifest.census_counts();
    let format_counts = |values: &std::collections::BTreeMap<&'static str, usize>| {
        values
            .iter()
            .map(|(name, count)| format!("{name}={count}"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    format!(
        "census: total={} tiers=[{}] kinds=[{}] visibility=[{}] research={}",
        counts.total,
        format_counts(&counts.tiers),
        format_counts(&counts.kinds),
        format_counts(&counts.visibilities),
        counts.research
    )
}

/// Add or replace only the generator-owned `fleet:*` task tables.
pub fn render_mise_tasks(existing: &str, tasks: &str) -> String {
    let generated = FLEET_TASK_NAMES
        .iter()
        .map(|name| format!("[tasks.\"{name}\"]"))
        .collect::<std::collections::BTreeSet<_>>();
    let mut output = String::new();
    let mut skipping = false;
    for line in existing.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') && trimmed.ends_with(']') {
            skipping = generated.contains(trimmed);
        }
        if !skipping {
            output.push_str(line);
            output.push('\n');
        }
    }
    if !output.ends_with("\n\n") {
        output.push('\n');
    }
    output.push_str(tasks.trim_start());
    if !output.ends_with('\n') {
        output.push('\n');
    }
    output
}

fn normalize_newline(value: &str) -> String {
    let mut output = value.replace("\r\n", "\n").replace('\r', "\n");
    if !output.ends_with('\n') {
        output.push('\n');
    }
    output
}
